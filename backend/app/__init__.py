# 【本文件的作用】这是一个「包（package）的入口文件」。
# 在 Python 里，一个文件夹里只要有 __init__.py，这个文件夹就被当成一个「包」，
# 里面的 .py 文件才能用 `from app.xxx import yyy` 这种「相对导入」互相引用。
# 例如 main.py 里的 `from .config import get_settings`，那个 `.` 指的就是本包（app）。
#
# 【为什么它几乎没内容】因为它不需要做任何初始化动作（不建连接、不读配置），
# 只承担「标记这是一个包」的职责。真正的初始化都是「用到时才做」（惰性初始化），
# 这样模块导入更快，也避免「导入即连接数据库」导致的各种启动顺序问题。
#
# 【它下面会写什么注释吗】没有 —— 就下面两行。保持这个文件干净是刻意的。
#
# 【注意事项】不要往这里塞复杂的初始化逻辑（比如连数据库）。
# 因为任何 `import app.xxx` 都会先执行本文件，一旦这里报错，
# 整个后端所有模块都会导入失败，问题会非常难定位。

