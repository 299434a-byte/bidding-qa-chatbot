# ============================================================================
# 文件：bm25.py —— 给文字做「关键词检索」的引擎
#
# ============================================================================
# 【重要】这个文件建议「从下往上」读，因为它是一次问答的「逆过程」：
#
#   用户搜索时是「拿着词来找文档」；但这个文件从一开始是「给文档建索引」。
#   所以按执行时间先后，阅读顺序应该是：
#     ① tokenize()       —— 把中文句子切成一个个词（分词）
#     ② BM25Index.fit()  —— 把所有文档的词汇总，统计出「词表」和「每个词在几篇文档里出现过」
#     ③ BM25Index.save() —— 把上一步的统计结果存成 JSON 文件（否则重启服务就白算了）
#     ④ BM25Index.load() —— 服务启动/检索时把统计结果读回内存
#     ⑤ encode_document()—— 建库时：把每篇文档变成一串「稀疏向量」存进向量库
#     ⑥ encode_query()   —— 检索时：把用户问题也变成一串「稀疏向量」
#     ⑦ 两边向量做点积    —— 得分即标准 BM25 分数（这一步在向量库 Qdrant 里做，不在本文件）
#
# ============================================================================
# 【这个文件在整个项目里是干什么的】
#   它是「两路召回」里的其中一路。整个检索用两种方式找答案：
#     - 一路是「语义检索」（向量）：理解意思，能答「意思相近」的问题；
#     - 另一路是「关键词检索」（就是本文件，BM25）：看字面重合，擅长精确的词，如公司名、编号。
#   两路结果最后会被融合（RRF），再交给大模型作答。
#
# 【谁调用它（上游）】
#   backend/app/ingest.py —— 建库时：分词、fit() 统计、encode_document() 编码、save() 存盘。
#   backend/app/retriever.py —— 检索时：load() 载入统计、encode_query() 编码用户问题。
#
# 【它给谁用（下游）】
#   backend/app/vector_store.py —— 把编码出的「下标 + 权重」两串数字存进 Qdrant
#   的 sparse vector（稀疏向量）字段。
#
# 【特别说明：为什么这个文件被反复改造过、要小心读】
#   本文件经历过多次修修补补，所以会看到一些「不像新手会写」的细节，例如：
#   ready 属性、avg_doc_length or 1.0、denominator <= 0 判断、load 失败返回空索引……
#   这些都是为了「空知识库 / 配置文件损坏 / 数据缺失」时程序还能活着，
#   下方注释里都会逐条说明。
# ============================================================================

