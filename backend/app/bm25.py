#   jieba 用统计方法帮我们切词，切得准不准直接决定关键词检索的效果。
# 【注意事项】jieba 首次使用时需要加载词典，会有几百毫秒的启动耗时，
#   之后它就常驻内存了，不影响后续速度。
import jieba

# 【这行在干什么】预先编译一条正则规则，放进变量 _TOKEN_KEEP。
# 【通俗翻译】这条规则的意思是：「整个字符串从开头到结尾，全部由 \w 或中文字组成」。
#   满足就保留这个「词元」（token），不满足（例如里面夹着逗号、括号）就丢掉。
# 【参数逐个解释】
#   ^        —— 表示「字符串开头」；
#   [ ... ]  —— 方括号表示「字符集合」，即「下面列出的这些字符里的任意一个」；
#   \w       —— 表示「单词字符」，也就是字母、数字、下划线（Python 3 里它其实已经
#               能匹配中文了，所以下面再写一遍汉字范围属于「双保险」，不写也对）；
#   \u4e00-\u9fff —— 汉字的 Unicode 编码范围（从「一」到「龥」），把所有汉字都涵盖进来；
#   +        —— 表示「前面的内容出现 1 次或多次」，也就是「至少要有一个字」；
#   $        —— 表示「字符串结尾」。
# 【为什么这么写】分词结果里会混进「，」「（」「%」这类纯标点，它们对检索毫无价值，
#   留在索引里只会让词表变大、检索变慢，所以顺手过滤掉。
# 【注意事项】这是「全匹配」规则（有 ^ 和 $），所以像「abc,def」这种内部带逗号的词
#   也会被整条丢掉，这正是我们要的效果。
# 仅保留中文、字母、数字、下划线组成的词元，过滤纯标点
_TOKEN_KEEP = re.compile(r"^[\w\u4e00-\u9fff]+$")


# 【这行在干什么】定义一个函数 tokenize：把一段文字切成一个个「词」组成的列表。
# 【为什么需要】BM25 是「按词比对」的算法，输入必须是词，而不是整段句子。
# 【通俗解释：分词】像把人名「欧阳修」拆成「欧阳 + 修」还是「欧阳修」——
#   切法不同，检索效果差别很大。jieba 负责给出合理的切法。
# 【参数含义】text=待切分的原文（比如用户的问题或文档正文）。
# 【返回值】一个列表，里面是一个个归一化后的词，例如「市政道路」可能切成 ["市政", "道路"]。
def tokenize(text: str) -> list[str]:
    """中文分词 + 归一化。"""
    # 【这行在干什么】如果传进来的是空字符串（或 None 之类的假值），直接返回空列表。
    # 【为什么这么写】空文本没有词可切，提前返回可以省掉后面所有计算；
    #   同时保证函数在任何输入下都返回「列表」这种统一类型，调用方不用做额外判断。
    #   这叫「防御性编程」：把边界情况在入口就处理掉。
    if not text:
        return []
    # 【这行在干什么】准备一个空列表，用来装切好的词。
    # 【类型标注解释】tokens: list[str] 表示「这是一个装字符串的列表」；
    #   标注只给人看和给编辑器看，不影响运行。
    tokens: list[str] = []
    # 【这行在干什么】调用 jieba 把 text 切成一个个片段，逐个处理。
    # 【参数解释】jieba.cut(text, cut_all=False)：
    #   - text 是要切的原文；
    #   - cut_all=False 表示使用「精确模式」，也就是尽量切出唯一合理的一种结果。
    #     如果设成 True，就是「全模式」，会把所有可能的词都切出来（例如「南京市长江大桥」
    #     会切出一大堆重复组合），结果是噪声变多、索引变大，所以这里必须用 False。
    # 【注意事项】jieba.cut 返回的是「迭代器」（一个一个吐，而不是一次性全给），
    #   所以可以直接放在 for 里循环，不需要先转成列表。
    for piece in jieba.cut(text, cut_all=False):
        # 【这行在干什么】把切出来的这一小段两头空白去掉，并统一转成小写。
        # 【为什么这么写】①去掉分词残留的空格与换行，避免「空格」被当成一个词；
        #   ②统一小写是为了让「Python」「python」「PYTHON」被当成同一个词，
        #   否则用户大小写不同就搜不到彼此。
        # 【注意事项】中文没有大小写，lower() 对中文无影响，只对英文/拼音有效。
        token = piece.strip().lower()
        # 【这行在干什么】只有当这个词「非空」且「完全符合上面那条白名单规则」时才收下。
        # 【参数解释】token 非空判断避免空串进入词表；
        #   _TOKEN_KEEP.match(token) 返回匹配对象（算真）或 None（算假），
        #   所以它能直接当条件用。match 是从字符串开头尝试匹配。
        if token and _TOKEN_KEEP.match(token):
            # 【这行在干什么】把合格的词加进结果列表。
            # 【为什么用 append】往列表尾部追加，是最省事的收集方式。
            tokens.append(token)
    # 【这行在干什么】返回切好、洗干净的词列表。
    # 【为什么返回列表而不是生成器】后面 fit() 需要反复遍历这些词（先算总长度、
    #   再按 set 去重统计），列表可以反复读，生成器只能读一遍。这是刻意的选择。
    return tokens


# 【这行在干什么】定义 BM25Index 类：它既是「统计数据的仓库」，又是「稀疏向量编码器」。
# 【为什么把两者放一起】因为编码时必须用到统计结果（词表、文档频率、平均长度），
#   放在一个对象里就不用满世界传参数了。
# 【本类的数据生命周期】先 fit() 统计 → save() 存盘 → 下次 load() 读回 → 之后一直用它编码。
class BM25Index:
    """可持久化的 BM25 统计量与稀疏向量编码器。"""

    # 【这行在干什么】定义构造函数，创建 BM25Index 实例并设定两个算法参数。
    # 【参数逐个解释】
    #   k1 = 1.5 —— 控制「词频的饱和程度」。一个词在一篇文档里出现 1 次还是 10 次，
    #     得分不应该差 10 倍，出现多了要「收益递减」。k1 越小饱和越快（出现两三次就到头），
    #     k1 越大越看重出现次数。1.2~2.0 是工业界常用区间，1.5 是经典默认值。
    #   b = 0.75 —— 控制「文档长度归一化」的强度。长文档天然更容易撞上各种词，
    #     不惩罚就会「长的文档总是占便宜」。b=0 完全不归一化，b=1 完全归一化，
    #     0.75 是经典默认值。
    # 【注意事项】这两个参数会被一起存进 JSON；load() 时如果文件里有记录就覆盖默认值，
    #   从而保证「建库时用的参数」和「检索时用的参数」一致——不一致会导致打分口径错乱。
    # 【为什么标注 -> None】表示这个函数不返回任何东西（它只负责初始化对象）。
    def __init__(self, k1: float = 1.5, b: float = 0.75) -> None:
        # 【这行在干什么】把参数 k1 存到对象自己身上（self 表示「我自己」）。
        # 【为什么需要 self.】不加 self. 就只是局部变量，函数一结束就没了；
        #   加上之后它变成「实例属性」，后面所有方法都能随时取用。
        self.k1 = k1
        # 【这行在干什么】同上，把 b 存成实例属性。
        # 【为什么需要】打分公式里要用到它，必须能跨方法访问。
        self.b = b
        # 【这行在干什么】建立「词 → 编号」的对照表，初始为空。
        # 【为什么需要编号】稀疏向量在向量库里是用「下标 + 权重」两串数字表示的：
        #   下标必须是从 0 开始的整数，不能直接用中文词。所以要把每个词分配一个固定编号。
        # 【专业词解释：dict[str, int]】表示「键是字符串（词），值是整数（编号）」的字典。
        #   举例：{"市政": 0, "道路": 1, "工程": 2}
        # 【最容易踩的坑】编号一旦分配就必须永久固定！如果重新建库时编号变了，
        #   但向量库里存的还是旧编号，那检索就会「张冠李戴」。
        #   所以这份对照表必须存盘（见 save/load），并且建库时要整体重建。
        self.term_to_id: dict[str, int] = {}
        # 【这行在干什么】建立「词 → 它在几篇文档里出现过」的统计表，初始为空。
        # 【为什么需要】这是 IDF 的原料。一个词出现在越少的文档里，说明它越「有辨识度」，
        #   权重就该越高。「市政」可能出现在 1000 篇里，「废标」可能只出现在 20 篇里，
        #   后者显然更能帮我们定位到想要的文档。
        # 【专业词解释】df 是 document frequency 的缩写，即「文档频率」。
        # 【注意区别】df 是「出现在几篇文档里」（按篇计数），不是「出现多少次」（按次数）。
        self.doc_freq: dict[str, int] = {}
        # 【这行在干什么】记录总共有多少篇文档，初始为 0。
        # 【为什么需要】IDF 公式里要用到「总文档数」这个分母。
        # 【专业词解释】一篇文档 = 一条被检索的记录（就是 documents.py 产出的一个 Document）。
        self.n_docs = 0
        # 【这行在干什么】记录所有文档的「总词数」（所有文档长度加起来），初始为 0。
        # 【为什么需要】用来算平均文档长度。
        self.total_length = 0
        # 【这行在干什么】记录「平均每篇文档有多少个词」，初始为 0.0。
        # 【为什么需要】打分公式里要拿「当前文档长度 ÷ 平均长度」来判断这篇文档是长还是短。
        # 【注意事项】用 0.0 而不是 0，是为了明确告诉大家这是个小数（浮点数）。
        self.avg_doc_length = 0.0

    # ----------------------------- 拟合 ----------------------------- #
    # 【这行在干什么】这是「分隔注释」，把文件按功能分成几个区块，方便快速定位。
    # 【为什么叫拟合】fit 是机器学习界的术语，意思是「拿数据把模型的参数算出来」。
    #   在这里「参数」就是词表、文档频率、平均长度这些统计量。
    # ----------------------------- 拟合 ----------------------------- #
    def fit(self, token_lists: list[list[str]]) -> "BM25Index":
        """基于全量语料统计词表与文档频率。空语料也能安全通过。"""
        # 【这行在干什么】把词表清空，重新开始统计。
        # 【为什么必须清空】如果不重置，重复调用 fit() 会把新旧数据混在一起，
        #   统计量彻底失真。所以 fit 设计成「整表重建」而不是「追加」。
        self.term_to_id = {}
        # 【这行在干什么】把文档频率表也清空。
        # 【为什么】同上，必须整表重建，避免残留旧数据。
        self.doc_freq = {}
        # 【这行在干什么】声明一个局部变量 total_length（从 0 开始累加词数）。
        # 【为什么用局部变量而不是直接累加到 self.total_length】先在这里算完，
        #   等全部算好再一次性写回对象属性，中途万一出错也不会把对象搞得半新半旧。
        total_length = 0
        # 【这行在干什么】声明一个局部变量 n_docs（从 0 开始数文档篇数）。
        # 【为什么】同上，先在局部算完再写回。
        n_docs = 0

        # 【这行在干什么】逐篇文档遍历，tokens 是「这一篇文档的全部词」。
        # 【参数含义】token_lists=所有文档的词列表组成的列表，结构是「列表套列表」，
        #   例如 [["市政","道路"], ["工程","招标"]] 表示两篇文档。
        # 【为什么用这种嵌套结构】因为它正好对应「每篇文档 → 它的词」这种自然层级。
        for tokens in token_lists:
            # 【这行在干什么】文档篇数加一。
            # 【为什么在这里加】每进一圈就代表一篇文档，所以这是在数「一共几篇」。
            n_docs += 1
            # 【这行在干什么】把这篇文章的词数累加到总词数上。
            # 【参数解释】len(tokens)=这篇文档有几个词。
            # 【为什么需要总词数】后面要用「总词数 ÷ 篇数」算出平均文档长度。
            total_length += len(tokens)
            # 【这行在干什么】用 set(tokens) 把这篇文章的词去重，然后逐个统计。
            # 【为什么要去重（关键）】因为 df 统计的是「这个词出现在几篇文档里」，
            #   而不是「出现了几次」。如果一篇文章里「道路」出现了 10 次，
            #   用不去重的列表会把它重复计数 10 次，导致 df 严重虚高。
            #   set 会自动去掉重复项，保证一篇文档里每个词只算一次。
            # 【专业词解释：set 集合】一堆不重复元素放在一起，天然去重。
            #   副作用：集合是无序的，遍历顺序不固定——但这里只是计数，顺序无所谓。
            for term in set(tokens):
                # 【这行在干什么】如果这个词以前没见过，就给它分配一个新编号。
                # 【为什么编号取 len(self.term_to_id)】因为词表初始是空的，
                #   第一个词拿到 0，然后长度变 1；第二个词拿到 1，长度变 2……
                #   这样编号天然是连续、唯一、从 0 开始的，正好满足稀疏向量下标的要求。
                # 【注意事项 1（真实的坑）】编号分配顺序并不是「词在文档里出现的顺序」，
                #   而是 set 集合的遍历顺序——集合的顺序由哈希值决定，甚至还可能因为启动参数
                #   PYTHONHASHSEED 的不同而变化。不过这不影响正确性：
                #   只要「编号表」和「用这套编号编码出来的向量」是同一次流程里产出、
                #   并且一起存下来的，两边就始终自洽。
                # 【注意事项 2】也正因如此，绝不能「只补几个新词就跑一遍编码」——
                #   那会让新旧数据用上不同的编号，下标错位后检索结果会张冠李戴，
                #   而且这种错误很隐蔽、很难发现。要重建就整体重建（索引 + 向量一起）。
                if term not in self.term_to_id:
                    # 【这行在干什么】给这个词登记编号。
                    # 【为什么先判断再赋值】不判断的话会把已存在的词重新编号，
                    #   旧编号就作废了，向量库里的历史数据全部失效。
                    self.term_to_id[term] = len(self.term_to_id)
                # 【这行在干什么】把这个词的「文档频率」加一。
                # 【为什么用 .get(term, 0)】这个词可能是第一次出现，字典里还没有它，
                #   直接取会报错；.get(term, 0) 的意思是「取不到就当 0」，
                #   然后再 +1 变成 1。这是 Python 里做计数的经典写法。
                self.doc_freq[term] = self.doc_freq.get(term, 0) + 1

        # 【这行在干什么】把统计好的文档篇数写回对象属性。
        # 【为什么到这里才写】见前面「局部变量」的解释：算完再落库，避免中间状态污染。
        self.n_docs = n_docs
        # 【这行在干什么】把总词数写回对象属性。
        # 【为什么需要存它】它已经体现在平均长度里了，但保留原始值便于排查问题、
        #   也便于未来调整公式。
        self.total_length = total_length
        # 【这行在干什么】算出平均文档长度：总词数 ÷ 文档篇数。
        # 【写法解释】`(A / B) if n_docs else 0.0` 是三元表达式，读作
        #   「如果 n_docs 有值（不为 0），就做除法；否则取 0.0」。
        # 【为什么必须做这个保护（重要）】空知识库时 n_docs 是 0，直接除会触发
        #   ZeroDivisionError（除以零错误），整个建库流程就崩了。
        #   本项目要求「空数据也能正常运行」，所以这里必须防住。
        self.avg_doc_length = (total_length / n_docs) if n_docs else 0.0
        # 【这行在干什么】返回自己（self）。
        # 【为什么返回自己】这是「链式调用」的写法，允许写 `idx = BM25Index().fit(data)`，
        #   一行完成创建和拟合两个动作，用起来更顺。
        return self

    # 【这行在干什么】定义一个「属性」ready，用来回答「这个索引现在能不能用」。
    # 【专业词解释：@property】加上这个装饰器后，调用时可以写成 `idx.ready`（像读变量一样），
    #   而不用写成 `idx.ready()`（加括号调用函数）。这样读起来更像「在问它一个状态」。
    # 【为什么需要】空知识库时索引里什么统计量都没有，如果还硬要编码，
    #   会得到一堆空向量、甚至除以零。给调用方一个「先问一句」的开关，检索侧就能提前短路。
    # 【注意事项】它是「只有取值、不能赋值」的属性，想改会报错。
    @property
    def ready(self) -> bool:
        """语料为空时 BM25 不可用，检索侧据此短路。"""
        # 【这行在干什么】同时满足两个条件才算就绪：至少有一篇文档，且词表非空。
        # 【为什么两个都要判】极端情况下可能出现「有文档但一个有效词都没有」
        #   （例如文档全是标点符号，全被 _TOKEN_KEEP 过滤掉了），
        #   此时词表是空的，编码出来也是空向量，同样不能算「能用」。
        # 【参数解释】self.n_docs > 0 说明统计过文档；
        #   bool(self.term_to_id) 把字典转成真假：空字典是 False，非空是 True。
        return self.n_docs > 0 and bool(self.term_to_id)

    # ----------------------------- 打分 ----------------------------- #
    # 【这行在干什么】又一个分隔注释，标记「打分相关」代码从这里开始。
    # 【为什么单独成块】因为这是 BM25 的数学核心，单独圈出来方便对照上面的公式说明读。
    # ----------------------------- 打分 ----------------------------- #
    def idf(self, term: str) -> float:
        # 【这行在干什么】函数说明行：计算某个词的 IDF（权重）。
        # 【通俗解释 IDF】就是「这个词有多稀罕」。越稀罕 → 分数越高 → 越能帮上忙。
        #   例如「的」「项目」这种到处都是的词几乎没权重；「流标」「联合体」这种词权重就高。
        # 【参数含义】term=要评估的词。

        # 【这行在干什么】如果一篇文档都没有（n_docs 为 0），直接返回 0.0。
        # 【为什么这么写】这是防「除以零」的保险：公式里有 (n_docs - df + 0.5)/(df + 0.5)，
        #   虽然分母不会为零，但空语料下算出来的数也毫无意义，直接给 0 更安全、语义也更清楚。
        if self.n_docs == 0:
            return 0.0
        # 【这行在干什么】查这个词的文档频率 df；如果没查到（词没见过）就取 0。
        # 【参数解释】self.doc_freq.get(term, 0) 同样是为了不报错。
        # 【为什么没见过的词 df 记 0】按公式 df=0 会得到较大的 IDF——但请注意，
        #   没见过的词在编码阶段会因为「查不到编号」被直接丢弃，
        #   所以这里的取值实际上不会影响最终结果。
        df = self.doc_freq.get(term, 0)
        # 【这行在干什么】套用 BM25 的 IDF 公式算出这个词的权重。
        # 【公式逐个符号解释】
        #   self.n_docs —— 总文档篇数（记为 N）；
        #   df          —— 这个词出现在几篇文档里；
        #   0.5         —— 平滑项。为什么要它？防止极端情况（比如 df=0 时公式退化）。
        #                 加了 0.5 之后，无论数据多偏，结果都稳定。
        #   1 + ...     —— 这是 BM25 的一种改良写法（常称 BM25+），
        #                 因为 log 里的内容最小也是 1（当整个分数部分接近 0 时），
        #                 log(1)=0，于是 IDF 永远 ≥ 0，不会出现「负权重」把相似度算成负分。
        # 【直觉验证一下】假设 1000 篇文档里只有 1 篇含「流标」：
        #   (1000-1+0.5)/(1+0.5) ≈ 666，log(1+666) ≈ 6.5 → 权重很高。
        #   若 1000 篇全含「项目」： (1000-1000+0.5)/(1000+0.5) ≈ 0.0005，
        #   log(1.0005) ≈ 0.0005 → 权重几乎为 0。
        #   这正符合预期：烂大街的词不给分。
        # 【注意事项】这个值只依赖「语料库统计」，跟具体是哪篇文档无关；
        #   正因如此，它才能被放在「查询侧」计算（原因见下方 encode_query 的说明）。
        return math.log(1 + (self.n_docs - df + 0.5) / (df + 0.5))

    # 【这行在干什么】把「一篇文档」编码成稀疏向量（文档侧）。
    # 【专业词解释：稀疏向量】一个超长的数字数组，绝大多数位置是 0，只有少数几个位置有值。
    #   为什么是稀疏的？因为词表可能有几万个词，而一篇文档只用到其中几十个词，
    #   存整个数组会浪费 99% 的空间。所以只用「下标列表 + 权重列表」两串数字表示：
    #     下标 [ 3, 17, 90 ] 和 权重 [ 0.8, 1.2, 0.5 ]
    #   含义是「第 3 号词权重 0.8，第 17 号词权重 1.2，第 90 号词权重 0.5，其余全为 0」。
    # 【参数含义】tokens=这一篇文档切好的词列表（由 tokenize 产出）。
    # 【返回值】一对（下标列表, 权重列表）。
    def encode_document(self, tokens: list[str]) -> tuple[list[int], list[float]]:
        """文档侧稀疏向量：只用 tf 归一化因子（不含 idf）。"""
        # 【这行在干什么】两个保险：没有词、或者索引还没就绪，就返回两个空列表。
        # 【为什么这么写】空列表在向量库里表示「这篇文档没有可检索内容」，
        #   是一个明确的、可被处理的信号；而如果硬算下去，会出现除以零等问题。
        # 【注意事项】这里返回的是「一对空列表」而不是一个空值，调用方解包时不会报错。
        # 【专业词解释：tuple[list[int], list[float]]】表示返回值是一个「二元组」，
        #   第一个元素是整数列表，第二个元素是小数列表。
        if not tokens or not self.ready:
            return [], []
        # 【这行在干什么】记下这篇文档的词数，也就是文档长度（公式里的 dl）。
        # 【参数含义】length=该文档的词数，例如 42。
        length = len(tokens)
        # 【这行在干什么】取平均文档长度，作为长度归一化的参照基准。
        # 【写法解释】`self.avg_doc_length or 1.0` 的意思是「如果平均长度是 0（空语料），
        #   就改用 1.0」。这是防止后面除以零的第二道保险。
        # 【为什么在这里还要防一次】虽然 ready 已经保证了 n_docs>0（此时平均长度不为 0），
        #   但对象状态可能被人手工改坏、或从残缺的存档载入，多一道保险更稳。
        avgdl = self.avg_doc_length or 1.0

        # 【这行在干什么】建立「词 → 在这篇文档里出现次数」的计数表。
        # 【专业词解释】tf 是 term frequency 的缩写，即「词频」，但这里统计的是原始次数，
        #   后面还会经过饱和处理。
        term_freq: dict[str, int] = {}
        # 【这行在干什么】遍历这篇文档的每个词，逐个计数。
        # 【参数含义】token=当前这个词。
        for token in tokens:
            # 【这行在干什么】把这个词的计数加一（取不到就当 0，再 +1）。
            # 【为什么用 .get(token, 0) + 1】这是 Python 计数的标准写法，
            #   等价于「在原来的基础上 +1，没出现过就从 1 开始」。
            # 【举例】文档是 ["道路","市政","道路"]，循环结束得到 {"道路":2, "市政":1}。
            term_freq[token] = term_freq.get(token, 0) + 1

        # 【这行在干什么】准备两个空列表，分别装下标和权重。
        # 【为什么必须是两个平行的列表】它们要一一对应：indices[0] 对应的权重是 values[0]，
        #   所以下面每次都要同时往两个列表里追加，保持长度一致。
        indices: list[int] = []
        # 【这行在干什么】准备权重列表。
        # 【注意事项】两个列表的长度必须始终相等，这是向量库的硬性要求。
        values: list[float] = []
        # 【这行在干什么】遍历这篇文档里出现过的每个词及其次数。
        # 【参数含义】term=词；freq=它在本篇文档里出现的次数（未饱和处理的原始次数）。
        for term, freq in term_freq.items():
            # 【这行在干什么】查这个词的编号。
            # 【为什么用 .get 而不是 []】因为这个词可能不在词表里（下面会解释什么是未登录词），
            #   用 .get 查不到会返回 None 而不是报错。
            term_id = self.term_to_id.get(term)
            # 【这行在干什么】如果这个词没有编号（就叫「未登录词」），跳过它。
            # 【专业词解释：未登录词】指在「统计阶段（fit）」没见过的词，
            #   所以在词表里查不到编号。
            # 【为什么建库时也会遇到未登录词（重要）】因为编码发生在 fit 之后，
            #   按理说文档里的词都在词表里……但实际中可能出现：传入编码的词表
            #   和 fit 用的词表不是同一批（例如分批建库），或者词表被人为改动。
            #   遇到就丢掉，是唯一安全的选择——因为「没有编号」就无法表达成向量。
            # 【注意事项】这是个诚实的降级：丢词会略微降低检索效果，
            #   但绝不会让程序报错停摆。
            if term_id is None:  # 未登录词直接丢弃
                # 【这行在干什么】跳过这个词，继续下一个。
                continue
            # 【这行在干什么】算出 BM25 分母，也就是「饱和 + 长度惩罚」那一坨。
            # 【公式逐个符号解释】freq + k1 * (1 - b + b * length / avgdl)
            #   freq              —— 这个词在这篇文档出现次数；
            #   k1                —— 饱和系数（默认 1.5），越大越看重出现次数；
            #   b                 —— 长度归一化系数（默认 0.75）；
            #   length / avgdl    —— 这篇文档比平均长度长多少倍；
            #                       比平均长 → 这个比值大于 1 → 分母变大 → 得分被压低（惩罚长文档）；
            #                       比平均短 → 比值小于 1 → 分母变小 → 得分被抬高（补偿短文档）。
            # 【为什么改这个会怎样】k1 调大 → 词频影响更大（重复出现的词更占便宜）；
            #   b 调大 → 长文档被压得更狠。
            denominator = freq + self.k1 * (1 - self.b + self.b * length / avgdl)
            # 【这行在干什么】如果分母算出来是 0 或负数，就跳过这个词。
            # 【为什么需要这个判断（重要）】分数是「分子 ÷ 分母」，分母一旦为 0 就会抛
            #   ZeroDivisionError，整个建库直接崩掉。什么情况下会 ≤0？比如有人把 b 配成很大、
            #   或 k1 配成负数这类非法值。这里做最后的兜底，宁可少一个词，也不能让流程崩溃。
            if denominator <= 0:
                # 【这行在干什么】跳过这个异常词。
                # 【为什么这么处理】单点异常不应该影响整体，丢了它只是少一点召回。
                continue
            # 【这行在干什么】把词编号追加到下标列表。
            # 【注意事项】必须和下一行的权重成对追加，否则两个列表会错位。
            indices.append(term_id)
            # 【这行在干什么】算出这个词在这篇文档里的权重，追加到权重列表。
            # 【公式解释】freq * (k1 + 1) / denominator
            #   - freq * (k1 + 1) 是分子：出现次数越多，分子越大；
            #   - (k1 + 1) 是固定的放大系数，目的是让结果「大致落在 0~1 的量级」，
            #     数值上更温和（对排序来说它其实是常数，可以省略，但保留更贴近教科书公式）。
            # 【关键设计：为什么这里「不含 IDF」（重要）】
            #   因为 IDF 只跟语料库统计有关，对同一批数据里的所有文档来说是完全相同的值。
            #   与其给每篇文档都乘一遍（白算几百万次），不如把它放到「查询侧」去乘一次。
            #   最后两边做点积时，IDF 自然就乘进来了，结果与标准 BM25 完全一致。
            #   所以这个函数注释里说「只用 tf 归一化因子」。
            # 【潜在风险】这种做法要求「文档侧编码时的公式」和「查询侧编码时的公式」
            #   必须严格配对，任何一边改了公式，另一边的结果就会整体偏掉。
            values.append(freq * (self.k1 + 1) / denominator)
        # 【这行在干什么】返回两个配对的列表（下标 + 权重），交给向量库存储。
        # 【注意事项】这里返回的是元组，调用方通常写成 `indices, values = ...` 来解包。
        return indices, values

    # 【这行在干什么】把「用户的问题」编码成稀疏向量（查询侧）。
    # 【和 encode_document 的区别（关键）】这是「一次问答的逆过程」的最后一环：
    #   文档侧在建库时就算好并存进了向量库；查询侧则是用户每次提问时现算。
    # 【参数含义】text=用户问题原文（还没分词）。
    # 【返回值】同样是（下标列表, 权重列表）一对。
    def encode_query(self, text: str) -> tuple[list[int], list[float]]:
        """查询侧稀疏向量：idf * 查询词频。"""
        # 【这行在干什么】索引没就绪就直接返回两个空列表。
        # 【为什么这么写】空知识库时应该「查不到」，而不是报错。
        #   返回空向量后，向量库算出的分数是 0，检索侧会正常地走「无数据」分支。
        if not self.ready:
            return [], []
        # 【这行在干什么】建立「词 → 在问题里出现次数」的计数表。
        # 【为什么和文档侧几乎一样的代码不抽成公共函数】因为两侧「用不用 IDF」不同，
        #   强行合并会让逻辑更绕；这种「看起来重复但意图不同」的代码，分开写反而更清楚。
        term_freq: dict[str, int] = {}
        # 【这行在干什么】先把用户的问题切词，再逐个计数。
        # 【参数含义】tokenize(text) 复用文件开头的分词函数，保证「建库时切词方式」和
        #   「检索时切词方式」完全一致——这点极其重要，两边切法不一致会直接导致搜不到。
        for token in tokenize(text):
            # 【这行在干什么】计数加一。
            # 【参数解释】freq 最终会作为查询侧权重的一部分（专业名叫 qtf，查询词频）。
            term_freq[token] = term_freq.get(token, 0) + 1

        # 【这行在干什么】准备下标列表。
        # 【注意事项】和文档侧一样，下标与权重必须成对、等长。
        indices: list[int] = []
        # 【这行在干什么】准备权重列表。
        values: list[float] = []
        # 【这行在干什么】遍历问题里出现的每个词。
        # 【参数含义】term=词；freq=这个词在问题里出现了几次。
        for term, freq in term_freq.items():
            # 【这行在干什么】查这个词的编号。
            # 【为什么查不到要处理】用户问题里很可能有词表里根本没有的词
            #   （比如打错字、或问了个知识库里没有的领域），这种词无法表达成向量。
            term_id = self.term_to_id.get(term)
            # 【这行在干什么】没编号（未登录词）就跳过。
            # 【为什么这么写】没有编号就没法放进稀疏向量的下标里，
            #   丢弃是唯一可行的处理；效果上相当于「这个词不参与本次检索」，符合直觉。
            if term_id is None:
                # 【这行在干什么】跳过这个词。
                # 【注意事项】如果用户问题里的词全部都是未登录词，最终会得到两个空列表，
                #   也就是「这次关键词检索什么都召不回来」——这是正常且预期的降级行为。
                continue
            # 【这行在干什么】把编号加入下标列表。
            indices.append(term_id)
            # 【这行在干什么】把权重加入权重列表，权重 = IDF × 查询词频。
            # 【为什么查询侧要乘 IDF（核心设计）】前面说过，IDF 对所有文档都相同，
            #   所以从文档侧挪到查询侧来算，省下大量重复计算。
            #   最终向量库把「文档侧权重」和「查询侧权重」相乘再求和（点积），
            #   结果恰好等于：Σ idf(词) × 词在文档里的饱和权重 × 词在问题里的次数
            #   —— 这就是标准的 BM25 分数。
            # 【为什么还要乘 freq】想象用户问「联合体 联合体 条件」，重复强调的词
            #   理应更重要一些，乘上出现次数体现这个倾向。
            # 【潜在风险】如果用户把某个词刷了很多遍，得分会被线性放大；
            #   生产系统有时会对 qtf 也做饱和处理，本项目为了公式清晰没有做。
            values.append(self.idf(term) * freq)
        # 【这行在干什么】返回查询侧的（下标, 权重）两个列表。
        return indices, values

    # --------------------------- 持久化 --------------------------- #
    # 【这行在干什么】分隔注释，标记「存盘/读盘」相关的代码从这里开始。
    # 【专业词解释：持久化】把内存里的数据存到硬盘上，这样程序重启后还能读回来。
    #   本文件算出的统计量如果丢了，每次启动都得把全库重新分词统计一遍，很慢，
    #   所以必须存盘。
    # --------------------------- 持久化 --------------------------- #
    def to_dict(self) -> dict:
        # 【这行在干什么】把对象里所有需要保存的状态，打包成一个字典返回。
        # 【为什么单独写一个方法】存盘（save）和别的地方可能都需要这份字典，
        #   抽出来避免把「组装数据」的代码写两遍。
        # 【返回值类型】普通的 dict（这里没写详细标注，表示内容比较杂，反正只要 JSON 能装下就行）。
        return {
            # 【这行在干什么】把饱和系数 k1 一起存档。
            # 【为什么参数也要存】如果只存统计量不存参数，而检索时又用了另一套参数，
            #   打分口径就会前后不一致，分数可比性被破坏。
            "k1": self.k1,
            # 【这行在干什么】把长度归一化系数 b 一起存档。
            # 【为什么】同上，保证「算分数」和「查分数」用的是同一套尺子。
            "b": self.b,
            # 【这行在干什么】存文档总篇数。
            # 【为什么需要】IDF 公式的分子分母都要用它，load 回来必须能复原。
            "n_docs": self.n_docs,
            # 【这行在干什么】存所有文档的总词数。
            # 【为什么需要】虽然平均长度已经能体现它，但保留原始值便于排查与将来改公式。
            "total_length": self.total_length,
            # 【这行在干什么】存平均文档长度。
            # 【为什么需要】编码文档时要用它做长度归一化，缺了它长度惩罚就失效。
            "avg_doc_length": self.avg_doc_length,
            # 【这行在干什么】存「词 → 编号」对照表（整个词表）。
            # 【为什么最关键】它决定了下标的含义。丢失或错位会导致「查到的分数对应到了错误的词」，
            #   检索结果会完全错乱且很难被发现。
            "term_to_id": self.term_to_id,
            # 【这行在干什么】存「词 → 文档频率」统计表。
            # 【为什么需要】查询侧每次都要算 IDF，而 IDF 要用 df，所以必须能随时取到。
            "doc_freq": self.doc_freq,
        }

    # 【这行在干什么】把索引保存到指定文件。
    # 【参数含义】path=目标文件路径（Path 对象）。
    def save(self, path: Path) -> None:
        # 【这行在干什么】确保上级目录存在；不存在就创建。
        # 【参数逐个解释】parents=True 表示「连接多级缺失的目录一起创建」
        #   （例如 data/bm25 两层都不存在也照样建好）；
        #   exist_ok=True 表示「目录已经存在时不报错」，让重复保存成为安全的操作。
        # 【为什么需要】第一次运行时数据目录往往还不存在，如果直接写文件会报
        #   FileNotFoundError，必须先建目录。
        path.parent.mkdir(parents=True, exist_ok=True)
        # 【这行在干什么】打开文件准备写入。
        # 【参数逐个解释】"w" 表示「写入模式」（写不存在的文件会新建，已存在的内容会被覆盖）；
        #   encoding="utf-8" 明确指定编码，避免在中文系统上写出乱码。
        # 【为什么用 with】with 语句会在代码块结束时自动关文件，即使中途出错也会关，
        #   避免「文件句柄泄漏」（打开太多文件会让系统资源耗尽）。
        with path.open("w", encoding="utf-8") as fp:
            # 【这行在干什么】把字典转成 JSON 文本写进文件。
            # 【参数逐个解释】self.to_dict() 是要写的数据；
            #   fp 是目标文件；
            #   ensure_ascii=False 表示「中文直接按中文写，不要转成 \uXXXX 这种转义形式」。
            # 【为什么设 ensure_ascii=False】不加它，文件里会是一堆「\u5e02\u653f」，
            #   人根本看不懂，排查问题时要命；加上之后是「市政」，直观可读。
            json.dump(self.to_dict(), fp, ensure_ascii=False)

    # 【这行在干什么】定义类方法 load：从文件读回索引，不用先创建实例。
    # 【专业词解释：@classmethod】类方法，第一个参数是 cls（代表「这个类本身」），
    #   调用时用 BM25Index.load(...)，它会在内部帮我们创建实例。
    #   为什么这样设计？因为「从文件恢复一个对象」这件事，逻辑上应该由类来负责，
    #   而不是先造一个空对象再让它自己去读文件。
    # 【参数含义】path=索引文件路径；k1、b=默认参数（文件里没有记录时使用）。
    # 【返回值标注】"BM25Index" 用引号包住，表示「现在先别解析这个类型名」，
    #   因为写到这一行时 BM25Index 类还没定义完。这叫做「前向引用」。
    #   （本文件开头已经开了延迟求值，其实不加引号也行，这里保留是更保险的写法。）
    @classmethod
    def load(cls, path: Path, k1: float = 1.5, b: float = 0.75) -> "BM25Index":
        """索引文件不存在（例如尚未建库）时，返回一个空索引而不是报错。"""
        # 【这行在干什么】先创建一个「空的」索引对象作为兜底结果。
        # 【为什么先造空的（重要设计）】因为下面所有异常分支都会直接返回它。
        #   这叫「降级」：读不到真数据时，给一个「什么都不知道但能用」的对象，
        #   让整个系统继续跑（表现为「关键词检索暂时没结果」），而不是直接崩掉。
        #   本项目明确要求「支持空数据运行」，这里是落实点之一。
        index = cls(k1=k1, b=b)
        # 【这行在干什么】如果索引文件根本不存在（例如还没建过库），直接返回空索引。
        # 【为什么这么写】第一次跑项目时文件当然不存在，这属于正常情况而不是错误，
        #   不应该报错吓人。
        if not path.exists():
            return index
        # 【这行在干什么】尝试打开并解析索引文件；出错的话（文件损坏、权限不足等）就兜住。
        # 【为什么要 try/except（潜在风险点）】存档文件可能因为「写盘写到一半断电」
        #   「被其他程序误删/改坏」「磁盘满」等原因变成非法内容。
        #   如果不兜住，服务一启动就读文件失败、直接起不来——这是生产环境最忌讳的。
        # 【参数解释】异常元组 (OSError, json.JSONDecodeError) 表示「这两类错误都在此处理」：
        #   OSError 覆盖文件读取层面的问题（打不开、读不了）；
        #   json.JSONDecodeError 覆盖「文件内容不是合法 JSON」的问题。
        try:
            # 【这行在干什么】打开文件读取。
            # 【参数解释】"r" 表示只读模式；encoding="utf-8" 必须与存盘时一致，
            #   否则中文会乱码甚至报解码错误。
            with path.open("r", encoding="utf-8") as fp:
                # 【这行在干什么】把文件里的 JSON 文本解析回 Python 字典。
                # 【安全性说明】json.load 只能解析纯数据，不会执行代码，
                #   所以读一个本地存档文件不存在「被执行恶意代码」的风险。
                data = json.load(fp)
        # 【这行在干什么】捕获上面两类错误。
        # 【为什么捕获后返回空索引而不是抛出异常】见上面的解释：宁可降级，不可崩溃。
        # 【注意事项】代价是「静默失败」——文件坏了但没人知道，只是检索效果悄悄变差。
        #   好在调用方通常会把 ready 状态暴露到健康检查接口里，运维能看到线索。
        except (OSError, json.JSONDecodeError):
            # 【这行在干什么】返回那个空的索引对象，让程序继续运行。
            return index
        # 【这行在干什么】从字典里取回 k1；如果键不存在就用传入的默认值。
        # 【为什么套 float(...)】JSON 里的数字理论上就是数字，但为了防御
        #   「被人手工改成字符串 "1.5"」这类情况，统一强制转成小数。
        # 【为什么这么谨慎】下面马上要用它做除法运算，类型不对会直接报错。
        index.k1 = float(data.get("k1", k1))
        # 【这行在干什么】同理取回 b 并强制转成小数。
        # 【为什么】它会参与除法运算，类型必须稳。
        index.b = float(data.get("b", b))
        # 【这行在干什么】取回文档总篇数并强制转成整数。
        # 【为什么用 int(...)】IDF 里要拿它做除法，类型不对会报错；
        #   int 会丢弃小数部分，正好符合「篇数必然是整数」的语义。
        index.n_docs = int(data.get("n_docs", 0))
        # 【这行在干什么】取回总词数并转成整数。
        # 【为什么】同样是为了保证参与运算的数值类型正确。
        index.total_length = int(data.get("total_length", 0))
        # 【这行在干什么】取回平均文档长度并转成小数。
        # 【为什么用 float】它天然是小数（总词数 ÷ 篇数 往往除不尽），必须保留小数部分。
        index.avg_doc_length = float(data.get("avg_doc_length", 0.0))
        # 【这行在干什么】把存下来的「词 → 编号」字典恢复出来，并保证编号都是整数。
        # 【写法解释】`{k: int(v) for k, v in data.get("term_to_id", {}).items()}`
        #   是「字典推导式」：遍历原字典的每一项，重新生成一个新字典。
        #   可以读作「对于每一项 (k, v)，生成 k: int(v)」。
        # 【为什么必须逐个 int() 转换（重要）】如果文件被人手工编辑过，
        #   里面的编号可能变成字符串 "0"；字符串下标会导致向量库直接拒绝写入
        #   或者静默错位。在这里统一转成整数，把问题挡在入口。
        index.term_to_id = {k: int(v) for k, v in data.get("term_to_id", {}).items()}
        # 【这行在干什么】同理恢复「词 → 文档频率」，并把频率值统一转成整数。
        # 【为什么】df 会参与 IDF 的分母计算，类型必须正确，
        #   否则会出现「字符串除以数字」这种运行时错误。
        index.doc_freq = {k: int(v) for k, v in data.get("doc_freq", {}).items()}
        # 【这行在干什么】返回恢复好的索引对象，检索侧拿到它就能正常编码用户问题了。
        # 【注意事项】如果文件是残缺的（例如只写了前半段就被中断），
        #   上面的 .get(..., 默认值) 会让缺失的部分退化成默认值，
        #   对象「不会报错但可能不准」——这是有意的取舍：可用性优先于精确性。
        return index