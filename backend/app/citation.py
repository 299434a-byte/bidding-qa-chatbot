# ============================================================================
# 正则：三类「要找的东西」各自的模式
# ============================================================================
# 【这行在干什么】匹配回答里的引用标记，两种写法都认：`[参考资料3]` 和 `[参考3]`。
# 【写法拆解】r"\[参考资料(\d+)\]|\[参考(\d+)\]"：
#   · \[ 和 \] —— 方括号在正则里是特殊符号，所以要反斜杠转义，表示「真的方括号」；
#   · 参考资料 / 参考 —— 字面匹配这两个中文字；
#   · (\d+) —— 一对小括号是「捕获组」，把里面的数字单独抓出来；\d+ 表示一串数字；
#   · | —— 「或」：前半段（参考资料N）不匹配时，再试后半段（参考N）。
# 【为什么两种都认】提示词里约定用「[参考资料N]」，但模型偶尔会简写成「[参考N]」；
#   都认下来，校验才不会因为写法差异漏检。
_CITE_RE = re.compile(r"\[参考资料(\d+)\]|\[参考(\d+)\]")

# 【这行在干什么】匹配「带货币单位的金额」，如 1590万元 / 528057.00 万元 / 50万 / 1200元。
# 【写法拆解】r"(?P<num>\d[\d,]*(?:\.\d+)?)\s*(?P<unit>万元|万|元)"：
#   · (?P<num>...) —— 具名捕获组，给抓到的内容起名 num，后面按名字取，比数第几个括号清楚；
#   · \d[\d,]* —— 一开头必须是个数字，后面允许跟数字或逗号（应对千分位「1,590」）；
#   · (?:\.\d+)? —— 可选的小数部分；?: 表示「只分组不捕获」，因为我们只要整串；
#   · \s* —— 数字和单位之间允许有空格；
#   · (?P<unit>万元|万|元) —— 单位。**顺序很关键**：万元写在万前面，
#     否则匹配「1590万元」时会先撞上「万」把「元」落下（正则的「或」是从左到右取第一个能成的）。
# 【注意事项】这里不认「亿」。题目只要求统一「万元/万/元」；少认一种单位，宁可漏检也不误杀
#   （比如回答把 528057万元 近似成「52.8亿元」，值其实不等，硬比会误判成编造）。
_AMOUNT_RE = re.compile(r"(?P<num>\d[\d,]*(?:\.\d+)?)\s*(?P<unit>万元|万|元)")

# 【这行在干什么】匹配百分比，如 100% / 50％。
# 【写法拆解】r"(?P<num>\d[\d,]*(?:\.\d+)?)\s*(?P<pct>[%％])"：
#   结构和金额那条一样；末尾的 [%％] 同时接受半角 % 和全角 ％（保险起见，NFKC 漏网的也能接住）。
_PCT_RE = re.compile(r"(?P<num>\d[\d,]*(?:\.\d+)?)\s*(?P<pct>[%％])")

# 【这行在干什么】匹配日期，如 2024年08月22日 / 2024-8-22 / 2024/08/22。
# 【写法拆解】r"(\d{4})\s*[-/年.]\s*(\d{1,2})\s*[-/月.]\s*(\d{1,2})\s*日?"：
#   · (\d{4}) —— 年：4 位数字；
#   · [-/年.] —— 年与月之间的分隔符，可能是 -、/、「年」或小数点；
#   · (\d{1,2}) —— 月：1~2 位；
#   · [-/月.] —— 月与日之间的分隔符；
#   · (\d{1,2}) —— 日：1~2 位；
#   · 日? —— 结尾的「日」可有可无。
# 【为什么不担心和金额冲突】日期里没有「元/万」单位，金额那条正则不会误吃日期。
_DATE_RE = re.compile(r"(\d{4})\s*[-/年.]\s*(\d{1,2})\s*[-/月.]\s*(\d{1,2})\s*日?")


# 【这行在干什么】定义内部函数 _to_halfwidth：把全角字符统一转成半角。
# 【参数解释】text —— 原始文本；可能为 None（来源字段偶尔是空的），所以先兜一层。
# 【返回值】半角化后的字符串。
# 【为什么必须做这一步】中文录入里「５０％」和「50%」混用很常见。不转就比不出相等，
#   会把正常回答误判成「数值无依据」——这正是我们要防的「误杀」。
def _to_halfwidth(text: str | None) -> str:
    """全角 → 半角（NFKC 归一化），让「５０％」与「50%」能比出相等。"""
    # 【这行在干什么】字符串为空时直接返回空串，避免下面 None 调 normalize 报错。
    if not text:
        return ""
    # 【这行在干什么】用 Unicode 官方 NFKC 规则做归一化。
    # 【为什么用 NFKC】它会把「全角数字/字母/标点」折叠成对应的半角形式，
    #   同时不会破坏中文汉字、也不会乱改别的符号，正好满足我们的需求。
    return unicodedata.normalize("NFKC", text)


# 【这行在干什么】定义内部函数 _to_number：把「1,590.00」这类带千分位的数字文本变成本文数值。
# 【参数解释】raw —— 正则抓到的数字片段（可能含逗号）。
# 【返回值】float 数值；解析失败返回 None。
# 【为什么要去掉逗号】「1,590.00」里的逗号只是人类看的千分位分隔符，参与运算前必须剔除。
def _to_number(raw: str) -> float | None:
    """把「1,590.00」这样的文本转成 float；解析不了返回 None。"""
    # 【这行在干什么】打开「接住解析失败」的网。
    # 【为什么必须接住】正则理论上只抓到数字，但万一遇到畸形文本，转换会抛 ValueError；
    #   校验器不允许因为一个小片段崩掉，所以失败就返回 None、由调用方跳过。
    try:
        return float(raw.replace(",", ""))
    except (TypeError, ValueError):
        return None


# 【这行在干什么】定义本文件的核心之一 normalize_numbers：把文本里的金额/百分比/日期归一化。
# 【参数解释】text —— 任意一段文字（通常是回答全文，或某条来源的原文）。
# 【返回值】一个「集合」（set），里面每个元素都是「可直接比较」的标准化值：
#   · 金额 → float，单位统一为「元」（万元 × 10000）；
#   · 百分比 → float，例如 100% 变成 100.0；
#   · 日期 → 字符串 "YYYY-MM-DD"（补齐两位，便于直接比对）。
# 【为什么返回集合而不是列表（关键）】我们只关心「这个数有没有出现过」，不关心出现几次；
#   集合天然去重，也支持「差集」运算（哪些数字在回答里出现、却不在来源里），正合用途。
# 【为什么不提取「裸数字」】像「第3条」「2024年」这种不带金额/百分比/日期特征的数字，
#   在正常回答里到处都是，全抓进来必然误杀。所以只认「带单位/带日期特征」的，宁缺毋滥。
def normalize_numbers(text: str | None) -> set[float | str]:
    """把文本里的金额/百分比/日期归一化为可比较的集合。"""
    # 【这行在干什么】先做全角转半角，后面所有匹配都在这个「半角版」上进行。
    s = _to_halfwidth(text)
    # 【这行在干什么】准备一个空集合，收集归一化结果。
    out: set[float | str] = set()

    # ---- 金额：统一换算成「元」 ----
    # 【这行在干什么】逐条扫描所有「数字+货币单位」的写法。
    for m in _AMOUNT_RE.finditer(s):
        # 【这行在干什么】把抓到的数字文本转成 float；转不动就跳过这一条。
        num = _to_number(m.group("num"))
        if num is None:
            continue
        # 【这行在干什么】按单位决定换算倍数：万元/万 → ×10000，元 → ×1。
        # 【为什么统一到「元」】因为「1.59万元」和「15900元」是同一个钱数，
        #   换算到同一个基准单位后，两者会得到相同的数值，才能判为相等。
        factor = 10000.0 if m.group("unit") in ("万元", "万") else 1.0
        # 【这行在干什么】算完四舍五入到 4 位小数再放进集合。
        # 【为什么要 round】浮点乘法偶尔会产生 15900000.000000002 这种尾巴，
        #   不收敛的话「1590万元」和「1590.0万元」可能因为尾数不同而判成不等——又是误杀。
        out.add(round(num * factor, 4))

    # ---- 百分比：按百分数点保留（100% → 100.0） ----
    for m in _PCT_RE.finditer(s):
        num = _to_number(m.group("num"))
        if num is None:
            continue
        out.add(round(num, 6))

    # ---- 日期：统一成 "YYYY-MM-DD" ----
    for m in _DATE_RE.finditer(s):
        # 【这行在干什么】把「年-月-日」三位分别取出，月份/日期补足两位（8 → 08）。
        # 【为什么补零】「2024-8-2」和「2024-08-02」是同一个日期，补零后字符串才相等。
        year, month, day = m.group(1), int(m.group(2)), int(m.group(3))
        # 【这行在干什么】做一个基本的合理性检查：月 1~12、日 1~31。
        # 【为什么加这层（防误杀）】「2024-99-99」这种明显不是日期，多半是编号或误匹配，
        #   放进去只会让集合里多出噪声、干扰比对，所以直接丢掉。
        if 1 <= month <= 12 and 1 <= day <= 31:
            out.add(f"{year}-{month:02d}-{day:02d}")

    return out


# 【这行在干什么】定义内部函数 _extract_refs：从回答里抽出所有引用编号。
# 【参数解释】text —— 回答全文。
# 【返回值】一个整数列表，按出现顺序排列（可能有重复，比如 [1, 2, 1]）。
def _extract_refs(text: str | None) -> list[int]:
    """抽出回答里的引用编号（[参考资料N] / [参考N] → N）。"""
    refs: list[int] = []
    # 【这行在干什么】按正则扫全文，逐个处理匹配到的引用标记。
    for m in _CITE_RE.finditer(text or ""):
        # 【这行在干什么】取出编号文本：第 1 组（参考资料N）或第 2 组（参考N），谁有值用谁。
        # 【为什么用 or】两条分支同时只有一个能成，另一个组是 None，or 正好挑到有值的那个。
        raw = m.group(1) or m.group(2)
        try:
            refs.append(int(raw))
        except (TypeError, ValueError):
            # 【为什么接住异常】理论上不会走到，但校验器要「任何情况都不崩」，所以兜一下。
            continue
    return refs


# 【这行在干什么】定义内部函数 _source_numbers：把一条来源里出现的所有数字归一化成集合。
# 【参数解释】source —— 一条来源字典（含 text 正文、fields 原始字段）。
# 【返回值】该来源里所有可比数字的集合。
# 【为什么要连 fields 一起看】来源卡片展示给用户的是渲染好的 text，但真正「原始的权威值」
#   往往在 fields 里（例如 budget_amount=1590.0、budget_amount_unit=万）。
#   只查 text 可能漏掉「1590.0」+「万」被拆成两处的情况，把 fields 一起纳入更稳。
def _source_numbers(source: dict[str, Any]) -> set[float | str]:
    """把一条来源的正文与原始字段里的数字，归一化成一个集合。"""
    # 【这行在干什么】把「正文」和「各字段值」拼成一大段文本。
    # 【写法拆解】先取 text，再把 fields 里每个非空值 str 化后换行拼上。
    pieces: list[str] = [source.get("text") or ""]
    fields = source.get("fields") or {}
    for value in fields.values():
        # 【为什么跳过空值】空字段拼进来只会是空串，毫无信息，还多跑一次正则。
        if value not in (None, ""):
            pieces.append(str(value))
    # 【这行在干什么】拼成整段后一次性归一化，返回结果集合。
    # 【为什么合并成一次调用】省去反复合并集合的代码，也少建几个中间对象。
    return normalize_numbers("\n".join(pieces))


# 【这行在干什么】定义内部函数 _fmt_num：把归一化后的数值「还原成人看的样子」，用于提示文案。
# 【参数解释】value —— 归一化后的值（float 或日期字符串）。
# 【返回值】适合写进提示消息的字符串。
def _fmt_num(value: float | str) -> str:
    """把数值格式化成大人话，用于 issues 里的提示文案。"""
    # 【这行在干什么】日期字符串原样返回。
    if isinstance(value, str):
        return value
    # 【这行在干什么】整数就显示成整数（15900000.0 → "15900000"），小数保留有效位。
    # 【为什么这么做】15900000.0 直接显示很难读；整数化后是「15900000」更直观。
    if value == int(value):
        return str(int(value))
    return f"{value:g}"


# 【这行在干什么】定义本文件的核心之二 verify_citations：给回答做「引用体检」。
# 【参数解释】
#   · answer —— 大模型生成的回答全文（可能是空串）；
#   · sources —— 本轮真实的来源列表（rag.py 里 result.to_sources() 的结果）。
# 【返回值】一个字典：
#   {"ok": bool,               // 校验是否全部通过
#    "issues": [...],          // 问题清单（每条是带 type / message 的小字典，供前端提示）
#    "bad_refs": [...]}        // 「坏的」引用编号列表，交给 strip_bad_refs 精确删除
# 【两类问题的区别（关键）】
#   · ref_out_of_range —— 引用了不存在的第 N 条来源（编造出处）；
#   · number_no_source —— 回答里的某个金额/百分比在「对应来源」里找不到依据（疑似编数字）。
def verify_citations(answer: str, sources: list[dict[str, Any]]) -> dict[str, Any]:
    """校验回答里的引用编号与数字是否有依据。"""
    # 【这行在干什么】把 sources 规整成列表，防止调用方传 None 进来把后面搞崩。
    sources = list(sources or [])
    # 【这行在干什么】本轮真实存在的来源条数——用于判断引用有没有越界。
    n_sources = len(sources)
    # 【这行在干什么】准备两个清单：issues 记「问题描述」，bad_refs 记「要删的引用编号」。
    issues: list[dict[str, Any]] = []
    bad_refs: list[int] = []

    # ---- 第 ① 步：核对引用编号 ----
    # 【这行在干什么】抽出回答里所有引用编号，用 set 去重后逐个检查。
    refs = _extract_refs(answer)
    for n in sorted(set(refs)):
        # 【这行在干什么】编号小于 1 或大于来源总数 = 越界（第 N 条根本不存在）。
        # 【为什么两个条件都要判】N=0 或负数同样是「不存在的来源」，不能只判上界。
        if n < 1 or n > n_sources:
            issues.append({
                "type": "ref_out_of_range",
                "ref": n,
                "message": f"回答引用了不存在的 [参考资料{n}]（本轮来源共 {n_sources} 条）。",
            })
            bad_refs.append(n)

    # ---- 第 ② 步：核对数字有没有依据 ----
    # 【这行在干什么】先把回答里的引用标记抠掉，再去抽数字。
    # 【为什么必须先抠掉标记】[参考资料1] 里的那个「1」不是回答的内容，
    #   留着会让「抽取数字」把引用编号也当成一个数据（虽然它没单位、通常抓不到，
    #   但把标记先清掉最干净，也避免「[参考资料1]万元」这类粘连写法被误读）。
    answer_without_refs = _CITE_RE.sub(" ", answer or "")
    answer_numbers = normalize_numbers(answer_without_refs)

    # 【这行在干什么】确定「比对基准」：优先只在**被引用的那些来源**里找依据；
    #   如果一个有效引用都没有，才退而用全部来源。
    # 【为什么要「对应来源」（关键）】回答写了 [参考资料1]，就等于声明「这段依据来自第 1 条」；
    #   那么它旁边的数字理应能在第 1 条里找到。只在被引用的来源里比对，
    #   既符合「引用即出处」的语义，也能发现「引用张冠李戴」的错位。
    cited_valid = sorted({n for n in refs if 1 <= n <= n_sources})
    if cited_valid:
        basis_sources = [sources[n - 1] for n in cited_valid]
    else:
        basis_sources = sources

    # 【这行在干什么】把基准来源里所有数字合并成一个「依据池」。
    basis: set[float | str] = set()
    for src in basis_sources:
        basis |= _source_numbers(src)

    # 【这行在干什么】逐个检查回答里的数字：不在依据池里 = 疑似编造。
    for value in sorted(answer_numbers, key=lambda v: str(v)):
        if value not in basis:
            issues.append({
                "type": "number_no_source",
                "value": value,
                "message": f"回答中的数值「{_fmt_num(value)}」未能在引用来源中找到依据。",
            })

    # 【这行在干什么】问题清单为空才算通过。
    return {"ok": len(issues) == 0, "issues": issues, "bad_refs": sorted(set(bad_refs))}


# 【这行在干什么】定义本文件的核心之三 strip_bad_refs：精确删除「坏引用」标记。
# 【参数解释】
#   · answer —— 回答全文；
#   · bad_refs —— 要删除的引用编号列表（来自 verify_citations 的 bad_refs）。
# 【返回值】删掉坏标记后的新回答；没有坏引用时原样返回。
# 【为什么「只删坏的」（关键）】用户要求「成功的不动」。正常的 [参考资料1] 是有效出处，
#   删了反而让好引用丢失；只有越界的那些（如 [参考资料9]）才需要抹掉。
def strip_bad_refs(answer: str, bad_refs: list[int]) -> str:
    """只移除校验失败的引用标记，通过的保持原样。"""
    # 【这行在干什么】没有坏引用就直接原样返回——这也是「逐字节一致」的一部分：
    #   不需要改动的文本，绝不引入任何多余的空格或字符。
    bad = {int(n) for n in (bad_refs or [])}
    if not bad:
        return answer
    # 【这行在干什么】把 bad_refs 的语义以「整数集合」的形式固定下来，下面替换时按编号判断。

    # 【这行在干什么】定义替换函数：命中引用标记时，编号属于坏集合就返回空串（删除），
    #   否则返回原样文本（保留）。
    def _replace(m: re.Match[str]) -> str:
        n = int(m.group(1) or m.group(2))
        return "" if n in bad else m.group(0)

    # 【这行在干什么】用上面的规则把全文里所有引用标记过一遍。
    cleaned = _CITE_RE.sub(_replace, answer or "")
    # 【这行在干什么】把因删除标记而残留的「连续多个空格」压成一个。
    # 【为什么要做】删掉标记后可能留下「金额  。」这种双空格，看起来像排版事故；
    #   压一下更整洁。只动空格、不动别的字符，风险很低。
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    return cleaned