# ============================================================================
# 文件：citation.py —— 回答的「引用校验器」（核对引用编号与数字有没有依据）
#
# 【这个文件在整个项目里是干什么的】
#   大模型的回答已经通过 SSE 一段段流到了前端，等到我们发现它「引用了不存在的第 9 条资料」
#   或者「编了一个资料里根本没有的金额」时，那些文字早就显示给用户了——没法像传统程序那样
#   「撤销一段输出」。所以这里换了个思路：不拦在生成前，而是**在生成后做一次体检**，
#   把有问题的引用标记挑出来，再产出一份「修订稿」让前端覆盖展示。
#
#   本文件只做三件纯本地、不联网的事（除了这三个函数，别的都不干）：
#     1) normalize_numbers —— 把五花八门的金额/百分比/日期写法，归一化成「能直接比较」的集合；
#     2) verify_citations —— 体检：引用编号有没有越界？回答里的数字在来源原文里找不找得到？
#     3) strip_bad_refs   —— 只把「校验没通过」的那些引用标记删掉，通过的保持原样。
#
# 【最重要的设计原则（务必记住）】
#   「校验是附加信息，绝不能反过来把问答搞挂。」
#   任何一步出错（正则写错、sources 字段缺失……），调用方（rag.py）都要求静默跳过；
#   而且**校验通过时，整条问答链路的行为必须和以前逐字节一致**——不许多发一个事件。
#
# 【先懂的三个概念（大白话）】
#   1) 归一化（normalize）：同一件事的不同写法，先「翻译」成同一种标准形式再比较。
#      比如「1,590.0万元」「1590万元」「1590万」都是同一个数，直接比字符串会判成不同，
#      归一化后都变成 15900000.0（元），一比就相等。
#   2) 越界（out of range）：回答里写 [参考资料9]，但这一轮来源只有 3 条——第 9 条根本不存在，
#      这就是「编造出处」，比编数字更严重。
#   3) 防误杀：校验器宁可「漏掉一点小毛病」，也不能把正常回答误判成有问题。
#      最典型的就是「1590.0 万元」与「1590 万元」——写法不同但值一样，必须判为通过。
# ============================================================================

# 【这行在干什么】打开「类型注解延迟求值」开关。
# 【为什么这么写】本文件用了 list[dict[str, Any]]、set 这类新式标注，老版本 Python 认不全；
#   加上这行后标注先当字符串存着，需要时才解析，兼容性更好。
from __future__ import annotations

# 【这行在干什么】引入 re 模块（正则表达式，标准库）。
# 【为什么需要】「从一段文字里找出所有引用标记 / 数字 / 日期」本质就是模式匹配，
#   用正则最省事，也不需要额外装包。
import re

# 【这行在干什么】引入 unicodedata（Unicode 字符数据库，标准库）。
# 【为什么需要】中文公告里金额常写成全角（如「１５９０．０万元」「５０％」），
#   全角数字和半角数字在计算机眼里是两个不同的字符。用它的 NFKC 归一化可以把全角转半角。
# 【为什么用 NFKC 而不是手工替换】手工要枚举十来个字符；NFKC 是 Unicode 官方标准，
#   一行就能把「全角数字/字母/标点」统统转成半角，省事又不容易漏。
import unicodedata

# 【这行在干什么】引入 Any 类型标注工具。
# 【为什么需要】sources / issues 里的结构比较灵活（字典套列表套各种值），用 Any 兜住最省心。
from typing import Any

