# ============================================================================
# 文件：documents.py —— 建库流水线上的「翻译车间」
#
# 【这个文件在整个项目里是干什么的】
#   它把 MySQL 数据库里一行一行的「表格数据」，翻译成一段一段的「自然语言文字」，
#   再交给后面的检索系统去用。为什么非要翻译？因为数据库存的是结构化的列和值，
#   而检索系统（关键词检索、向量检索）需要的是能理解语义的连续文字。
#
# 【谁调用它（上游）】—— 谁在用这个文件
#   backend/app/ingest.py 里的 run_ingest()（建库管道）调用本文件的 build_documents()。
#   数据源头是 backend/app/db.py：
#     - discover_schema()：读数据库表结构，拿到列名、列类型、列注释（中文说明）、主键；
#     - iter_rows()：一行一行地把表里的数据读出来。
#
# 【它给谁用（下游）】—— 这个文件的产出被谁消费
#   build_documents() 产出 Document 对象后，有两个去处：
#     1) bm25.py            —— 拿 Document.text 做分词，建立「关键词索引」（BM25 算法）；
#     2) vector_store.py 的 upsert_documents() —— 拿 Document.text 算成向量，连同
#        Document.payload 一起写进向量数据库 Qdrant。
#   用户提问时，检索会命中这些数据，前端就能展示「命中的原文」。
#
# 【重要特性：它自己不连数据库、也不写向量库】
#   本文件只做纯粹的「数据变形」：输入一行数据 → 输出一段文字 + 一个整理好的小盒子。
#   它不做任何网络请求、不读写磁盘。好处是逻辑单纯、容易测试、出问题好定位。
#
# 【先记住三组数字（都在 .env 里配置，代码里不写死）】
#   MAX_DOC_CHARS = 1200   ：一段文字超过 1200 个字符，才需要切成小块；
#   CHUNK_SIZE    = 500    ：切成小块时，每块最多 500 个字符；
#   CHUNK_OVERLAP = 80     ：相邻两块之间故意重叠 80 个字符（防关键句被劈断）。
# ============================================================================

# 【这行在干什么】打开「类型注解延迟求值」这个开关。
# 【为什么这么写】本文件后面写类型标注时用了 list[str]、dict[str, Any]、str | None
#   这类「新式写法」。不加这行的话，老版本 Python（3.8 / 3.9）会因为不认识 list[str]
#   和竖线 | 而直接报错。加上这行之后，这些标注会先被当成「字符串」存着、真正要用时
#   才去解析，于是老版本 Python 也能正常跑起来。
# 【注意事项】它必须放在文件最顶部（在所有执行代码之前），否则 Python 直接报语法错误。
# 【举个例子】`def f(x: list[int])`：不加这行，Python 3.8 会 TypeError；加了就没事。
from __future__ import annotations

# 【这行在干什么】从 Python 自带的工具包 dataclasses 里借来两个工具：dataclass、field。
# 【为什么这么写】
#   - dataclass 是个「装饰器」（可以理解成贴在类头上的一张标签），贴上它以后，
#     Python 会自动帮这个类生成 __init__（构造函数）等一堆样板代码，省去手写。
#     举个对比：手写类要写 def __init__(self, doc_id, table, ...) 再逐个赋值；
#     用 @dataclass 只要把字段写成 `doc_id: str` 这种带类型的形式，就自动有了构造函数。
#   - field 用来给「某一个字段」做额外配置，本文件用它在第 35 行给字典字段设置默认值。
# 【注意事项】Python 2 / 很老的 3.x 没有 dataclasses，但本项目跑在 3.10，无需担心。
from dataclasses import dataclass, field

# 【这行在干什么】从 Python 自带的工具包 typing 里借来两个「类型标注」工具：Any、Iterator。
# 【为什么这么写】类型标注本身不影响程序运行，它的作用是：①让人一眼看懂数据长什么样；
#   ②让编辑器（IDE）能自动提示、提前发现写错的地方。
#   - Any：表示「任意类型，什么都行」。为什么需要它？因为从 MySQL 取出来的值类型不固定，
#     可能是整数、字符串、日期、金额小数……事先说不准，所以用 Any 兜住。
#   - Iterator：表示「迭代器」，也就是一种「能一个一个往外吐数据的东西」（详见下方 yield 的解释）。
# 【举个例子】`row: dict[str, Any]` 读作：「row 是一个字典，键是字符串，值是什么都行」，
#   比如 {"项目名称": "某某工程", "预算金额": 1500000} 就符合这个描述。
from typing import Any, Iterator

# 【这行在干什么】从本项目自己的 config 模块里拿到配置类 Settings。
# 【为什么这么写】切块阈值、每块多大、重叠多少，这些参数统统由配置文件（.env）决定，
#   代码里不写死数字。这样运维/开发想调优时，只改配置、重启服务即可，不用改代码。
# 【注意事项】开头那个点「.」表示「同一个包（同一个文件夹）里的模块」，
#   所以这行不能在项目外单独运行——必须作为 app 包的一部分被导入。
from .config import Settings

# 【这行在干什么】定义一个常量：单个字段的值写入 payload 时，最多保留 4000 个字符。
# 【为什么这么写】payload 可以理解为「跟着正文一起存进向量库的随身行李」，其中 fields
#   存的是这条记录的原始字段，供前端展示「命中的原文」。万一某个字段是几万字的备注，
#   整个 payload 会变得非常大，导致建库写入变慢、查询传输变大、内存占用变高。
#   所以在写入前先做一次截断。
# 【注意事项 1】它只截断「payload 里的展示副本」，不影响 text 正文，
#   所以调整它不会改变检索结果，只会改变前端看到的原文完整度。
# 【注意事项 2】截断是「从中间一刀切」的硬截断，不是智能摘要，所以被截断处会加标记，
#   让人知道内容不完整。
# 【调大调小会怎样】调大 → 原文更完整，但建库更慢、占用更大；调小 → 更快更省，
#   但用户可能看不到长文本字段的全貌。
# 单个字段值写入 payload 时的截断长度，防止超长文本撑爆 payload
_FIELD_TEXT_LIMIT = 4000

# 【这行在干什么】定义一个「字段类型黑名单」：这些类型的字段不参与文字生成。
# 【为什么这么写】blob / binary 这类是「二进制大对象」，用来存图片、附件、压缩包等
#   非文字内容。把它们的原始字节转成字符串只会得到一堆乱码，既占空间又污染检索结果，
#   所以干脆跳过。
# 【专业词解释】set 是「集合」：一堆不重复的元素放在一起，{...} 是它的写法。
#   相比列表（list），集合查找「某个东西在不在里面」的速度快得多，
#   而且天然去重（同样的元素写两遍也只算一个）。
# 【注意事项】如果将来表里有别的「非文字类型」也想跳过（例如 json 大字段），
#   就往这个集合里补一个词。属于集合成员判断的是第 48 行。
# 这些类型不参与文本生成（二进制/大对象没有检索意义）
_SKIP_TYPES = {"blob", "tinyblob", "mediumblob", "longblob", "binary", "varbinary"}


# 【这行在干什么】给下面的 Document 类贴上 dataclass 标签，让 Python 自动生成构造函数。
# 【为什么这么写】见上方 import 处的解释：省掉手写 __init__ 的样板代码，
#   字段定义即构造函数，一目了然、不容易漏字段。
# 【注意事项】字段的顺序就是构造函数的参数顺序。下面 yield Document(...) 时，
#   用的是「关键字传参」（doc_id=...），所以顺序其实不影响调用，
#   但保持顺序一致更易读。
@dataclass
class Document:
    """一条可检索的最小单元。"""

    # 【这行在干什么】声明第 1 个字段 doc_id，类型是字符串。
    # 【为什么这么写】它是文档的唯一编号，格式为「表名:主键:块序号」，
    #   例如 bidding_notices:123:0。
    # 【为什么必须长这样（关键设计）】因为建库可能被反复重跑。只要编号是「可复现的」，
    #   同一行的同一块在每次重跑时都会得到同一个编号，下游就能用它做「覆盖更新」而不是
    #   「重复插入」。这叫做幂等（重复执行结果一致）。若编号不可复现，重跑一次库里就会
    #   多出一整套重复数据，检索结果会重复、排序被扰乱。
    # 【注意事项】doc_id 的字符串本身不能直接当向量库的 ID 用：向量库只接受数字或
    #   UUID，所以下游 vector_store.py 会把它映射成确定性的 UUID（同样输入得到同样输出）。
    doc_id: str  # 形如 bidding_notices:123:0（表:主键:块序号），保证重跑幂等
    # 【这行在干什么】声明第 2 个字段 table：这条文档来自哪张数据库表。
    # 【为什么这么写】检索命中后，前端需要展示「数据来自哪张表」，也便于按表过滤。
    table: str
    # 【这行在干什么】声明第 3 个字段 label：表的中文展示名，例如「招标公告」。
    # 【为什么这么写】前端要显示中文名，如果让前端自己维护「英文表名 → 中文名」的映射，
    #   一旦加表就要改前端代码。放在这里由后端统一给出，前端拿到的就是能直接显示的文字。
    label: str  # 表的中文展示名
    # 【这行在干什么】声明第 4 个字段 primary_key：该行记录的主键值。
    # 【为什么用 Any 而不是 str】主键可能是数字（如 123），也可能是字符串（如业务编号），
    #   类型不确定，所以用「任意类型」Any 兜住。
    # 【为什么需要它】前端拿到主键，才能精确定位到「到底是哪一条原始记录」。
    primary_key: Any
    # 【这行在干什么】声明第 5 个字段 chunk_index：这一块是本条记录的第几块，从 0 开始数。
    # 【为什么这么写】一条很长的记录会被切成多块，每块单独作为一个 Document 入库，
    #   所以需要记住块的顺序，前端才能显示「第 2/3 块」。
    # 【注意事项】从 0 开始是编程惯例（称为零基索引），展示给用户时要 +1。
    chunk_index: int
    # 【这行在干什么】声明第 6 个字段 chunk_total：本条记录一共被切成了几块。
    # 【为什么这么写】配合 chunk_index 使用，前端才能知道「这是 3 块里的第 1 块」，
    #   也便于判断内容是否被截断/是否完整。
    # 【注意事项】它至少是 1（哪怕没切块，也算「共 1 块」）。
    chunk_total: int
    # 【这行在干什么】声明第 7 个字段 text：真正参与检索的正文。
    # 【为什么它是本文件最重要的字段】下游会拿它去做两件事：①分词建关键词索引（BM25）；
    #   ②算成向量建语义索引。检索质量好不好，几乎全看这段文字写得好不好。
    text: str  # 参与稠密向量 + BM25 的正文
    # 【这行在干什么】声明第 8 个字段 payload（字典类型），默认值用 field(default_factory=dict) 生成。
    # 【为什么不直接写 payload: dict = {}（重要坑）】在 Python 里，写 = {} 会让「所有实例
    #   共用同一个字典」——这是初学者最容易踩的经典陷阱。因为默认值只在类定义时创建一次，
    #   之后所有 Document 都指向这同一个字典，改一个就全被改了。
    #   field(default_factory=dict) 的含义是：「每次新建实例时，请调用一次 dict() 现场造一个
    #   全新的空字典」。这样每个实例都有自己独立的一份。
    # 【注意事项】凡是默认值为「可变对象」（字典、列表、集合）的字段，都必须用 default_factory。
    payload: dict[str, Any] = field(default_factory=dict)


# 【这行在干什么】定义函数 render_row：把「一行数据」渲染成多行文字。
# 【为什么需要它】数据库给的是结构化的列和值，检索系统要的是自然语言文本，
#   这个函数就是那个「排版工人」。
# 【关于下面这种换行写参数】参数很多时，一行写完太长不好读，可以像这样换行排列，
#   Python 靠括号来判断语句没结束，所以换行不会出错。
def render_row(
    # 【这行在干什么】第 1 个参数 row：一行原始数据。
    # 【类型含义】dict[str, Any] 读作「键是字符串、值是任意类型」的字典。
    # 【举例】{"id": 123, "project_name": "某某市政道路工程", "budget": 1500000}
    row: dict[str, Any],
    # 【这行在干什么】第 2 个参数 columns：表结构里的列定义清单。
    # 【类型含义】是一个列表，列表里每个元素又是一个字典，字典里有 name（列名）、
    #   type（列类型）、comment（列注释，也就是数据库里给字段写的中文说明）。
    # 【举例】[{"name": "id", "type": "int", "comment": "编号"},
    #          {"name": "budget", "type": "decimal", "comment": "预算金额"}]
    # 【为什么需要它】①它决定字段的展示顺序；②用它识别二进制列并跳过；③用它取中文字段名。
    columns: list[dict[str, Any]],
    # 【这行在干什么】第 3 个参数 label：表的中文名，例如「招标公告」。
    # 【为什么需要它】渲染出的第一行是「【表名】记录ID：xxx」这种抬头，
    #   让每一段文字都自带「我来自哪张表」的溯源信息。
    label: str,
    # 【这行在干什么】第 4 个参数 primary_key：该行记录的主键值。
    # 【为什么需要它】抬头里要标出记录 ID，方便人工核对、也方便前端定位到具体记录。
    primary_key: Any,
# 【这行在干什么】参数列表结束，并声明「本函数返回一个字符串」。
# 【为什么标注返回值】让人和编辑器知道拿到的是一段文字；如果哪里写错、返回了别的类型，
#   编辑器能提前提示。
) -> str:
    """把一行记录渲染成「字段: 值」的多行文本。"""
    # 【这行在干什么】创建结果列表，并把「抬头行」作为第一个元素放进去。
    # 【为什么这么写】先放抬头，保证任何一段文字都带着溯源信息。
    #   f"..." 是「格式化字符串」：双引号前加字母 f 后，里面的 {变量名} 会自动被替换成
    #   变量的实际值。举例：label="招标公告"、primary_key=123 时，这行结果是
    #   【招标公告】记录ID：123
    lines = [f"【{label}】记录ID：{primary_key}"]
    # 【这行在干什么】按 columns 的顺序，一个字段一个字段地处理。
    # 【为什么按 columns 而不是按 row 的键顺序】columns 来自表结构，顺序固定；
    #   而 row 的键顺序不保证稳定。固定顺序能让「同样的数据每次生成同样的文字」，
    #   这对重跑建库时保持内容一致很重要。
    # 【注意事项】col 是循环变量，每一圈代表一个列定义字典。
    for col in columns:
        # 【这行在干什么】取出当前列的列名。
        # 【参数含义】col["name"] 是数据库里的真实列名，例如 "project_name"。
        # 【为什么用方括号取值】方括号表示「按键取值」，从字典里把 name 对应的值拿出来。
        name = col["name"]
        # 【这行在干什么】如果这一列的类型命中「二进制黑名单」，就跳过它、处理下一列。
        # 【为什么这么写】见 _SKIP_TYPES 处解释：二进制内容转文字只会产生乱码噪声。
        # 【参数含义】col.get("type") 用 get 而不是 col["type"]，是因为万一某个列定义里
        #   没带 type 这个键，col["type"] 会直接报错，而 get 会安静地返回 None，
        #   逻辑更稳。
        # 【注意事项】判断的是「类型名是否在集合里」，属于集合的成员判断，速度很快。
        if col.get("type") in _SKIP_TYPES:
            # 【这行在干什么】continue 表示「跳过本轮剩下的代码，直接进入下一圈循环」。
            # 【为什么这么写】相比写成一整块 if/else 嵌套，用 continue 提前跳出能让代码
            #   更扁平、更好读。效果是：这个字段完全不出现在生成的文字里。
            # 【注意事项】continue 只影响当前这一圈，不会终止整个循环。
            continue
        # 【这行在干什么】从这一行数据里，按列名取出对应的值。
        # 【为什么用 .get() 而不是 row[name]】同理：万一这行数据里缺了某个列（比如查询只
        #   选了部分字段），方括号取值会报错中断整个流程，而 get 会返回 None，
        #   让后面的空值判断去兜住。
        value = row.get(name)
        # 【这行在干什么】如果值是「空」（None 或空字符串），跳过这个字段。
        # 【为什么这么写】空值渲染出来只会得到「字段名: 」这样一行空壳，属于噪声：
        #   它既占长度（浪费模型输入预算），又会稀释语义（让向量把注意力分给无意义的符号）。
        # 【注意事项】这里只覆盖了 None 和 ""（完全空的字符串），
        #   像「全是空格」的情况由下面第 54 行再补一刀。
        if value is None or value == "":
            # 【这行在干什么】跳过该字段。
            # 【为什么这么写】理由同上：保持逻辑扁平、可读。
            continue
        # 【这行在干什么】把值强制转成字符串，并去掉首尾的空白字符。
        # 【为什么必须转字符串】值可能是数字、日期、金额小数（Decimal）等类型，
        #   而最终拼接的文本必须是字符串，否则拼接时会报错。
        # 【为什么加 .strip()】数据库里的文本字段经常带着多余的空格、换行，
        #   strip() 把首尾这些看不见的字符清掉，避免污染检索文本。
        text = str(value).strip()
        # 【这行在干什么】如果转成字符串并清理空白后变成了空字符串，也跳过。
        # 【为什么这么写】这是对上面空值判断的补充：value 可能原本是一堆空格
        #   （既不是 None 也不是 ""），经过 strip 后才变成空，此时同样应该跳过，
        #   否则又会产出一行空壳文字。
        if not text:
            # 【这行在干什么】跳过该字段。
            # 【为什么这么写】保持扁平、易读。
            continue
        # 【这行在干什么】决定这个字段在文字里用什么名字显示：优先用数据库的列注释，
        #   没有注释就退回英文列名。
        # 【为什么这么写（关键设计）】这正是「全程不写死任何业务字段名」的实现方式。
        #   字段的中文名来自数据库运行时读到的 COLUMN_COMMENT，所以：
        #   表结构或注释改了，重跑建库就会自动适配，不用改一行代码。
        # 【参数含义】col.get("comment") 取列注释（可能不存在或为空串）；
        #   `A or B` 是 Python 的常用写法：当 A 是「假值」（None、空串等都算假）时，
        #   整个表达式取 B。所以这行的意思是「注释有内容就用注释，否则用列名」。
        field_label = col.get("comment") or name
        # 【这行在干什么】把「字段显示名: 值」追加到结果列表里。
        # 【为什么用 append 而不是用字符串相加】Python 的字符串是「不可变的」，
        #   每次相加都要重新复制一整遍旧内容，字段一多就会越拼越慢；
        #   先往列表里追加、最后一次性拼接（第 58 行）效率高得多。
        lines.append(f"{field_label}: {text}")
    # 【这行在干什么】把列表里的所有行，用一个换行符连接成一整段文本并返回。
    # 【参数含义】"\n" 是换行符（在 Python 字符串里，一对引号中的 \n 表示「换行」）；
    #   .join(列表) 的用法是「用前面的字符串，把列表元素依次粘起来」。
    # 【为什么用换行分隔】分行既方便人阅读，也让后面切块时不容易把两个字段从中间粘在一起。
    # 【注意事项】join 的调用者是「分隔符」，不是列表——写成 "\n".join(lines) 而不是
    #   lines.join("\n")，这个顺序初学者最容易写反。
    return "\n".join(lines)


# 【这行在干什么】定义函数 split_text：把长文本按「滑动窗口」切成多块。
# 【为什么需要它】向量模型把一整段文字压成一个向量，如果一段有 5000 字，各种主题
#   会被糊在一起，检索时很难精确匹配用户的细粒度问题；切成小块后，每块的语义更集中，
#   检索更准。
# 【通俗解释「滑动窗口切块」】想象把一句很长的句子拿去复印：第一次复印第 1~500 个字，
#   第二次不从头开始，而是从第 421 个字开始复印到第 920 个字……这样相邻两张纸之间有
#   80 个字是重复的（重叠区），句子即使正好跨越边界，也不会两边都读不全。
# 【参数含义】text=待切分的文本；chunk_size=每块最多的字符数；overlap=相邻两块重叠的字符数。
def split_text(text: str, chunk_size: int, overlap: int) -> list[str]:
    """按字符滑窗切块；文本不长时原样返回单块。"""
    # 【这行在干什么】两种情况直接返回原文（不切块）：
    #   ① chunk_size <= 0（块大小配成了 0 或负数，属于非法配置）；
    #   ② len(text) <= chunk_size（原文本来就装得下一块）。
    # 【为什么必须写这个判断】如果 chunk_size 是 0 或负数，下面的步长计算会得出 0，
    #   而后面按 0 步长推进的循环会「原地打转」永不结束（死循环），程序就卡死了。
    #   所以这里先做防御性拦截。
    # 【参数含义】chunk_size=每块字符数上限；len(text)=文本的字符个数。
    if chunk_size <= 0 or len(text) <= chunk_size:
        # 【这行在干什么】返回一个「只装着原文」的列表。
        # 【为什么包成列表】让调用方无论切没切块，拿到的都是「一个列表」，
        #   不必写两套处理逻辑去区分「是单块还是多块」。
        return [text]
    # 【这行在干什么】计算滑动步长，也就是「下一个窗口从第几个字符开始」。
    # 【通俗解释】步长 = 每块长度 − 重叠长度。例如每块 500 字、重叠 80 字，
    #   步长就是 420：第 1 块从 0 开始，第 2 块从 420 开始，于是 420~500 这段
    #   在两块里都出现，形成了 80 字的「重叠区」。
    # 【为什么要 max(1, ...)】如果重叠长度被配得大于等于块长度（例如块 500、重叠 600），
    #   步长会算成 0 或负数，循环就会原地卡死。max(1, x) 的意思是「取 x 和 1 里较大的那个」，
    #   保证步长至少是 1，程序永远不会卡死。
    # 【为什么要 max(0, overlap)】负数的重叠没有物理意义，统一当作 0 处理，
    #   避免「负重叠」意外把步长撑得比块还大、从而漏掉内容。
    step = max(1, chunk_size - max(0, overlap))
    # 【这行在干什么】准备一个空列表，用来装切好的每一块。
    # 【为什么先收集再返回】最后需要判断「是不是一块都没切出来」这个极端情况（第 73 行），
    #   先攒在列表里更方便。
    # 【类型标注解释】chunks: list[str] 是在声明「这个变量是一个装字符串的列表」。
    chunks: list[str] = []
    # 【这行在干什么】按步长在文本上滑动取窗口。
    # 【参数含义】range(起点, 终点, 步长) 会依次产出：0、step、2*step、3*step……
    #   直到接近文本末尾为止。也就是说 start 会依次等于每个窗口的起始下标。
    # 【通俗解释】下标可以理解为「第几个字符」，第一个字符的下标是 0（编程从 0 数起）。
    for start in range(0, len(text), step):
        # 【这行在干什么】切片：从 start 位置开始，往后取最多 chunk_size 个字符，得到这一块。
        # 【通俗解释】切片 text[a:b] 是「左闭右开」区间：包含第 a 个字符，不包含第 b 个字符。
        #   例如 text[0:5] 得到的是前 5 个字符（下标 0、1、2、3、4）。
        # 【为什么不用额外判断越界】Python 的切片自带保护：如果右边界超过了文本长度，
        #   它会自动截到末尾，不会报错。所以最后一圈很安全。
        piece = text[start : start + chunk_size]
        # 【这行在干什么】只有当这一块「去掉空白后还有内容」时，才把它收进结果。
        # 【为什么这么写】窗口滑到末尾时，可能切出一段全是空白或换行的尾巴；
        #   这种内容存进向量库没有任何检索价值，只是噪声，直接丢掉。
        if piece.strip():
            # 【这行在干什么】把这一块加入结果列表。
            # 【参数含义】piece=这一个窗口切出来的文本片段。
            chunks.append(piece)
        # 【这行在干什么】判断「这一块已经覆盖到文本末尾」，是的话就结束循环。
        # 【参数含义】start + chunk_size 是本块的右边界；len(text) 是文本总长度。
        # 【为什么需要这个 break】没有它，range 还会继续往后推进，切出重复的空白尾巴，
        #   白白浪费计算；加了这个判断，读到最后一块就干净利落地收工。
        if start + chunk_size >= len(text):
            # 【这行在干什么】提前跳出整个循环。
            # 【为什么这么写】已到达文本末尾，不会再有新内容了。
            break
    # 【这行在干什么】返回切好的块；如果一块都没有（极端情况：全文都是空白字符），
    #   就把原文当作唯一一块返回。
    # 【为什么用 `chunks or [text]`】这是 Python 的常用简写：or 会在左边是「假值」
    #   （空列表也算假）时返回右边。于是「有块就用块，没块就退回原文单块」。
    # 【为什么必须保证非空】让调用方永远至少拿到一块，下游就不会出现「一条记录产出零个
    #   文档」这种诡异情况，省去一堆边界判断。
    return chunks or [text]


# 【这行在干什么】定义内部函数 _truncate_fields：给一行数据做一份「超长值已被截断」的副本。
# 【为什么需要它】payload 里要存原始字段给前端看，如果某字段长达几万字，payload 会极其
#   臃肿，拖慢建库写入和查询传输，所以写入前先截断。
# 【函数名为什么以下划线开头】这是 Python 的约定：下划线开头表示「供本模块内部使用」，
#   提醒外部代码别依赖它（它可能随时改）。它并不阻止外部调用，只是「君子协定」。
# 【参数含义】row=一行的原始数据字典。
def _truncate_fields(row: dict[str, Any]) -> dict[str, Any]:
    # 【这行在干什么】准备一个空字典，用来装处理后的结果。
    # 【为什么新建而不是直接改 row】如果就地修改传入的 row，会影响调用方的数据（这叫
    #   「副作用」）。调用方后面可能还要用原始值，所以这里复制出一份新的来改。
    out: dict[str, Any] = {}
    # 【这行在干什么】遍历这一行里的所有「键和值」。
    # 【专业词解释：元组解包】字典的 .items() 每次会吐出一个「键值对」，形式是 (键, 值)
    #   这样两个元素打包在一起的东西（叫元组）。写成 `for key, value in ...` 时，
    #   Python 会自动把这两个元素分别装进 key 和 value 里，这个过程就叫「解包」。
    #   举例：如果某一项是 ("项目名称", "某某工程")，那 key 就是 "项目名称"，
    #   value 就是 "某某工程"。
    for key, value in row.items():
        # 【这行在干什么】判断两个条件是否同时成立：①这个值是字符串；②它的长度超过 4000 字符。
        # 【参数含义】isinstance(value, str) 是「类型判断」，问「value 是不是字符串」；
        #   len(value) 是字符个数；_FIELD_TEXT_LIMIT 就是上面那个 4000。
        # 【为什么只处理字符串】数字、日期、短文本本来就不长，也不该被改动，
        #   只对可能很长的文本字段做截断，尽量少动原始数据。
        if isinstance(value, str) and len(value) > _FIELD_TEXT_LIMIT:
            # 【这行在干什么】只保留前 4000 个字符，并在末尾加上「…（已截断）」标记。
            # 【参数含义】value[:_FIELD_TEXT_LIMIT] 是切片，取从开头到第 4000 个字符的内容；
            #   后面的 + "…（已截断）" 是字符串拼接。
            # 【为什么加标记】让人一看就知道「这里内容不完整」，避免误以为原文只有这么长。
            # 【注意事项】截断是硬切，可能正好切在一个词或一句话中间，
            #   所以展示给用户的原文会有「断头」现象，这是已知取舍。
            out[key] = value[:_FIELD_TEXT_LIMIT] + "…（已截断）"
        # 【这行在干什么】否则（不是字符串，或者长度没超标），原样存入。
        # 【为什么这么写】没超长就完全不动它，最大程度保留数据真实性。
        else:
            # 【这行在干什么】把原值放进结果字典。
            # 【为什么这么写】保证每个字段都不会被丢掉——哪怕值恰好是 None，
            #   也照样带过去，让前端能区分「字段存在但为空」和「字段不存在」。
            out[key] = value
    # 【这行在干什么】返回处理好的新字典。
    # 【为什么返回新字典】如上所述，入参 row 保持原样，调用方逻辑不受影响。
    return out


# 【这行在干什么】定义本文件的核心函数 build_documents：把 MySQL 的行「流水线式」地
#   变成一个个 Document。
# 【为什么它是核心】它是这条流水线的总装线，串起了「定主键 → 渲染文字 → 需要就切块 →
#   打上唯一编号 → 产出文档」全过程。
# 【参数含义】见下面逐行说明。
def build_documents(
    # 【这行在干什么】第 1 个参数 rows：从数据库逐行读取数据的「迭代器」。
    # 【为什么用迭代器，而不是一次读成列表（重要）】这个项目的数据表可能有几万甚至几十万行。
    #   如果一次性全读进内存，内存会被撑爆；迭代器的特点是「你要一行，我读一行」，
    #   内存占用恒定，无论表多大都很稳。
    # 【通俗解释「迭代器」】像饮水机：拧一下出一杯，而不是先把整桶水倒进所有杯子。
    # 【注意事项】迭代器只能往前走、不能回头，读过的行无法再读第二遍（若真的需要重读，
    #   得重新创建一个迭代器）。
    rows: Iterator[dict[str, Any]],
    # 【这行在干什么】第 2 个参数 columns：列定义清单（列名 / 类型 / 中文注释 / 顺序）。
    # 【为什么需要它】字段顺序、要跳过哪些类型、字段的中文名，全部从这里来。
    columns: list[dict[str, Any]],
    # 【这行在干什么】第 3 个参数 table：来源表的英文表名，例如 "bidding_notices"。
    # 【为什么需要它】要写进 doc_id 和 payload，供检索时区分数据来源。
    table: str,
    # 【这行在干什么】第 4 个参数 label：表的中心展示名，例如「招标公告」。
    # 【为什么需要它】写进正文抬头和 payload，前端拿到后可以直接显示，无需再查映射表。
    label: str,
    # 【这行在干什么】第 5 个参数 settings：配置对象，里面装着切块相关的三个阈值。
    # 【为什么需要它】MAX_DOC_CHARS / CHUNK_SIZE / CHUNK_OVERLAP 都来自 .env，
    #   集中传进来，代码里不出现写死的数字，方便调优。
    # 【注意事项】本文件只用到其中三个属性：max_doc_chars、chunk_size、chunk_overlap。
    settings: Settings,
    # 【这行在干什么】第 6 个参数 primary_key_column：主键的列名，默认值是 None。
    # 【为什么给默认值 None】有些表可能没有主键，或者调用方一时拿不到主键列名。
    #   给了默认值，这种「残缺」情况下函数依然能跑（退化成用行号当编号，见第 98 行）。
    # 【类型含义】str | None 读作「字符串，或者空（None）」。
    primary_key_column: str | None = None,
# 【这行在干什么】参数结束，声明本函数返回「一个能逐个吐出 Document 的迭代器」。
# 【为什么返回类型是 Iterator[Document] 而不是 list[Document]（关键）】因为函数体里用了
#   yield（见第 112 行），这使得它变成一个「生成器函数」：调用它不会立刻算完所有文档，
#   而是返回一个「随用随产」的对象。这让上面第 1 个参数的「流式处理」能真正落地——
#   读一行、产一块、交一块，全程内存占用恒定。
) -> Iterator[Document]:
    """逐行生成文档（行内容过长时会产生多块）。"""
    # 【这行在干什么】逐行遍历数据，同时拿到「第几行」和「这一行内容」。
    # 【专业词解释：enumerate】它会把迭代器里的每一项包成「(序号, 内容)」再吐出来，
    #   这样一次循环就能同时得到位置和数据，不用自己维护计数器。
    # 【参数含义】index=行序号，从 0 开始；row=这一行的数据字典。
    # 【为什么需要 index】当表没有主键时，它会作为「行号兜底」的编号基础（第 98 行）。
    for index, row in enumerate(rows):
        # 【这行在干什么】如果配置了主键列名，就从这一行里取出主键值；否则取 None。
        # 【专业词解释：三元表达式】`A if 条件 else B` 读作「条件成立就取 A，否则取 B」。
        #   这里等价于：primary_key_column 有值时执行 row.get(...)，为 None 时取 None。
        # 【为什么用 row.get(...) 而不是 row[...]】同理，避免这一行缺少该列时直接报错。
        pk = row.get(primary_key_column) if primary_key_column else None
        # 【这行在干什么】如果主键没取到（None），或者是空字符串，就用「行号 + 1」顶替。
        # 【为什么必须兜底（重要）】主键是生成 doc_id 的依据。如果让它保持为空，
        #   doc_id 会变成「表名::块号」这种缺少中段的形式，导致同一张表里所有行互相覆盖，
        #   数据会大面积丢失。宁可编号不完美，也绝不能让它是空的。
        # 【为什么 +1】行号从 0 开始，加 1 之后从 1 开始，更符合人的计数习惯，
        #   也让生成的编号看起来更像「第 1 条记录」。
        if pk is None or pk == "":
            # 【这行在干什么】把兜底的编号赋给 pk。
            # 【为什么这么做】保证后面拼 doc_id 时永远有值可用。
            pk = index + 1

        # 【这行在干什么】把这一行的数据渲染成「字段: 值」的多行文字。
        # 【参数含义】row=原始行数据；columns=列定义；label=中文表名；pk=上面确定的记录编号。
        # 【为什么先渲染再判断空】因为「这行有没有有效内容」必须看渲染结果才知道——
        #   如果所有字段都是空的，渲染出来就只剩一个抬头，属于无意义数据。
        body = render_row(row, columns, label, pk)
        # 【这行在干什么】如果渲染结果去掉空白后是空的，就跳过这一行。
        # 【为什么这么写】空文档放进检索库毫无价值，还会占空间、拉低检索质量；
        #   提前丢掉最省事。
        # 【注意事项】如果整行字段都为空，渲染结果其实还剩一行「【表名】记录ID：x」抬头，
        #   它不算空，所以这一行不会被丢掉——也就是说「完全为空的行」极少被跳过，
        #   这个判断真正拦截的是渲染结果只有空白字符的极端情况。
        if not body.strip():
            # 【这行在干什么】跳过这一行，直接处理下一行。
            # 【为什么这么写】continue 让「被跳过的行」不产出任何文档，
            #   保持逻辑扁平（原因同前）。
            continue

        # 短记录不切块；长记录才走滑窗切分
        # 【这行在干什么】判断渲染后的文字长度是否不超过配置的阈值 max_doc_chars（.env 默认 1200）。
        # 【为什么这么写】短记录本身就是一个完整的语义单元，硬切成几块反而会把上下文割裂，
        #   导致检索时「问的是一件事，命中的却是半句话」。只有超长记录才值得切。
        # 【参数含义】settings.max_doc_chars=单条记录允许作为一整块的最大字符数；len(body)=实际字符数。
        if len(body) <= settings.max_doc_chars:
            # 【这行在干什么】不切块，把整条文字当作「唯一的一块」。
            # 【为什么还要包成列表 [body]】因为下面第 111 行会统一用「遍历每一块」的方式处理；
            #   这里保持同样的数据结构，后面就不用写 if/else 两套分支，代码更短、更不易错。
            chunks = [body]
        # 【这行在干什么】否则（文字超长）就走滑窗切分。
        # 【为什么这么写】超长文字必须切，否则语义被稀释、检索精度下降，
        #   而且可能超出模型能处理的最大长度。
        else:
            # 【这行在干什么】调用切块函数，按配置的「每块大小」和「重叠长度」来切。
            # 【参数含义】settings.chunk_size=每块最大字符数（默认 500）；
            #   settings.chunk_overlap=相邻块重叠字符数（默认 80）。
            # 【为什么用配置值而不是写死数字】调优时只改 .env、重启服务即可，代码不动。
            chunks = split_text(body, settings.chunk_size, settings.chunk_overlap)

        # 【这行在干什么】给这一行的原始字段做截断处理，得到用于 payload 的字段副本。
        # 【为什么容易混淆，要特别注意】它处理的是「原始 row」，而上面的 body 是
        #   「渲染后的文字」。两者是不同的数据，用途也不同：
        #     - body / chunk：给检索用（算向量、建关键词索引）；
        #     - payload_fields：给前端展示原文用（结构化字段，方便排版成表格）。
        #   所以截断只影响展示，不会让检索内容变少。
        payload_fields = _truncate_fields(row)
        # 【这行在干什么】遍历切好的每一块，同时拿到「块序号」。
        # 【参数含义】i=块序号（从 0 开始）；chunk=这一块的文字内容。
        # 【为什么一条记录要产出多个 Document】因为每一块都作为独立的一条数据入库，
        #   检索时才可能精确命中「正好包含答案的那一块」。
        for i, chunk in enumerate(chunks):
            # 【这行在干什么】产出一个 Document 对象（yield），交给调用方。
            # 【专业词解释：yield 与生成器（本文件最关键的概念之一）】
            #   - 普通函数用 return 返回结果，一返回函数就结束，且结果必须一次性算完。
            #   - 用了 yield 的函数会变成「生成器函数」：每执行到 yield 就「交出」一个值，
            #     然后函数暂停在那里，等调用方下次来取时，再从暂停处继续往下跑。
            #   - 通俗类比：普通函数像「一次性炒完一整桌菜再端出去」；
            #     yield 像回转寿司——做一盘、送一盘，客人边吃厨房边做。
            #   - 好处（为什么这么写）：几十万行的表，可以做到「内存里同时只有一两块」，
            #     内存占用恒定；如果改成 return 一个大列表，所有块都得先堆在内存里，会爆。
            #   - 注意事项：因为函数被 yield「暂停」了，调用方不把生成器取完，
            #     后面的代码就永远不执行；另外生成器只能从头到尾走一遍，不能回退。
            yield Document(
                # 【这行在干什么】拼出这条文档的唯一编号，格式是「表名:主键:块序号」。
                # 【为什么是这个组合】这三段合起来能唯一确定「某张表的某条记录的第几块」。
                #   又因为它是「可复现」的（同样的数据永远算出同样的编号），
                #   所以重跑建库时，同一块会拿到同一个编号，下游就能做「覆盖更新」而不是
                #   「重复插入」——这就是幂等的来源。
                # 【通俗类比】像快递单号：同一个包裹重发一次，单号不变，系统就知道是同一个包裹，
                #   会更新它而不是再堆一个。
                # 【参数含义】table=表名；pk=主键值；i=块序号（从 0 开始）。
                doc_id=f"{table}:{pk}:{i}",
                # 【这行在干什么】把来源表名写进 Document。
                # 【为什么需要】检索命中后前端要显示「数据来自哪张表」。
                table=table,
                # 【这行在干什么】把中文展示名写进 Document。
                # 【为什么需要】前端可以直接显示中文，不必自己维护表名映射。
                label=label,
                # 【这行在干什么】把记录编号写进 Document。
                # 【为什么需要】让前端/后续查询能精确定位到原始的那一条记录。
                primary_key=pk,
                # 【这行在干什么】写进块序号。
                # 【为什么需要】前端可据此显示「第 i+1 块」，也能按块顺序还原长文本。
                # 【注意事项】这里存的是从 0 开始的序号，展示给用户时要 +1。
                chunk_index=i,
                # 【这行在干什么】写进这条记录总共被切成了几块。
                # 【为什么需要】前端据此显示「共 N 块」，判断内容是否完整。
                # 【注意事项】这个值在每一圈循环里都会重新算一次（虽然结果相同），
                #   属于轻微重复计算，但代码更直观，可忽略。
                chunk_total=len(chunks),
                # 【这行在干什么】把这一块的正文交给 Document.text。
                # 【为什么这是最重要的字段】它就是要写进向量库、参与检索的内容，
                #   直接决定检索质量。
                text=chunk,
                # 【这行在干什么】组装随正文一起存入向量库的附加信息 payload。
                # 【专业词解释：payload】可以理解成「随身行李」——正文是用来算相似度的，
                #   而展示「命中的原文」需要结构化的字段，所以把表名、中文名、主键、
                #   块信息、原始字段都打包一起带上。检索命中时，这些东西能原样取回来，
                #   前端就能排版出「来源卡片」。
                payload={
                    # 【这行在干什么】把表名放进 payload。
                    # 【为什么需要】检索结果里也要能拿到来源表，便于展示和按表过滤。
                    "table": table,
                    # 【这行在干什么】把中文表名放进 payload。
                    # 【为什么需要】前端展示友好名称，不需要再做一次映射。
                    "label": label,
                    # 【这行在干什么】把记录编号放进 payload。
                    # 【为什么需要】前端据此定位、关联到原始记录。
                    "primary_key": pk,
                    # 【这行在干什么】把块序号放进 payload。
                    # 【为什么需要】同一条记录会被切成多块，结果里要能区分是哪一块。
                    "chunk_index": i,
                    # 【这行在干什么】把总块数放进 payload。
                    # 【为什么需要】前端可提示「共 N 块」，让用户知道内容是否被切分过。
                    "chunk_total": len(chunks),
                    # 【这行在干什么】把（已截断的）原始字段整体放进 payload。
                    # 【为什么需要】这就是前端「来源卡」上展示的原文。保留结构化字段
                    #   （而不是只给一段拼接好的文字）的好处是：前端可以按字段名排版成表格，
                    #   用户对照起来更清楚。
                    # 【注意事项】这里存的是「截断后的副本」，超长字段会有「…（已截断）」标记；
                    #   它不影响 text 正文，所以调整截断阈值不会改变检索结果。
                    "fields": payload_fields,
                },
            )