# ============================================================================
# 文件：embeddings.py —— 把「文字」变成「一串数字（向量）」的翻译官
#
# 【这个文件在整个项目里是干什么的】
#   计算机看不懂中文，但它很擅长算数字。所谓「语义检索」（也叫向量检索）的核心思路是：
#   把一段文字交给一个「模型」，模型吐出几百个小数，组成一个数组（例如 512 个浮点数），
#   这个数组就叫「向量」。关键特性是：意思越接近的两段文字，它们的向量在数学上也越接近。
#   这样用户问「市政道路的招标」，即使某篇公告里写的是「城市道路工程」，两者向量也很接近，
#   于是也能被检索出来 —— 这就是它比关键词检索更强的地方。
#
# 【两路召回里的哪一路】
#   项目里检索是「两路并发」的：
#     ① 本文件负责的「稠密向量检索」（语义）—— 擅长理解意思；
#     ② bm25.py 负责的「稀疏向量检索」（关键词）—— 擅长精确的词，如公司名、编号。
#   两路结果最后由 retriever.py 用 RRF 融合，再交给大模型作答。
#
# 【谁调用它（上游）】
#   backend/app/ingest.py    —— 建库时：把每篇文档的正文批量转成向量，写进 Qdrant。
#   backend/app/retriever.py —— 检索时：把用户的问题转成向量，拿去 Qdrant 里找相近的。
#
# 【它给谁用（下游）】
#   backend/app/vector_store.py —— 把这里算出的向量存进/查出向量数据库 Qdrant。
#
# 【需要先懂的三个概念（大白话）】
#   1) 什么是「向量」：就是一串小数，比如 [0.12, -0.05, 0.88, ...]。
#      可以把它想象成「一个点在几百维空间里的坐标」。意思相近的文字，坐标靠得近。
#   2) 什么是「维度（dim）」：这一串小数有几个数字。本模型固定 512 个，
#      所以叫「512 维」。维度是硬性契约：模型吐出来的、数据库里存的、查询时用的，
#      必须全部是同一个数字，否则整库作废（下面 _check_dim 就是守这个门的）。
#   3) 什么是「懒加载（lazy）」：模型文件很大（几十上百 MB），加载它要花时间。
#      如果服务一启动就加载，启动会变慢，而且很多请求根本用不到它。所以这里设计成
#      「第一次真正要用时才加载」，加载完就常驻内存，后面反复用同一份（见 Embedder.model）。
#
# 【本文件的代码为什么写得有点绕（重要）】
#   下面会看到「连续两次 if self._model is None」这种看着冗余的写法，还有一把锁 _lock。
#   这不是新手笔误，而是为了「多线程安全 + 只加载一次」刻意写的，注释里会逐行说明。
#   简单说：多个请求可能同时进来，如果不管，模型会被重复加载好几份，白吃内存还可能崩。
# ============================================================================
# 【下面是本文件原有的「模块说明」（docstring，即模块文档字符串）】
# 【它是什么】三引号包起来的一段文字，Python 会把它当作本模块的「官方自我介绍」，
#   别人用 help(app.embeddings) 或看文档时就能读到它。
#   注释（以 # 开头）和它不一样：注释是给读代码的人看的随手笔记，docstring 是「正式档案」。
# 【为什么把它放在这里】按 Python 规则，docstring 必须是模块里的第一条「语句」；
#   上面那一大段是注释（注释不算语句），所以放在它前面完全没问题，不影响它继续当模块说明。
"""fastembed 稠密向量封装。

模型默认 ``BAAI/bge-small-zh-v1.5``（512 维），fastembed 内部走 ONNX Runtime，
不需要 PyTorch，模型首次使用时自动下载并缓存到本地。

bge 系列中文模型建议只给「查询」加检索指令前缀，文档侧不加，
这一点通过 ``EMBED_QUERY_PREFIX`` 控制，置空即可关闭。
"""

# 【这行在干什么】打开「类型注解延迟求值」开关。
# 【为什么这么写】本文件用了 list[str]、list[list[float]]、Embedder | None 这类新式写法。
#   老版本 Python（3.8/3.9）不认 list[str] 和竖线 |，会直接报错；加上这行后，
#   这些标注会被当作字符串先存着、真正需要时才解析，于是老版本也能跑。
# 【注意事项】必须放在文件最顶部（所有执行代码之前），这是 Python 的硬性要求。
from __future__ import annotations

# 【这行在干什么】引入 threading 模块，本文件只用到它里面的 Lock（线程锁）。
# 【为什么需要】模型是「全局共享」的一份资源，多个请求线程可能同时第一次来加载它。
#   用一把锁把加载动作围起来，保证同一时刻只有一个线程在加载，其它线程在外等候，
#   进来时发现已经加载好了就直接用。这是「延迟初始化 + 线程安全」的标准做法。
# 【专业词解释：线程】可以把一个进程想象成一个厨房，线程就是厨房里的多个厨师，
#   他们同时干活、共享同一个冰箱（内存）。如果两个厨师同时开冰箱拿同一份食材，
#   就可能出乱子 —— 锁的作用就是「谁拿了钥匙谁才能进冰箱，别人排队等」。
import threading

# 【这行在干什么】从同目录的 config 模块引入两个东西：Settings（配置类）和 get_settings（取配置的函数）。
# 【为什么这么写】模型名、向量维度、批量大小、查询前缀这些参数全部来自 .env 配置文件，
#   代码里一律不写死。这样调参只需改配置并重启服务，不用改代码。
#   - Settings      —— 配置的「类型」（相当于一张表格的模板，告诉你有哪些字段）；
#   - get_settings  —— 真正去读取 .env 并生成配置对象的函数（带缓存，反复调用不会重复读盘）。
# 【注意事项】开头的点「.」表示「同一个包（同一个文件夹）里的模块」，
#   所以本文件必须作为 app 包的一部分被导入，不能脱离项目单独跑。
from .config import Settings, get_settings


# 【这行在干什么】定义一个自定义异常类 EmbeddingError，它继承自 Python 内置的 RuntimeError。
# 【为什么需要自定义异常】①名字自带含义：看到 EmbeddingError 就知道「是向量化这一环出问题了」，
#   比看到一个笼统的 RuntimeError 好定位；②上层（main.py 的接口）可以专门捕获它，
#   给用户回一句人能看懂的话（例如「向量维度不匹配，请修正配置后重建知识库」），
#   而不是把一大段程序崩溃栈直接甩给用户。
# 【专业词解释：异常】程序运行中出的「岔子」。raise 是「主动抛出岔子」，
#   而 except/try 是「提前准备好接住岔子的网」。
# 【专业词解释：继承 / RuntimeError】括号里写 RuntimeError 表示「本异常是一种运行时错误」，
#   这样即使上层只写 except RuntimeError，也照样能接住它（子类能被父类的网兜住）。
class EmbeddingError(RuntimeError):
    """向量化过程中的可读错误。"""


# 【这行在干什么】定义 Embedder 类：它是「向量模型」的一层包装（外壳）。
# 【为什么不直接用 fastembed 的模型对象】因为我们需要额外做三件事：
#   ① 延迟加载（用时才加载）并且保证线程安全；② 统一做「查询要不要加前缀」这层处理；
#   ③ 统一做「维度自检」。把这些收在一个类里，调用方就不用操心这些细节。
# 【每个 Embedder 对象身上带着什么】三个属性：_settings（配置）、
#   _model（真正干活的那个模型，一开始是 None，表示还没加载）、_lock（线程锁）。
class Embedder:
    """懒加载的向量模型包装器（模型加载较慢，只在首次使用时初始化）。"""

    # 【这行在干什么】构造函数：创建 Embedder 实例时，先准备好上面说的三个属性。
    # 【参数解释】settings=配置对象，由调用方传进来（而不是在这里自己去读 .env）。
    # 【为什么要把 settings 当参数传进来（重要设计）】这叫「依赖注入」——
    #   通俗说就是「你需要什么东西，我从外面递给你，而不是你自己去仓库里拿」。
    #   好处：测试时可以塞一份「假的配置」进来，不必真的去读 .env、不必真的下载模型，
    #   代码更好测、也更容易复用（换一份配置就能跑另一套参数）。
    # 【返回值为 -> None 是什么意思】表示这个函数不返回任何值，它只负责把对象初始化好。
    def __init__(self, settings: Settings) -> None:
        # 【这行在干什么】把外面递进来的配置存到对象自己身上。
        # 【为什么加 self.】不加 self. 的话 settings 只是个局部变量，函数一结束就消失了；
        #   加上 self. 后它变成「实例属性」，本对象的其它所有方法（如 embed_documents）
        #   都能随时取用。
        self._settings = settings
        # 【这行在干什么】把「模型」占位为 None（空），表示「现在还没加载」。
        # 【为什么用 None 占位而不马上加载】这就是「懒加载」的核心：先摆一个空位子，
        #   等第一次真要用了再装进去（见下面的 model 属性）。好处是服务启动快、
        #   不用向量化功能时不浪费内存。
        # 【注意事项】判断「有没有加载过」的标准就是 self._model is None，
        #   所以第一句必须是 None，不能写成别的。
        self._model = None
        # 【这行在干什么】创建一把线程锁，存到对象上。
        # 【为什么需要】见文件头解释：防止多个线程同时去加载模型、把模型加载好几份。
        # 【参数解释】threading.Lock() 造出来的是一把最基础的「互斥锁」：
        #   同一时刻只允许一个线程持有它（with 语句进入时上锁、退出时自动解锁）。
        self._lock = threading.Lock()

    # 【这行在干什么】@property 把下面的 model 方法包装成「属性」。
    # 【通俗解释】用 @property 之后，调用方写 obj.model 就行，不用写 obj.model()。
    #   但它又不是一个死值 —— 每次读取这个属性，都会真的去执行下面的函数体。
    #   这样一来，「没加载就现场加载」这件事就被藏在了「读取一个属性」这么简单的动作背后。
    # 【为什么这么设计】调用方只需要 self.model 就能保证「拿到的一定是加载好的模型」，
    #   不用在每个用到的地方都写一遍 if 判断。
    # 【专业词解释：装饰器】就是写在函数上方、以 @ 开头的一行，作用是「给这个函数增强功能」。
    #   这里 @property 增强的效果是「让方法能像属性一样被读取」。
    @property
    def model(self):
        # 【这行在干什么】先「不正经地」看一眼：模型是不是已经加载好了？
        # 【为什么先在外面看一次（关键优化）】因为绝大多数调用都发生在「已经加载好」之后。
        #   如果在没加载的情况下都要去抢锁，那每次取模型都要排队，白白拖慢速度。
        #   所以这里先不加锁地快速瞄一眼：已经好了就直接返回，根本不进锁。
        #   这个技巧叫「双重检查锁定」。
        if self._model is None:
            # 【这行在干什么】加锁。只有走到这里（确认真的还没加载）才会去抢锁。
            # 【with ... 是什么意思】这是「上下文管理器」语法，大白话是：
            #   「进入这个代码块时自动上锁，离开这个代码块时自动解锁（哪怕中途报错也会解锁）」。
            #   相当于「拿着钥匙进门，出门时一定会把钥匙还回去」，不会因为意外把门锁死。
            # 【潜在风险】如果加载模型的过程非常慢（比如要下载几百 MB），
            #   这段时间里其它线程会全部卡在这里排队等待。这是刻意的取舍：
            #   短期排队换「模型只有一份」，总比每个线程都加载一份把内存撑爆要好。
            with self._lock:
                # 【这行在干什么】拿到锁之后再检查一次：模型是不是已经被别的线程加载好了？
                # 【为什么必须再查一次（这是精髓，别删）】设想两个线程 A、B 同时到达外层的 if，
                #   都发现 _model 是 None，于是都来抢锁。A 先抢到、把模型加载好、释放锁；
                #   此时 B 才拿到锁 —— 如果没有这第二次检查，B 会再把模型重新加载一遍，
                #   前面 A 白干了，而且 self._model 会被覆盖，浪费内存和时间。
                #   第二次检查让 B 一眼看到「A 已经装好了」，于是直接跳过加载。
                if self._model is None:
                    # 【这行在干什么】打开「接住任何岔子」的网，尝试加载模型。
                    # 【try 是什么意思】「请试着执行下面的代码；万一出岔子，就跳到 except 分支处理」。
                    #   try 和 except 必须成对出现，中间是「可能出错但我们要自己兜住」的代码。
                    try:
                        # 【这行在干什么】真正把 fastembed 库引入进来，取出其中的 TextEmbedding 类。
                        # 【为什么把 import 写在函数内部（重要）】
                        #   ① 首次 import fastembed 会连带加载 ONNX Runtime 等一大堆重东西，
                        #      放在文件顶部的话，任何模块只要 import 了本文件就被迫付出这份代价，
                        #      哪怕根本用不到向量功能；放在这里则只有真正要加载模型时才付出。
                        #   ② 与此配套，环境变量（HF_ENDPOINT 等）在配置阶段就已经设好——
                        #      因为本机直连 HuggingFace 会超时，必须在 import 之前就改好下载源。
                        #      延迟 import 正好让「先设环境变量、后 import」这个顺序得到保证。
                        from fastembed import TextEmbedding

                        # 【这行在干什么】用指定的模型名创建模型实例，并挂到 self._model 上。
                        # 【参数解释】model_name=self._settings.embed_model：
                        #   模型名来自 .env（默认 BAAI/bge-small-zh-v1.5，中文小模型、512 维）。
                        #   传什么名字就下载/加载什么模型，所以换模型只需改配置。
                        # 【首次使用会发生什么】本地没有该模型时会自动从网上下载并缓存到本地磁盘，
                        #   所以第一次调用会明显慢（可能几十秒到几分钟），之后就快了。
                        # 【潜在风险】如果网络不通、模型名写错、或依赖没装，这里会抛异常，
                        #   被下面的 except 接住并翻译成一句人话。
                        self._model = TextEmbedding(model_name=self._settings.embed_model)
                    # 【这行在干什么】接住 try 里抛出的任何异常，把它绑定到变量 exc 上。
                    # 【参数解释】as exc 表示「把捕获到的异常对象命名为 exc」，后面用它取原始报错信息。
                    # 【这行末尾的注释在说什么】它列出了这个 except 想覆盖的三种常见情况：
                    #   模型下载失败 / 模型名写错 / 依赖缺失，都是「环境问题」而不是「代码问题」。
                    except Exception as exc:  # 下载失败 / 模型名错误 / 依赖缺失
                        # 【这行在干什么】把原始异常「翻译」成一个更好懂的 EmbeddingError 抛出。
                        # 【为什么这么写】原始的报错往往是英文的一长串技术细节，
                        #   直接透传到接口层，用户看不懂也不知道怎么办。这里补上「是哪个模型加载失败了」
                        #   以及「原本的报错是什么」，报错信息立刻就变得可行动了。
                        # 【f"..." 是什么】格式化字符串，双引号前加字母 f 后，
                        #   里面的 {self._settings.embed_model} 和 {exc} 会被替换成实际内容。
                        # 【注意事项】这里必须用 raise 主动抛出，而不是 print 一句就算完——
                        #   否则加载失败了函数还会继续往下走，后面用到 None 的模型会报出更莫名其妙的错。
                        raise EmbeddingError(
                            f"加载向量模型 {self._settings.embed_model} 失败：{exc}"
                        ) from exc
                        # 【这行在干什么】上面 raise 语句结尾的 from exc 表示「新异常是由 exc 引起的」。
                        # 【为什么加 from】这样原始报错的完整脉络会被保留下来（叫「异常链」），
                        #   排查时既能看到我们写的这句人话，也能顺着看到最初到底谁报的错。
                        # 【为什么单独占一行】上面那句太长，拆成几行写更易读，
                        #   末尾的 from exc 属于 raise 语句的一部分，Python 允许这样换行。
        # 【这行在干什么】返回模型对象。
        # 【为什么写在 if 外面（关键）】因为无论「本来就加载好了」还是「刚刚才加载好」，
        #   最终都要把模型交出去。写在最外面就不用把 return 写两遍，逻辑更简单。
        # 【注意事项】执行到这里，self._model 一定不是 None（要么原本就有，要么刚装上，
        #   要么已经在 except 里抛异常提前结束了），所以调用方拿到的必然是可用模型。
        return self._model

    # 【这行在干什么】定义方法 embed_documents：把「一批文字」批量转成「一批向量」。
    # 【为什么叫 documents】这批文字在建库场景下就是一篇篇文档的正文，所以叫 documents。
    # 【参数解释】texts=字符串列表，例如 ["【招标公告】...", "【招标公告】..."]。
    # 【返回值】二维列表（列表套列表）：外层每个元素对应一段文字，内层是该文字的 512 个小数。
    #   举例：输入 3 段文字 → 返回 [[512个数], [512个数], [512个数]]。
    # 【为什么要「批量」而不是一次一段】向量计算在硬件上是「一次算一批更快」，
    #   而且模型的加载/调度开销能被摊薄。所以这里做成收一批、算一批。
    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        # 【这行在干什么】如果传进来的是空列表，直接返回空列表。
        # 【为什么这么写】①空输入直接返回可以省掉后面所有计算；②更重要的原因：
        #   某些模型在收到空列表时会报错或返回异常结果，这里提前挡掉，保证函数
        #   在任何输入下都返回「列表」这种统一类型，调用方不用额外判断。
        #   这叫「防御性编程」——把边界情况在入口就处理干净。
        if not texts:
            # 【这行在干什么】返回空的二维列表。
            # 【为什么返回 [] 而不是 None】保持返回类型一致，调用方可以放心地直接遍历它，
            #   不用先写 if result is not None。
            return []
        # 【这行在干什么】调用模型把一批文字算成向量，并顺手把每个数字统一转成 Python 的 float 类型。
        # 【为什么写成这种「列表推导式」】这是 Python 里「用一行写一个循环」的写法，
        #   下面这 4 行等价于：
        #       vectors = []
        #       for vec in self.model.embed(texts, batch_size=...):
        #           vectors.append([float(x) for x in vec])
        #   用列表推导式是为了紧凑易读，效果完全一样。
        # 【参数逐个解释】
        #   self.model  —— 触发上面的懒加载逻辑，保证拿到的是可用的模型对象；
        #   .embed(...) —— 模型提供的「批量向量化」方法，返回「一批向量」；
        #   texts       —— 要向量化的那批文字；
        #   batch_size=self._settings.embed_batch_size —— 告诉模型「内部一次处理多少段文字」。
        #     这个值来自 .env（EMBED_BATCH_SIZE）。它是个「内存与速度的平衡旋钮」：
        #     调大 → 每次算得多、更快，但瞬时吃内存更多（显存/内存小的机器可能被拖垮）；
        #     调小 → 更省内存但更慢、更碎。默认值是适配普通机器的折中值。
        # 【为什么要再套一层 float(x)】模型底层（ONNX Runtime）返回的数字可能是
        #   它自己的特殊数值类型，不是标准的 Python 小数。这里统一转成 float，
        #   是为了后面能被 JSON 序列化、能被 Qdrant 客户端接受、能参与普通的数学运算。
        # 【注意事项】转成 float 后精度可能从「超高精度」降到「标准双精度」，
        #   这对检索毫无影响（向量检索不怕这点误差），所以可以放心转。
        vectors = [
            [float(x) for x in vec]
            for vec in self.model.embed(texts, batch_size=self._settings.embed_batch_size)
        ]
        # 【这行在干什么】做一次「维度自检」，确保模型吐出来的数字个数和配置一致。
        # 【为什么必须检查】如果 .env 里写的 EMBED_DIM 是 512，但实际模型输出 768 维，
        #   那么建库时写进 Qdrant 的向量维度、和查询时用的维度就会对不上，
        #   Qdrant 会直接拒绝写入或查询报错，而且报错信息往往很难懂。
        #   在这里主动检查并给出明确提示，能省掉大量排查时间。
        # 【注意事项】这里只检查、不修改任何数据（详见 _check_dim）。
        self._check_dim(vectors)
        # 【这行在干什么】把算好的向量交回给调用方。
        # 【为什么放在最后】保证「交出去的一定是通过自检的合格数据」，
        #   不会让错误数据流到下游（Qdrant）才炸。
        return vectors

    # 【这行在干什么】定义方法 embed_query：把「用户的一个问题」转成「一个向量」。
    # 【为什么要单独写一个方法，而不是直接用 embed_documents】因为「查询侧」和「文档侧」
    #   的处理规则不一样 —— bge 系列中文模型的做法是：给「查询」加一句指令前缀，
    #   文档侧不加。原因见下面注释。所以查询必须走一条专属通道。
    # 【参数解释】question=用户原始问题文本，例如「最近有哪些市政道路类的招标公告？」
    # 【返回值】一个一维列表：512 个小数的向量（就是上面二维结果里的那一行）。
    # 【注意事项】如果问题为空，走下面的链路会返回空列表 []，调用方要能处理这种情况。
    def embed_query(self, question: str) -> list[float]:
        # 【这行在干什么】决定要不要给问题加「查询指令前缀」，并把结果存到 text。
        # 【为什么这么写（重要，别改）】bge 这类中文向量模型在训练时，是「拿一个问题去匹配一段文档」，
        #   训练数据里问题前面带了一句固定的提示（本项目的默认是「为这个句子生成表示以用于检索相关文章：」
        #   之类，具体以 .env 的 EMBED_QUERY_PREFIX 为准）。所以使用时也要照做，
        #   检索效果才和训练时一致。而文档侧从来不带这句提示，所以两边不能混用。
        # 【这行的读法（三元表达式）】`A if 条件 else B` 的意思是「条件成立就用 A，否则用 B」。
        #   这里就是：如果配置里有前缀，就把「前缀 + 问题」拼起来；没有前缀，就原样用问题。
        # 【参数解释】self._settings.embed_query_prefix 来自 .env（EMBED_QUERY_PREFIX），
        #   置空即关闭这个行为。
        # 【潜在风险】前缀改了必须重建知识库吗？—— 不需要。前缀只影响查询侧的输入文本，
        #   不改动库里的数据；但改了之后，查询与文档的「口径」最好保持一致，
        #   否则可能让检索效果变差，所以不建议随意改动。
        text = f"{self._settings.embed_query_prefix}{question}" if self._settings.embed_query_prefix else question
        # 【这行在干什么】把单个问题当成「只有一条的批次」丢给批量方法，拿到二维结果。
        # 【为什么绕这一下】复用 embed_documents 可以「一份代码两处用」，
        #   维度自检、空值处理、数值转换这些逻辑只写一遍，不会出现两条链路行为不一致。
        # 【注意事项】这里传入的是 [text]（外面套了方括号），表示「这是一个只含 1 条文字的列表」。
        vectors = self.embed_documents([text])
        # 【这行在干什么】从二维结果里取出第一条（也就是我们要的那一个向量）返回。
        # 【这行的读法（三元表达式）】如果 vectors 非空，就取 vectors[0]；否则返回空列表 []。
        # 【为什么还要判断空】理论上问题不为空时一定有结果，但万一上游传了空字符串，
        #   这里就可能拿到空结果。写上这个保护，可以避免 IndexError（取不存在的位置报的错）
        #   把整个请求搞崩 —— 属于低成本的防御性写法。
        # 【专业词解释：下标 [0]】表示「列表里的第 1 个元素」。编程里位置都从 0 开始数，
        #   所以第 1 个是 [0]、第 2 个是 [1]，这叫「零基索引」。
        return vectors[0] if vectors else []

    # 【这行在干什么】@property 装饰下面这个 dim 方法，让它能像属性一样被读取（写法是 embedder.dim）。
    # 【为什么需要它】别的地方（例如给 Qdrant 建集合时）需要知道「本模型是多少维」，
    #   有了这个属性，调用方写 embedder.dim 就能拿到，不用自己去翻配置文件。
    # 【注意事项】它返回的是「配置里声称的维度」，不是「模型实际吐出来的维度」。
    #   实际维度由 _check_dim 在真正算完向量后校验，两者必须一致。
    @property
    def dim(self) -> int:
        # 【这行在干什么】把配置里的向量维度返回出去。
        # 【参数解释】self._settings.embed_dim 来自 .env（EMBED_DIM，本项目是 512）。
        # 【为什么必须和模型真实维度一致】因为 Qdrant 的「集合（Collection）」在建的时候
        #   就要声明维度，之后写入/查询的向量必须严格等于这个维度，多一个少一个数字都不行。
        #   所以这个值实际上成了整个知识库的「契约」，改动它就意味着必须重建整套索引。
        return self._settings.embed_dim

    # 【这行在干什么】定义内部方法 _check_dim：校验一批向量里每个向量的长度是否等于配置维度。
    # 【为什么叫「内部方法」】名字前面的下划线 _ 是 Python 的「约定俗成」写法，
    #   意思是「这是本类内部用的私人物品，外面的人请不要直接调用」。
    #   它只是个君子协定，Python 不会强制阻止，但看到下划线就该明白别乱用。
    # 【参数解释】vectors=要校验的二维列表（列表套列表）。
    # 【返回值为 -> None】表示它只是检查，不返回结果；发现问题的方式是「抛异常」。
    # 【注意事项】它只检查第 1 个向量的长度，不逐个检查所有。为什么可以这样？
    #   因为同一批是同一个模型算的、模型输出形状是固定的，所以查一个即可，
    #   这样更省时间。这是「够用就好」的性能取舍。
    def _check_dim(self, vectors: list[list[float]]) -> None:
        # 【这行在干什么】如果向量列表是空的，直接 return（什么都不做）。
        # 【为什么这么写】空列表没有东西可检查，如果继续往下走，后面 len(vectors[0])
        #   会因为「第 0 个位置不存在」而直接报错。所以必须先挡掉这种情况。
        if not vectors:
            # 【这行在干什么】立即结束这个方法。在函数里裸写 return 相当于「到此为止，不干了」。
            return
        # 【这行在干什么】取出第 1 个向量的长度（也就是它有多少个数字），存到 actual（实际的）。
        # 【参数解释】vectors[0] 是第 1 个向量（一个列表），len(...) 数它有几个元素。
        # 【为什么用变量名 actual】和下面配置里的 expected 形成对照，读代码时一眼能看出
        #   这是在比对「实际 vs 期望」。
        actual = len(vectors[0])
        # 【这行在干什么】如果实际维度不等于配置维度，就抛出一个人能看懂的错误。
        # 【为什么用 != 而不是 ==】这里是在检查「不匹配」的坏情况 —— 只有不匹配时才需要报错，
        #   匹配（正常情况）就什么都不做，安静地继续跑。
        if actual != self._settings.embed_dim:
            # 【这行在干什么】抛出一个带详细说明的 EmbeddingError，把「实际是多少、配置是多少、
            #   该怎么办」三件事一次说清。
            # 【为什么报错信息要写得这么啰嗦】这种错误几乎都发生在「换模型 / 改配置之后忘了重建库」，
            #   一句「维度不匹配」会让人一头雾水；写清数字并直接给出「请修正配置后重建知识库」
            #   的建议，运维看一眼就知道怎么办。
            # 【注意事项】这是「致命错误」，必须抛出而不能只打印日志 ——
            #   因为一旦带着错误维度继续写库，会把整个知识库污染成不可用状态，比直接失败更糟。
            raise EmbeddingError(
                f"向量维度不匹配：模型 {self._settings.embed_model} 实际输出 {actual} 维，"
                f"但 .env 中 EMBED_DIM={self._settings.embed_dim}。请修正配置后重建知识库。"
            )


# 【这行在干什么】声明一个模块级的全局变量 _embedder，用来保存「唯一的那个 Embedder 对象」。
# 【为什么初始值是 None】表示「还没创建过」。等第一次调用 get_embedder 时才真正创建。
# 【专业词解释：单例】意思是「整个程序里只要一份」。这里用它来保证向量模型只加载一次：
#   模型很大，加载很贵，多份实例纯属浪费。
# 【为什么类型标注是 Embedder | None】竖线 | 表示「或者」，即「要么是一个 Embedder，
#   要么还是 None（尚未创建）」。这是新式写法，靠文件顶部的 from __future__ 才能在老版本跑。
_embedder: Embedder | None = None

# 【这行在干什么】再创建一把独立的锁，专门保护「单例创建」这个动作。
# 【为什么要第二把锁、不复用 Embedder 里那把】因为两把锁保护的是两件不同的事：
#   · 这把保护的是「谁来创建/持有那唯一的 Embedder 对象」；
#   · Embedder 内部那把保护的是「模型加载」。
#   混用一把锁在极端情况下会引起「自己等自己」的死锁，所以分开更安全、职责也更清楚。
# 【专业词解释：死锁】两个厨师互相拿着对方想要的钥匙，谁也不肯先放手，结果一起卡死。
#   代码里的死锁就是程序永远停在那里不动，非常难排查，所以宁可多一把锁也要避免。
_embedder_lock = threading.Lock()


# 【这行在干什么】定义函数 get_embedder：给外界一个「拿向量模型」的统一入口。
# 【为什么要有这个函数，而不是让大家各自 new 一个】因为它实现了「全局单例」：
#   谁调用它，拿到的都是同一个 Embedder 对象（进而同一个模型），内存里只有一份模型。
# 【参数解释】settings=None 表示「调用方可以不传配置」。
#   不传时（默认）就用 get_settings() 从 .env 读取；传了就用传进来的。
#   这个设计是为了「方便测试」——测试时塞一份假配置进来，不必真的读 .env、不必真的下模型。
# 【返回值】一个 Embedder 对象（已保证可用）。
def get_embedder(settings: Settings | None = None) -> Embedder:
    """进程内单例，避免重复加载模型。"""
    # 【这行在干什么】声明「下面要用的是那个模块级的全局变量 _embedder，我要改它」。
    # 【为什么必须写 global（新手最容易踩的坑）】在函数里给变量赋值，Python 默认会创建一个
    #   「局部的」新变量，函数一结束就丢了。写上 global 才是告诉 Python：
    #   「我改的是外面那个真正的全局变量」，这样上面创建好的对象才能被保存下来，
    #   下次调用还能拿到。少了这行，单例就完全失效了（每次调用都会新建一个）。
    global _embedder
    # 【这行在干什么】第一次检查：全局变量是不是已经有了？
    # 【为什么先查一次（同 model 属性的思路）】绝大多数调用都发生在「已经创建过」之后。
    #   先在锁外面快速看一眼：有就直接返回，完全不用抢锁，速度最快。这叫「双重检查锁定」。
    if _embedder is None:
        # 【这行在干什么】加锁。with 会在进入时上锁、离开时自动解锁（即使中途报错也会解锁）。
        #   —— 注意这里用的是 _embedder_lock，专门保护「创建单例」这件事。
        with _embedder_lock:
            # 【这行在干什么】拿到锁之后再检查一次：是不是已经被别的线程创建好了？
            # 【为什么必须再查一次】和上面 model 属性里的原因一模一样：假设两个线程同时走到
            #   外层判断，都发现是 None，都来抢锁；先抢到的创建完毕，后抢到的若不复查，
            #   就会把前面那个好端端的对象覆盖掉，白创建一次（还多加载一份模型，最坏情况内存翻倍）。
            if _embedder is None:
                # 【这行在干什么】创建唯一的 Embedder 对象并存进全局变量。
                # 【参数解释】settings or get_settings() 的意思是：
                #   如果调用方传了配置（settings 不是 None），就用它；
                #   如果没传（None 在 Python 里算「假」），就调用 get_settings() 从 .env 里读一份。
                #   这是一种很常见的「你可以不传，不传我就给个默认值」写法。
                # 【注意事项】get_settings() 自带缓存，反复调用不会重复读磁盘，所以这里用着很放心。
                _embedder = Embedder(settings or get_settings())
    # 【这行在干什么】把那个唯一的 Embedder 交给调用方。
    # 【为什么写在所有 if 外面】因为不管「早就创建过」「刚刚才创建」「在这次调用里被创建」，
    #   最后都要把它返回出去，写在最外层只需一句，逻辑最干净。
    return _embedder