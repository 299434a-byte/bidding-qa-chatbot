# 【这行在干什么】定义一个常量：每次送给向量模型「批量处理」的文档数（64 个）。
# 【为什么要分批（关键性能设计）】如果一次性把几万个文档全交给向量模型，
#   ①显存/内存会瞬间暴涨甚至崩掉；②模型推理效率反而下降。
#   分批（每 64 个算一批）能稳定控制内存占用，让长流水线平稳跑完。
# 【调大调小会怎样】调大 → 每批更快但吃内存；调小 → 更省内存但批次更多、调度开销变多。
