#   可能写成 "ranking"、"rank"、"result"……与其报错降级，不如把这些常见写法都认了。
# 【结构解释】元组（tuple）：和列表很像，也是「一串值」，但创建后不能改。这里只是遍历用，
#   不需要修改，用元组更合适（也更省内存、更不容易被误改）。
# 【查找顺序】从前往后依次试，谁先命中用谁，所以把最可能的 "order" 放最前面。
_ORDER_KEYS = ("order", "ranking", "rank", "result", "indices", "indexes")


# 【这行在干什么】定义内部函数 _summarize：把一条候选压缩成一行短摘要。
# 【名字前下划线的含义】约定俗成：下划线开头是「本模块内部专用」，外部不该引用。
# 【参数逐个解释】
#   · hit —— 一条候选记录字典（含 text、fields 等键）；
#   · max_chars —— 摘要最多保留多少个字符（超了从尾巴砍掉）。
# 【返回值】一行文本摘要。
# 【为什么需要「压缩」（关键）】候选可能有几十条，每条原文动辄几百上千字。全部原样塞进
#   提示词，不仅浪费钱（按词元计费），还可能超出模型能接收的上限、或者让模型"看花了眼"。
#   所以每条只留最关键的一小段。
def _summarize(hit: dict[str, Any], max_chars: int) -> str:
    """把一条候选压成一行摘要，控制提示词体积。

    ``text`` 是建库时渲染好的「字段注释: 值」文本，已带中文标签，比原始 ``fields``
    更适合直接喂给模型。首行「【表名】记录ID：x」在候选行前缀里已体现，去掉以免挤占长度预算。
    """
    # 【这行在干什么】把 text 按行拆开、去掉首尾空白、丢掉空行，得到一组「有内容的行」。
    # 【写法逐步拆解】这是一条「列表推导式」（一种紧凑的循环写法），从里往外读：
    #   · (hit.get("text") or "").splitlines() —— 取出 text 并按换行切成多行；
    #     用 get 加默认值是为了防「这条记录没带 text 键」时直接报 KeyError；
    #     `or ""` 则是防 text 是 None 时调 splitlines 报错；
    #   · for line in ... —— 逐行处理；
    #   · if line.strip() —— 只保留「去掉空白后非空」的行（过滤掉空行）；
    #   · line.strip() —— 每行本身也去掉首尾空白，避免缩进残留。
    lines = [line.strip() for line in (hit.get("text") or "").splitlines() if line.strip()]
    # 【这行在干什么】如果第一行是以「【」开头的（形如【表名】记录ID：x），就把它丢掉。
    # 【为什么要丢掉首行】这段「【表名】记录ID」信息在候选行的前缀里已经写过一遍了
    #   （见 build_rerank_messages），保留在这里纯属重复占字数、挤占摘要预算。
    if lines and lines[0].startswith("【"):
        lines = lines[1:]
    # 【这行在干什么】把剩下的多行合并成「用空行隔开再统一压成单空格」的一行文本。
    # 【写法逐步拆解】从里往外读：
    #   · " ".join(lines) —— 先把多行用空格连成一个大字符串；
    #   · .split() —— 不带参数时，按「任意连续空白字符」切开，并自动丢弃空片段；
    #     这一步会把连续空格、制表符、缩进统统变成"没有"；
    #   · " ".join(...) —— 再用单个空格把碎片重新拼起来。
    # 【效果举例】"招标\n  公告   项目" → "招标 公告 项目"（多行变一行、多个空格变一个）。
    summary = " ".join(" ".join(lines).split())
    # 【这行在干什么】如果压出来是空的（text 没内容或全是空白），就退而用原始字段拼一份摘要。
    if not summary:
        # 【这行在干什么】取出原始字段字典；没有就空字典兜底（防 KeyError / None 报错）。
        fields: dict[str, Any] = hit.get("fields") or {}
        # 【这行在干什么】把字段拼成「键: 值；键: 值」的字符串。
        # 【写法拆解】
        #   · fields.items() —— 把字典变成「键值对」逐个遍历；
        #   · if v not in (None, "") —— 只保留「有值」的字段（跳过空值，避免出现「金额: 」这种半截话）；
        #   · f"{k}: {v}" —— 拼成「字段名: 字段值」；
        #   · "；".join(...) —— 用中文分号把多段连起来。
        summary = "；".join(f"{k}: {v}" for k, v in fields.items() if v not in (None, ""))
    # 【这行在干什么】最后做长度截断，返回不超过 max_chars 个字符。
    # 【写法解释】summary[:max_chars] 是「切片」：取从开头到第 max_chars 个字符为止的一段。
    #   如果字符串比 max_chars 短，就原样返回（不会报错）。
    # 【注意事项】这里是「硬砍」，可能把一句话砍成半截。对摘要场景可以接受——模型只需要
    #   大致判断相关性，不要求语句完整。
    return summary[:max_chars]


# 【这行在干什么】定义函数 build_rerank_messages：把问题和候选拼成给大模型的消息列表。
# 【参数逐个解释】
#   · question —— 用户的问题原文；
#   · hits —— 候选记录列表（每条一个字典）；
#   · max_chars=300 —— 每条候选摘要最多多少字符（默认 300，可由配置覆盖）。
# 【返回值】OpenAI 风格的消息列表：[{"role":"system",...}, {"role":"user",...}]。
# 【为什么候选要「带编号」】重排的结果是「一串序号」（比如让我排成 2,1,3），不是内容本身。
#   所以必须在提示词里给每条候选标上号，模型才能说「我建议把第 3 条放前面」。
def build_rerank_messages(
    question: str,
    hits: list[dict[str, Any]],
    max_chars: int = 300,
) -> list[dict[str, str]]:
    """拼重排提示词：问题 + 带编号的候选摘要列表。"""
    # 【这行在干什么】建一个空列表，收集每一行「候选行」文本。
    lines: list[str] = []
    # 【这行在干什么】遍历候选，并给每条配一个编号。
    # 【写法拆解】enumerate(hits, start=1) 让循环里同时拿到「序号 i」和「内容 hit」，
    #   start=1 表示编号从 1 开始——因为提示词里要让模型看到「1. 2. 3.」这种人类习惯的编号。
    for i, hit in enumerate(hits, start=1):
        # 【这行在干什么】确定这条候选要显示的「来源标签」。
        # 【写法拆解】`hit.get("label") or hit.get("table") or ""`：三段兜底——
        #   优先用中文表名 label（如「招标公告」）；没有就用英文表名 table；再没有就空字符串。
        # 【为什么要有兜底】不同调用方传进来的 hit 字段完备程度可能不同，兜底避免显示 None。
        label = hit.get("label") or hit.get("table") or ""
        # 【这行在干什么】拼出一行候选文本，追加到列表。
        # 【写法拆解】f"{i}. [{label}|记录 {hit.get('primary_key')}] {_summarize(hit, max_chars)}"：
        #   · 「i. 」—— 编号，模型靠它来指代候选；
        #   · 「[表名|记录 主键]」—— 告诉模型这条来自哪张表、哪条记录（便于它理解上下文）；
        #   · 后面跟 _summarize 压缩出的摘要正文。
        # 【为什么不放完整原文】见 _summarize 的说明：省预算、防止模型"看花眼"。
        lines.append(f"{i}. [{label}|记录 {hit.get('primary_key')}] {_summarize(hit, max_chars)}")

    # 【这行在干什么】拼出「用户消息」的完整正文：问题 + 候选清单 + 输出格式要求。
    # 【写法拆解】这是一条跨多行拼接语句（外层括号让它能安全换行）：
    #   · 先写【用户问题】和问题原文；
    #   · 再写【候选资料】和上面收集的所有候选行（用 "\n".join(lines) 用换行连起来）；
    #   · 最后再叮嘱一次输出格式 `{"order": [2, 1, 3]}`（给个具体例子，模型更容易照做）。
    # 【为什么最后还要再强调格式】system 守则里已经说过一遍，但这属于"重要的事说三遍"——
    #   格式错误是重排失败的头号原因，多提醒一次成本极低、收益明显。
    user_content = (
        f"【用户问题】\n{question}\n\n"
        "【候选资料】\n" + "\n".join(lines) + "\n\n"
        '请只输出 JSON，形如 {"order": [2, 1, 3]}。'
    )
    # 【这行在干什么】返回标准消息列表：一条 system（守则）+ 一条 user（具体任务）。
    return [
        {"role": "system", "content": RERANK_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


# 【这行在干什么】定义函数 extract_json：从模型输出里「抠出」并解析出 JSON 数据。
# 【参数解释】raw —— 模型返回的原始文本（可能很脏）。
# 【返回值】解析成功就返回 Python 数据（字典或列表）；解析不出来返回 None。
# 【为什么需要它（通用工具，被两处复用）】
#   ① 重排（本文件）—— 要解析出 {"order": [...]}；
#   ② 深度模式的规划与自评（deep_agent.py）—— 同样要解析模型输出的 JSON。
#   模型输出常常不守规矩：把 JSON 包在 ``` 代码块里、或在前后夹一段解释文字。
#   统一由这个函数兜住，避免两处各写一遍容易不一致。
def extract_json(raw: str) -> Any | None:
    """从大模型输出里剥掉代码围栏、提取并解析内嵌的 JSON（对象或数组）。

    深度模式（``deep_agent``）的规划与自评输出也走这里：
    模型常把 JSON 包在 ``` 里或在前后夹一段解释，统一在这里兜住。
    解析不出来时返回 ``None``，由调用方决定降级。
    """
    # 【这行在干什么】空输入直接返回 None（连解析都不用试）。
    # 【为什么先判断】raw 可能是空字符串或 None，后面的正则和 json.loads 处理它们没意义。
    if not raw:
        return None
    # 【这行在干什么】先做「清洗」：把所有 Markdown 代码围栏标记替换成空格，再去掉首尾空白。
    # 【写法拆解】_FENCE_RE.sub(" ", raw) —— 用预编译的正则把所有匹配到的「```xxx」片段
    #   替换成一个空格。用空格而不是空字符串，是为了避免把前后文字"粘"在一起。
    text = _FENCE_RE.sub(" ", raw).strip()
    # 【这行在干什么】清洗完如果啥都不剩，直接返回 None。
    if not text:
        return None

    # 【这行在干什么】建一个列表，按「优先级」收集待解析的候选片段。
    chunks: list[str] = []
    # 【这行在干什么】用正则找「被 {} 或 [] 包住的那一段」。
    # 【写法解释】match 是匹配结果对象；没匹配上时是 None（假值），所以直接写 `if match` 判断。
    match = _JSON_RE.search(text)
    if match:
        # 【这行在干什么】把匹配到的那段文本放进候选列表，排在最前面（优先尝试）。
        # 【写法解释】match.group(0) 表示「整个匹配到的内容」（0 号组=整体）。
        # 【为什么要优先这一段】被括号包住的通常就是真正的 JSON 主体；
        #   整段原文可能还夹着解释文字，直接解析会失败。
        chunks.append(match.group(0))
    # 【这行在干什么】再把「清洗后的完整全文」也放进候选列表，作为第二选择。
    # 【为什么要留这个兜底】如果 JSON 本身没被括号正常包住（比如模型漏了收尾括号），
    #   上面那条正则可能匹配到很奇怪的一段；这时直接拿全文试试，说不定能成功。
    chunks.append(text)
    # 【这行在干什么】依次尝试解析每个候选片段，谁先成功就返回谁。
    for chunk in chunks:
        # 【这行在干什么】打开「接住岔子」的网，尝试把这段文本解析成 Python 数据。
        try:
            # 【这行在干什么】json.loads 把 JSON 文本变成 Python 对象
            #   （对象→字典，数组→列表，字符串→字符串，数字→数字）。
            return json.loads(chunk)
        # 【这行在干什么】解析失败（格式不合法）时，忽略这个候选，继续试下一个。
        # 【参数解释】同时接住 ValueError（JSON 格式错误）和 TypeError（类型不对，比如传了 None）；
        #   用 continue 跳到下一次循环（也就是试下一个候选片段）。
        except (ValueError, TypeError):
            continue
    # 【这行在干什么】所有候选都试完了还是不行，返回 None。
    # 【为什么返回 None 而不是抛异常（设计取舍）】本文件的设计原则是「失败就降级」，
    #   解析失败是预期内的情况（模型可能不听话），不该让调用方去处理异常，
    #   用 None 表达「没解析出来」最简洁，调用方看到 None 就知道该回退原顺序了。
    return None


# 【这行在干什么】定义内部函数 _extract_sequence：从解析好的 JSON 里，找出那个「序号数组」。
# 【参数解释】data —— extract_json 解析出来的 Python 数据（可能是列表、字典或其他）。
# 【返回值】找到的数组（列表）；找不到返回 None。
# 【为什么要单独抽一步（关键）】因为模型的输出结构可能有多种形态：
#   · 最理想：直接给一个数组 [2, 1, 3]（此时 data 本身就是列表）；
#   · 常见：包一层字典 {"order": [2, 1, 3]}；
#   · 不听话：键名写成别的（ranking/rank/...）；
#   · 极不听话：用了个我们完全没预料到的键名。
#   这个函数就是「把各种形态都认一遍」的兼容层。
def _extract_sequence(data: Any) -> list[Any] | None:
    """从解析出的 JSON 里找到那个序号数组。"""
    # 【这行在干什么】如果 data 本身就是列表，那它就是我们要的序号数组，直接返回。
    # 【写法解释】isinstance(data, list) 是「类型判断」：检查 data 是不是列表类型。
    if isinstance(data, list):
        return data
    # 【这行在干什么】如果 data 是字典，就按几种可能的键名去逐个找数组值。
    if isinstance(data, dict):
        # 【这行在干什么】按预设的候选键名顺序遍历（order → ranking → rank → ...）。
        for key in _ORDER_KEYS:
            # 【这行在干什么】取值（用 get 安全取，键不存在时拿到 None，不会报错）。
            value = data.get(key)
            # 【这行在干什么】只要这个键对应的值确实是列表，就认定为序号数组，返回它。
            if isinstance(value, list):
                return value
        # 【这行在干什么】兜底：上面那些键名都没命中，那就「看哪个值是数组就用哪个」。
        # 【为什么这个兜底很有用】模型可能用了我们没想到的键名（比如 "sorted"），
        #   但只要它给的是个数组，大概率就是排序结果——这是"宁滥勿缺"的容错思路。
        for value in data.values():
            if isinstance(value, list):
                return value
    # 【这行在干什么】其他情况（是数字、是字符串、是 None…）一律返回 None，表示没找到。
    return None


# 【这行在干什么】定义函数 parse_order：把大模型返回的原始文本，解析成「合法的候选顺序」。
# 【参数逐个解释】
#   · raw —— 模型返回的原始文本；
#   · n —— 候选总数（用来校验序号别越界）。
# 【返回值】一个「从 0 开始的序号列表」，是 range(n) 的一个排列；实在解析不出来就返回 None。
# 【为什么返回值的处理这么讲究（核心设计：绝不丢候选）】
#   返回值保证「一定是 0..n-1 的一个完整排列」——既不重、也不漏。模型漏掉的候选，
#   按原顺序补到末尾。这样上层无论如何都能拿到完整的一批资料，不会出现「某条资料凭空消失」。
#   「绝不丢候选」是本项目明确的设计要求，因为丢掉的可能正是最该展示给用户的那条。
def parse_order(raw: str, n: int) -> list[int] | None:
    """把大模型返回的文本解析成 0 起的候选顺序。

    模型输出并不可靠，这里要兜住：代码围栏、JSON 前后夹杂解释文字、序号越界、
    重复序号、漏项。完全无法解析时返回 ``None``，由调用方回退到原顺序。

    返回值一定是 ``range(n)`` 的一个排列——**绝不丢候选**：模型漏掉的按原顺序补到末尾。
    """
    # 【这行在干什么】输入校验：文本为空、或者根本没有候选（n <= 0），直接返回 None。
    # 【为什么先拦这两件事】没内容就没得解析；n 为 0 时后面算「排列」也没意义。
    if not raw or n <= 0:
        return None

    # 【这行在干什么】剥掉 Markdown 代码围栏并去首尾空白（同 extract_json 的清洗步骤）。
    text = _FENCE_RE.sub(" ", raw).strip()
    # 【这行在干什么】洗完还是空，返回 None。
    if not text:
        return None

    # 优先解析被 {} 或 [] 包住的片段；失败再整体试一次
    # 【这行在干什么】建候选片段列表（同 extract_json，先"括号片段"后"全文"）。
    chunks: list[str] = []
    # 【这行在干什么】找被括号包住的 JSON 主体。
    match = _JSON_RE.search(text)
    if match:
        # 【这行在干什么】把括号片段作为第一优先候选。
        chunks.append(match.group(0))
    # 【这行在干什么】把清洗后的全文作为第二候选（兜底）。
    chunks.append(text)

    # 【这行在干什么】准备一个变量，用来存放「找到的序号数组」，初始为 None。
    # 【类型解释】list[Any] | None 表示：要么是一个列表，要么是 None。
    sequence: list[Any] | None = None
    # 【这行在干什么】逐个候选片段尝试解析，直到成功找到数组为止。
    for chunk in chunks:
        try:
            # 【这行在干什么】解析这段文本为 Python 数据。
            data = json.loads(chunk)
        except (ValueError, TypeError):
            # 【这行在干什么】这段解析失败，跳过，试下一段。
            continue
        # 【这行在干什么】从解析出的数据里提取序号数组（兼容多种结构，见上面 _extract_sequence）。
        sequence = _extract_sequence(data)
        # 【这行在干什么】一旦真正找到了数组，就跳出循环（不用再试后面的候选）。
        # 【为什么这里用 break 而不是 return】因为后面还要对 sequence 做「清洗和补全」，
        #   不能在这里就返回原始结果。
        if sequence is not None:
            break

    # 【这行在干什么】如果所有候选都没能找出数组，返回 None（交给上层降级）。
    if sequence is None:
        return None

    # 【这行在干什么】准备一个集合，记录「已经收进结果的序号」，用来去重。
    # 【为什么用集合（set）而不是列表】集合的「查某个元素在不在」是瞬间完成的（哈希查找），
    #   而列表要从头找到尾（越往后越慢）。这里要频繁判断重复，集合快得多。
    seen: set[int] = set()
    # 【这行在干什么】准备结果列表（按模型给的顺序收集合法序号）。
    order: list[int] = []
    # 【这行在干什么】逐个检查模型给的序号，把合法的收进来。
    for item in sequence:
        # 【这行在干什么】把模型给的编号转成「从 0 开始」的索引。
        # 【为什么 -1（重要）】提示词里给模型的编号是「1、2、3…」（人类习惯），
        #   而 Python 列表的下标是「0、1、2…」。所以模型说「第 1 条」时，
        #   我们要取的是 hits[0]，必须减 1。这一步搞错了整个顺序就全歪了。
        try:
            index = int(item) - 1  # 提示词里的编号从 1 开始
        except (TypeError, ValueError):
            # 【这行在干什么】如果这一项不是能转成整数的东西（比如模型给了个词、给了 null），
            #   跳过它，继续看下一项。宁可漏一项（后面会补），也不能让整个解析崩掉。
            continue
        # 【这行在干什么】校验：序号要在合法范围内（0 到 n-1），且不能重复。
        # 【写法拆解】`0 <= index < n` 是 Python 特有的「链式比较」，等价于
        #   `0 <= index and index < n`，但更简洁好读。写成这样能一次挡住两个越界方向：
        #   太小的负数、太大的正数。这是防御「模型瞎写序号」的关键一步。
        #   `index not in seen` 则是防重复——模型偶尔会把同一条说两遍。
        if 0 <= index < n and index not in seen:
            # 【这行在干什么】登记这个序号，表示"已收下"。
            seen.add(index)
            # 【这行在干什么】按模型给的出现顺序，把它追加到结果列表末尾。
            order.append(index)

    # 【这行在干什么】如果一条合法序号都没有（模型完全在胡说），返回 None 降级。
    if not order:
        return None

    # 【这行在干什么】补全：把模型漏掉的候选，按原始顺序追加到结果末尾。
    # 【写法拆解】order.extend(...) 表示"把一批元素批量加进 order 列表末尾"；
    #   括号里是「生成器表达式」（一种懒执行的循环写法）：`i for i in range(n) if i not in seen`
    #   含义是"对 0..n-1 里的每个 i，如果它还没被收过，就拿出来"。
    # 【为什么这样写能保证完整（关键设计）】range(n) 覆盖了全部候选下标，seen 记录了已收的，
    #   两者一差就是「所有漏掉的」；把它们按自然顺序补到末尾，最终 order 一定是 0..n-1 的
    #   完整排列——一条都不丢。这就是 docstring 里承诺的「绝不丢候选」。
    order.extend(i for i in range(n) if i not in seen)
    # 【这行在干什么】返回最终顺序（一个完整的 0..n-1 排列）。
    return order


# 【这行在干什么】定义主函数 rerank_hits：对候选做二次排序，返回「结果 + 元信息」。
# 【参数逐个解释】
#   · question —— 用户问题（重排的判断依据）；
#   · hits —— 待重排的候选列表（RRF 融合后的顺序）；
#   · settings —— 配置对象（可省）；
#   · top_k —— 最终要留几条（不传就用配置里的 retrieve_final_top_k）。
# 【返回值】一个「二元组」(结果列表, meta 字典)。
#   【为什么返回两个东西（设计说明）】结果列表是要给下一步（组织答案）用的；
#   meta 是"这次重排到底发生了什么"的诊断信息（是否生效、用了哪个模型、有没有报错），
#   要给前端展示徽标和告警用。把两者一起返回，调用方一次就能拿全，不用二次查询。
def rerank_hits(
    question: str,
    hits: list[dict[str, Any]],
    settings: Settings | None = None,
    top_k: int | None = None,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """对 RRF 融合后的候选做二次排序，返回 (结果, meta)。

    meta 字段：``rerank_applied`` / ``rerank_model`` / ``rerank_candidates`` / ``rerank_error``。
    任何失败都只会让 ``rerank_applied`` 保持 False，不会向上抛异常。
    """
    # 【这行在干什么】确定用哪份配置（同前，允许外部注入便于测试）。
    s = settings or get_settings()
    # 【这行在干什么】确定最终保留条数：传了 top_k 就用传的，否则用配置里的默认值。
    want_k = top_k or s.retrieve_final_top_k

    # 【这行在干什么】先准备好 meta 字典，把默认值都填上。
    # 【为什么先建默认值（关键习惯）】这样无论后面走哪条分支、在哪一步失败，
    #   返回的 meta 结构都是完整一致的（字段齐全），调用方永远不用做「这个键存不存在」的判断。
    #   这是「失败也是正常输出」的设计思路。
    meta: dict[str, Any] = {
        # 【这行在干什么】rerank_applied=False 表示"重排尚未生效"；
        #   只有一路顺利跑完才会被改成 True。它是前端的"重排是否起作用"的判断依据。
        "rerank_applied": False,
        # 【这行在干什么】用了哪个模型重排，初始为 None（还没定）。
        "rerank_model": None,
        # 【这行在干什么】候选总数（诊断用：能看出"给模型喂了多少条"）。
        "rerank_candidates": len(hits),
        # 【这行在干什么】错误信息，初始为 None（没出错）。
        "rerank_error": None,
    }

    # 【这行在干什么】如果压根没有候选，直接原样返回，不浪费一次大模型调用。
    # 【为什么 hits[:want_k] 而不是 hits】保持返回类型一致（都是列表）；空列表怎么切都是空。
    if not hits:
        return hits, meta

    # 未配置大模型：静默跳过（meta.llm_configured 已能说明原因）
    # 【这行在干什么】检查「重排所需的大模型配置」是否齐全；不齐就直接跳过重排。
    # 【为什么是「静默」跳过而不是报错（重要）】没配大模型是「预期内的正常状态」
    #   （比如运维故意只开检索功能）。这种情况不该在 meta 里留下"错误"字样吓人，
    #   前端的 llm_configured 字段已经能解释原因了。
    if not s.rerank_configured:
        return hits[:want_k], meta

    # 候选本来就不比目标条数多，排序没有意义
    # 【这行在干什么】如果候选数量本来就不超过要保留的条数，那排序毫无意义（反正全都要），
    #   直接截断返回，省一次大模型调用（也省钱）。
    # 【举例】候选 4 条、要留 5 条 → 全留着就行，不需要知道先后顺序。
    if len(hits) <= want_k:
        return hits[:want_k], meta

    # 【这行在干什么】把实际要用的重排模型名写进 meta（供前端展示"用了哪个模型"）。
    # 【参数解释】s.rerank_model_or_default 是配置里的"重排模型"（配了就用配的，
    #   没配就用系统默认），这个逻辑在 config.py 里已经处理好了。
    meta["rerank_model"] = s.rerank_model_or_default
    # 【这行在干什么】打开「接住岔子」的网——从这一步开始，任何失败都必须降级、绝不外抛。
    try:
        # 【这行在干什么】调用大模型做重排，并解析出顺序。
        # 【为什么要写成一个嵌套调用】这一步做了两件事，一口气表达清楚：
        #   ① complete_chat(...) 去问大模型（非流式，一次拿全）；
        #   ② parse_order(raw, len(hits)) 把模型返回的文字解析成顺序列表。
        # 【参数逐个解释】
        #   · build_rerank_messages(question, hits, s.rerank_max_chars) —— 拼提示词
        #     （每条候选最多显示 rerank_max_chars 个字符，防止提示词过长）；
        #   · settings=s —— 用这份配置；
        #   · model=s.rerank_model_or_default —— 重排专用的模型（可能与问答模型不同）；
        #   · temperature=0.0 —— 【关键】用最"死板"的模式，因为我们要的是稳定的排序、
        #     不是创作；温度高会让模型"发挥"，输出格式更容易乱。
        #   · max_tokens=_RERANK_MAX_TOKENS —— 3072，理由见该常量处的血泪教训；
        #   · timeout=s.rerank_timeout —— 【关键】配置里是 45 秒。曾经设成 20 秒时，
        #     推理模型还没想完就被掐断，导致"静默降级"（表面上没报错，实际重排没生效），
        #     极难发现；所以宁可等久一点，也不要偷偷降级。
        raw = complete_chat(
            build_rerank_messages(question, hits, s.rerank_max_chars),
            settings=s,
            model=s.rerank_model_or_default,
            temperature=0.0,
            max_tokens=_RERANK_MAX_TOKENS,
            timeout=s.rerank_timeout,
        )
        # 【这行在干什么】把模型返回的文本解析成「从 0 开始的候选顺序」；解析失败会得到 None。
        order = parse_order(raw, len(hits))
    # 【这行在干什么】如果抛出的是「没配大模型」异常，静默返回原序（同上面的未配置分支）。
    # 【为什么这里也要接】虽然前面已经查过 rerank_configured，但配置可能在运行期被改动、
    #   或者 llm 内部判定条件略有不同；多一层保险，确保绝不因配置问题中断问答。
    except LLMNotConfigured:
        return hits[:want_k], meta
    # 【这行在干什么】如果大模型调用失败（超时、密钥无效、网络不通……），记下原因并降级。
    except LLMError as exc:
        # 【这行在干什么】把错误文本写进 meta，前端看到这个字段就会显示红色告警。
        # 【为什么必须记下来（重要）】这正是"静默降级"的破解之道：降级了，但留下了痕迹。
        #   否则用户会以为重排正常工作，而实际上排序根本没做——这种"表面正常"最难排查。
        meta["rerank_error"] = str(exc)
        return hits[:want_k], meta
    # 【这行在干什么】兜底：接住任何其他意外异常，同样降级。
    # 【参数解释】`as exc` 把异常对象存进 exc 以便取消息文本。
    # 【`# noqa: BLE001` 是什么】这是给代码检查工具（linter）看的注释：BLE001 这条规则
    #   建议"不要用这么宽泛的 except Exception"（因为会掩盖真正的 bug）。但本文件的设计
    #   原则恰恰是"重排绝不允许影响问答主流程"，所以这里明确要求 linter 放行。
    except Exception as exc:  # noqa: BLE001 - 重排失败绝不能影响问答主流程
        # 【这行在干什么】记下「重排失败：具体原因」，仍返回原序。
        meta["rerank_error"] = f"重排失败：{exc}"
        return hits[:want_k], meta

    # 【这行在干什么】如果解析结果是 None（模型没说人话），记下原因并降级。
    if order is None:
        # 【这行在干什么】写一条人类能看懂的失败原因，前端会展示出来。
        meta["rerank_error"] = "大模型返回内容无法解析为排序结果，已沿用 RRF 顺序"
        return hits[:want_k], meta

    # 【这行在干什么】准备一个空列表，用来装按新顺序排好的候选。
    reranked: list[dict[str, Any]] = []
    # 【这行在干什么】按模型给的顺序，重新排列候选，并给每条打上"新排名"标记。
    # 【写法拆解】enumerate(order, start=1) 得到「新排名 rank」和「原始下标 index」；
    #   注意这里的 rank 从 1 开始（给人看的排名），而 index 是 hits 里的实际位置（从 0 开始）。
    for rank, index in enumerate(order, start=1):
        # 【这行在干什么】复制一份这条候选，然后写入新的排名。
        # 【为什么要 dict(hits[index]) 复制而不是直接用（重要）】dict(...) 会造一个「浅拷贝」——
        #   新的字典，但里面的值还是共享的。这样做是为了「不在原始 hit 上写 rerank_rank」：
        #   原始 hits 可能还被别的地方引用（比如 meta、日志、调用方的变量），
        #   直接改它会"污染"这些地方，产生难以预料的副作用。复制一份再改，干净。
        item = dict(hits[index])  # 复制，不改动原始 hit
        # 【这行在干什么】在新副本上写入「重排后的名次」，前端可以用它显示「Reranked #1」之类的徽标。
        item["rerank_rank"] = rank
        # 【这行在干什么】把排好位的这条收进结果列表。
        reranked.append(item)

    # 【这行在干什么】走到这里说明全程顺利完成，把「重排已生效」标记为真。
    # 【为什么放在最后才置 True】只有所有步骤都成功了才算真生效；
    #   中途任何一步失败都已经提前 return 了，不会执行到这行。
    meta["rerank_applied"] = True
    # 【这行在干什么】返回最终结果（截取前 want_k 条）+ meta。
    return reranked[:want_k], meta