# ============================================================================
# 文件：rerank.py —— 给检索结果「再排一次序」的复核员
#
# 【这个文件在整个项目里是干什么的】
#   检索（retriever.py）会一次捞出几十条候选，用 RRF 算法融合出一个顺序。但 RRF 有个天生
#   的局限：它只看「这条记录在某一路检索里排第几」，并不真的读片段内容、判断「这段话到底
#   能不能回答用户的问题」。所以候选一多，靠前的位置就容易混进「词面相似或语义相近，但
#   其实答非所问」的记录——而排在前面的这几条，恰恰就是大模型作答时唯一的依据。
#   本文件就是解决这个问题的「复核员」：把问题和候选片段一起交给大模型，让它按
#   「真实相关度」重新排序，再截取前 N 条送去做回答。
#
#   干活顺序是：build_rerank_messages（拼提示词）→ complete_chat（问大模型，在 llm.py 里）
#   → parse_order（把模型给的一串序号解析成我们要的顺序）→ 重排 hits 并截断。
#
# 【最重要的设计原则（务必记住）】
#   「重排是锦上添花，绝不能变成单点故障。」
#   没配大模型、接口超时、返回的不是合法 JSON、序号越界……任何一种意外，都不许让用户
#   收不到回答；本文件一律「悄悄退回 RRF 原顺序继续跑」，只在 meta 里留一条痕迹供排查。
#   这就是为什么这个文件里异常捕获写得特别多、特别"怂"——是刻意的。
#
# 【谁调用它（上游）】
#   · rag.py 的 /api/chat 链路 —— 检索之后、生成答案之前调用 rerank_hits；
#   · agent.py 的 RAG 工具（search_bidding_knowledge）—— 内部同样复用本文件；
#   · retriever.py 的 retrieve 在 rerank=True 时也会调用。
#
# 【它给谁用（下游）】
#   · llm.py 的 complete_chat —— 真正去问大模型（必须非流式，要拿到完整 JSON）；
#   · 前端 —— 展示「Reranked #N」徽标、以及重排失败时的红色告警。
#
# 【先懂的五个概念（大白话）】
#   1) 重排（re-ranking）：先用便宜快的方式粗筛一大批（召回），再用贵但准的方式精挑
#      一小批（重排）。像招聘：先简历粗筛 100 份，再 HR 细看挑 5 份约面试。
#   2) 提示词（prompt）：发给大模型的那段文字说明。写得清楚，模型才听话。
#   3) JSON：一种通用的「结构化文本」格式，形如 {"order": [2, 1, 3]}，机器最容易解析。
#   4) 正则表达式（regex）：一种「按模式找文字」的语法。本文件用它把模型输出里
#      多余的 Markdown 围栏、以及夹在中间的 JSON 抠出来。
#   5) 降级（fallback）：出问题时退回到「更弱但一定能用」的方案。这里就是回到 RRF 原序。
# ============================================================================

