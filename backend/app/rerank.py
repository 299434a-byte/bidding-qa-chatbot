# 【这行在干什么】预编译一条正则：匹配 Markdown 代码围栏的开头（如 ``` 或 ```json）。
# 【写法拆解】r"```[A-Za-z]*"：
#   · 开头的 r 表示「原始字符串」，含义是字符串里的反斜杠不当转义符处理（写正则时习惯加 r）；
#   · ``` 就是三个反引号，Markdown 里代码块的标记；
#   · [A-Za-z]* 表示「后面可以跟 0 个或多个英文字母」（比如 ```json 里的 json）；
# 【为什么要预编译（性能小知识）】re.compile 会先把正则"翻译"成内部可执行的形式。
#   如果一个正则在循环里要反复用，提前编译一次比每次现写字符串快得多。
_FENCE_RE = re.compile(r"```[A-Za-z]*")
# 【这行在干什么】预编译第二条正则：匹配一整段被 {} 或 [] 包住的内容（即 JSON 主体）。
# 【写法拆解】r"\{.*\}|\[.*\]"，参数 re.S：
#   · \{ 和 \} —— 匹配花括号（大括号在正则里有特殊含义，所以要用反斜杠转义）；
#   · \[ 和 \] —— 匹配方括号（同理需转义）；
#   · .* —— 匹配「尽可能多的任意字符」（贪婪匹配，会一路吃到最后一个括号）；
#   · | —— 「或」的意思，所以整条是「要么匹配 {...}，要么匹配 [...]」；
#   · re.S —— 一个开关，让点号 . 也能匹配「换行符」。默认情况下 . 遇到换行就停下，
#     而模型的 JSON 常常跨多行，不加 re.S 就匹配不到，这是很常见的坑。
_JSON_RE = re.compile(r"\{.*\}|\[.*\]", re.S)
