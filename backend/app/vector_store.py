# ============================================================================
# 文件：vector_store.py —— 向量数据库（Qdrant）的「收发室」
#
# 【这个文件在整个项目里是干什么的】
#   它负责跟「向量数据库 Qdrant」打交道，具体就三件事：
#     ① 建柜子：创建/清理一个存放向量的「集合（Collection）」；
#     ② 存档案：把每篇文档的向量 + 原文（payload）写进去；
#     ③ 找档案：拿用户问题的向量去库里找出最相近的若干条。
#
# 【什么是向量数据库（用一个比喻讲清）】
#   普通数据库擅长「精确匹配」：查 id=123 就给你 id=123 的那一行。
#   向量数据库擅长「找最像的」：给它一个问题的向量，它把库里成百上千个向量
#   一个个比一遍，返回「像的程度」排名靠前的几条。这正是语义检索需要的。
#
# 【为什么选「嵌入式本地模式」而不是装个数据库服务器（重要取舍）】
#   本机没有 Docker，装一套 Qdrant 服务端成本太高。Qdrant 提供了「嵌入式本地模式」：
#   直接用一个本地文件夹当数据库，不需要任何额外服务。代价是——
#   **同一个文件夹同一时间只能被一个进程打开**（文件夹上加了「独占锁」）。
#   所以：重建知识库要么走接口 POST /api/ingest（在后端进程内做），
#   要么先把后端停掉再跑命令行脚本；两个一起开必然报错。这一点文件里多处都在防守。
#
# 【谁调用它（上游）】
#   backend/app/ingest.py    —— 建库时：ensure_collection() 建集合、upsert_documents() 写数据。
#   backend/app/retriever.py —— 检索时：search_dense() 语义召回、search_sparse() 关键词召回。
#   backend/app/main.py      —— 探活时：stats() 统计、sample() 抽样看看库里有东西没。
#
# 【它给谁用（下游）】
#   检索结果（一堆带分数的字典）交给 retriever.py 做融合排序（RRF），最终送给大模型。
#
# 【先懂的四个概念（大白话）】
#   1) 集合（Collection）：可以理解成数据库里的「一张表」，或者一个「抽屉柜」。
#      本项目的所有文档都放在同一个集合里（名字由 .env 的 QDRANT_COLLECTION 决定）。
#   2) 点（Point）：集合里的一条记录，相当于「一行」。每条点包含三样东西：
#      一个 ID（编号）、一个或多个向量、一份 payload（随身携带的原始资料）。
#   3) payload：直译是「有效载荷」，这里就是「跟着向量一起存的附加信息」，
#      装着文档原文、来自哪张表、主键、第几块等。检索命中后，前端展示的就是它。
#   4) 稠密向量 vs 稀疏向量：本项目在一个集合里同时存两种向量——
#      · dense（稠密）：512 个小数，几乎每个都不为零，负责「意思像我」；
#      · bm25 （稀疏）：只有少数几个位置有值，负责「字面命中」，由 bm25.py 生成。
#      两种向量存在同一条点上，这就是「混合检索」的物理基础。
# ============================================================================

