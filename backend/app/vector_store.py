# 【这行在干什么】定义函数 text_hash：给一段正文算「内容指纹」（sha256 十六进制串）。
# 【为什么需要（增量建库的核心）】增量对比时，光凭 doc_id 只能知道「这条还在不在」，
#   无法知道「内容改没改」。用整块正文的 sha256 当指纹：内容一样 → 指纹一样；
#   改一个字 → 指纹完全不同。于是「更新」与「未变」可以精确区分。
# 【为什么要先 encode 成 utf-8】sha256 只接受「字节」，字符串要先按 utf-8 编码成字节
#   才能算；中文按 utf-8 编出来是稳定的，所以同一段中文每次算出的指纹都一样。
# 【注意事项】这是「确定性」计算，不发网络、不读磁盘，可以放心反复调用，代价极低。
def text_hash(text: str) -> str:
    """给一段正文算「内容指纹」（sha256 十六进制串）。"""
    # 先兜住 None：正文理论上是字符串，但历史上可能存成 None，直接 .encode 会报错。
    # 这里把 None 当空串处理，保证函数在任何输入下都能返回一个字符串。
    return hashlib.sha256((text or "").encode("utf-8")).hexdigest()


# 【这行在干什么】定义函数 point_id_of：把我们的 doc_id 转成 Qdrant 能接受的 UUID。
# 【参数解释】doc_id=文档编号，形如 "bidding_notices:123:0"（表名:主键:块序号）。
# 【返回值】一个字符串形式的 UUID，例如 "7c9f2a10-3b4e-5d6f-8a90-1b2c3d4e5f60"。
# 【为什么必须做这个转换（关键）】Qdrant 对点的 ID 有硬性限制：只接受「无符号整数」或
#   「UUID」，不接受任意字符串。我们的 doc_id 天生带冒号，直接塞进去会被拒绝。
#   于是这里把它「换算」成 UUID。但换算必须满足一个苛刻条件：见下面。
def point_id_of(doc_id: str) -> str:
    """Qdrant 只接受 uint64 或 UUID 作为点 ID。

    这里用 UUIDv5 把 ``表:主键:块序号`` 稳定映射成 UUID，
    同一个 doc_id 每次得到的 ID 完全一致，因此重建知识库是幂等覆盖，不会产生重复数据。
    """
    # 【这行在干什么】用 UUIDv5 算法，根据 doc_id 算出一个 UUID，转成字符串返回。
    # 【参数逐个解释】
    #   uuid.uuid5     —— 一种「确定性」的 UUID 生成算法：同一个输入永远得到同一个输出。
    #   uuid.NAMESPACE_URL —— 一个固定的「命名空间」常量（UUIDv5 要求必须给一个命名空间，
    #     相当于给这次计算加一个「域」，避免和别处用同样输入算出的 UUID 撞车）。
    #   "bidding-qa::" —— 我们自己再加一段固定前缀，进一步降低撞车概率，
    #     同时让 ID 的打分口径固定在「本项目」这个小世界里。
    #   doc_id         —— 真正的内容（表:主键:块序号）。
    # 【为什么必须是「确定性」的（最重要的设计点）】因为建库会被反复重跑。
    #   如果每次生成的 ID 都不一样，重跑一次库里就多出一整套重复数据：检索时同一条内容
    #   反复出现、排序被搅乱、库越滚越大。确定性生成让「同一块的 ID 永远一样」，
    #   于是写入变成「覆盖同一位置」，重跑多少次结果都一样——这叫「幂等」。
    # 【注意事项】它是纯计算，不发网络请求、不写磁盘，可以随便调用，代价极低。
    # 【小知识】uuid5 和 md5 一样是「哈希」：把任意长度的输入压成固定长度的指纹。
    #   理论上不同输入可能碰巧得到同一个指纹（叫「碰撞」），但概率低到可以忽略，
    #   而且这里额外加了固定的命名空间前缀，就更加安全了。
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"bidding-qa::{doc_id}"))


# 【这行在干什么】定义 VectorStore 类：它是「向量库」在本程序里的门面（统一入口）。
# 【为什么要有这个类】把「打开库、建集合、写数据、查数据、出统计」这些事都收在一处，
#   外部调用方只需要跟这一个对象打交道，不用关心 Qdrant 的各种细节。
class VectorStore:
    # 【这行在干什么】构造函数：建立连接、准备好锁、注册退出时的收尾动作。
    # 【参数解释】settings=配置对象，由外部传入（而不是在这里自己读 .env）。
    # 【为什么参数要外面传（依赖注入）】好处是：测试时可以塞一份「假配置」进来，
    #   比如指向一个临时目录，就不会碰到真实的数据库；代码也更容易复用。
    def __init__(self, settings: Settings) -> None:
        # 【这行在干什么】把配置存到对象自己身上，供后面所有方法使用。
        # 【为什么加 self.】不加的话 settings 函数一结束就没了；加了才成为「实例属性」。
        self.settings = settings
        # 【这行在干什么】确保向量库要用的那个文件夹已经存在，没有就创建它。
        # 【参数逐个解释】
        #   settings.qdrant_path —— 数据目录路径，来自 .env；
        #   .mkdir(parents=True, exist_ok=True) —— 建目录方法，两个参数都很关键：
        #     parents=True 表示「如果上层目录也不存在，就一路建上去」（像 mkdir -p）；
        #     exist_ok=True 表示「目录本来就在？那别报错，正常继续」。
        # 【为什么不加 exist_ok 会出错】因为「目录已存在」在 mkdir 眼里是一种错误；
        #   而服务重启、重复初始化时目录必然是存在的，所以必须开这个开关，否则第二次启动就崩。
        settings.qdrant_path.mkdir(parents=True, exist_ok=True)
        # 【这行在干什么】打开「接住岔子」的网，准备创建数据库客户端。
        # 【为什么这里需要 try】打开本地向量库是最容易出事的一步——目录被别的进程占着、
        #   权限不足、文件损坏，都会在这一步炸。这里必须接住并给出人能看懂的提示。
        try:
            # 【这行在干什么】创建 Qdrant 的本地客户端，数据就存在 settings.qdrant_path 这个文件夹里。
            # 【参数解释】path=str(...) 必须转成字符串：因为 qdrant 客户端只接受字符串路径，
            #   而 settings.qdrant_path 是个 Path 对象，直接传可能会报类型错误。
            # 【为什么这行是「本地模式」】只要给了 path 参数、没给服务器地址，
            #   Qdrant 就知道要用「嵌入式本地文件」方式工作（不需要 Docker、不需要起服务）。
            # 【注意事项（最容易踩）】本地模式对整个文件夹加了独占锁：
            #   一旦本进程打开，其它进程（比如另一个后端进程、或命令行建库脚本）
            #   再想打开就会失败。所以「重建知识库」要走接口在同一个进程里做，
            #   或者先停掉服务再跑脚本。
            self.client = QdrantClient(path=str(settings.qdrant_path))
        # 【这行在干什么】接住上面创建客户端时抛出的任何异常，并命名为 exc。
        # 【参数解释】as exc 意思是「把捕获到的异常对象叫做 exc」，后面用它取原始报错信息。
        except Exception as exc:
            # 【这行在干什么】把晦涩的原始报错，翻译成一句「说清了原因和怎么办」的提示再抛出。
            # 【为什么报错信息要写成这么长的一句】因为「打开本地向量库失败」最常见的原因
            #   就是「目录被另一个进程占用」，用户看到原始报错往往一头雾水。这里直接告诉他
            #   「本地模式一个目录只能被一个进程用，请确认没有别的后端/建库脚本在跑」，
            #   排查方向立刻就明确了。
            # 【f"..." 是什么】格式化字符串：双引号前加字母 f 后，里面的 {…} 会被替换成实际值。
            # 【注意事项】这里必须 raise 主动抛出，不能只打印一句就算了 ——
            #   否则后面会拿着一个不存在的 self.client 继续跑，报出更难懂的错误。
            raise VectorStoreError(
                f"打开本地向量库失败（{settings.qdrant_path}）：{exc}。"
                "本地模式同一目录只能被一个进程占用，请确认没有其他后端/建库脚本在运行。"
            ) from exc
            # 【这行在干什么】上面 raise 语句结尾的 from exc 表示「新异常由 exc 引起」。
            # 【为什么加 from】这样原始报错不会被丢掉（叫「异常链」），排查时既能读到
            #   我们写的这句人话，也能顺藤摸瓜看到最初是谁报的错。
        # 【这行在干什么】创建一把线程锁，存到对象上。
        # 【为什么需要这把锁（重点）】Qdrant 的本地客户端不是天生线程安全的；
        #   而 FastAPI 会同时处理多个请求（比如一个人在建库、另一个人正在提问），
        #   两个线程同时操作同一份文件句柄可能出乱子。锁的作用是排队：
        #   本文件中所有真正读写数据库的地方，都会用 with self._lock 把动作围起来。
        # 【专业词解释：threading.Lock()】最基础的「互斥锁」：
        #   同一时刻只允许一个线程持有（进入 with 时上锁、离开时自动解锁）。
        self._lock = threading.Lock()
        # 【这行在干什么】向 atexit 注册：进程退出时，帮忙调用 _close_quietly(self.client) 关闭连接。
        # 【为什么必须注册这个】见 _close_quietly 的说明：不主动关的话，Python 会在最后阶段
        #   自动去关，而那时环境已经很乱，会打印一大段吓人的报错。提前注册让「退场」变得干净。
        # 【参数解释】第二个参数 self.client 表示「到时候把客户端作为参数传给那个函数」。
        # 【注意事项】这是「一次性」注册：每个 VectorStore 对象注册一次，不会重复执行。
        atexit.register(_close_quietly, self.client)

    # ------------------------------------------------------------------ #
    # 集合管理
    # 【这段在干什么】下面几个方法负责「柜子」本身：叫什么名、存不存在、要不要重建。
    # 【为什么先看这段】因为任何读写之前都必须先有柜子，这是执行顺序上最靠前的一步。
    # ------------------------------------------------------------------ #
    # 【这行在干什么】@property 把下面这个 collection 方法包装成「属性」。
    # 【通俗解释】有了它，外部写 store.collection 就行，不必写 store.collection()。
    # 【为什么这么设计】集合名是「读一下就知道」的信息，用属性读法更自然、代码更短。
    # 【专业词解释：装饰器】写在函数上方、以 @ 开头的一行，用于给函数增强功能；
    #   这里 @property 增强的效果就是「让方法能像属性一样被读取」。
    @property
    def collection(self) -> str:
        # 【这行在干什么】把配置里的集合名返回出去。
        # 【参数解释】self.settings.qdrant_collection 来自 .env（QDRANT_COLLECTION）。
        # 【为什么不让各方法自己写名字】集中在这一个地方，将来改名只改配置即可，
        #   不会出现「某个方法写错名字导致查不到」的低级问题。
        return self.settings.qdrant_collection

    # 【这行在干什么】定义方法 collection_exists：判断那个集合（柜子）现在存不存在。
    # 【返回值】True 表示存在、False 表示不存在。
    # 【为什么这个判断到处都是】因为「首次运行」和「重跑」两种情况要区分对待：
    #   不存在就要建；存在就要检查维度对不对。判断结果决定了后面的分支。
    def collection_exists(self) -> bool:
        # 【这行在干什么】打开「接住岔子」的网，去问数据库这个集合在不在。
        # 【为什么这一步也可能出错】比如本地库文件损坏、目录读不了，
        #   这时候「查存在性」本身就会抛异常。
        try:
            # 【这行在干什么】调用客户端的 collection_exists 方法，把结果转成真假值返回。
            # 【为什么要外套 bool(...)】客户端返回的可能不是标准的 True/False，
            #   而是别的「真值/假值」表示。外套一层 bool() 保证返回的一定是干净的布尔值，
            #   调用方 if 起来不会有意外。
            return bool(self.client.collection_exists(self.collection))
        # 【这行在干什么】接住任何异常，并直接返回「不存在」。
        # 【为什么把「出错」当成「不存在」（重要的取舍）】查存在性出错时，两种选择：
        #   ① 抛异常让整个请求失败；② 当作不存在，让后续流程继续。
        #   这里选 ②，因为后续的 ensure_collection 会尝试「创建它」，
        #   真正的问题（比如目录坏了）会在那一步以更清楚的方式暴露出来。
        #   这就是「查探性操作尽量宽容，写入操作才严格报错」的思路。
        except Exception:
            return False

    # 【这行在干什么】定义方法 ensure_collection：保证集合存在、并且维度正确。
    # 【名字里的 ensure 是「确保」的意思】这个方法的设计意图是「不管现在什么状态，
    #   调用完就能放心地用」——该建的建、该重建的重建、该检查的检查。
    # 【参数解释】recreate=False：是否需要「先删掉旧的、再重新建」。
    #   默认 False（不动旧数据）；建库重建时传 True。
    # 【注意事项】recreate=True 是「破坏性操作」，会把库里已有的点全部删掉，
    #   所以只有在明确要重建知识库时才传 True。
    def ensure_collection(self, recreate: bool = False) -> None:
        """创建集合；``recreate=True`` 先删后建（重建知识库用）。"""
        # 【这行在干什么】加锁，进入「一次只允许一个线程操作数据库」的保护范围。
        # 【为什么建集合也要加锁】因为「删集合 → 建集合 → 检查维度」是一串连续动作，
        #   如果另一个线程在中途插进来（比如正好在删完之后来查数据），就会读到莫名其妙的中间状态。
        #   加锁保证这一整段是「一口气做完」的。
        # 【with 是什么意思】上下文管理器语法：进入代码块时自动上锁，离开时自动解锁，
        #   哪怕中途报错也一定会解锁，不会把数据库永久锁死。
        with self._lock:
            # 【这行在干什么】如果要求重建、并且旧的集合确实存在，就先把旧集合删掉。
            # 【为什么必须先删】因为「重建」的语义是「完全按当前配置来」。
            #   如果不删，旧数据（可能是旧模型、旧维度）会和新数据混在一起，库就废了。
            if recreate and self.collection_exists():
                # 【这行在干什么】删除整个集合（连同里面所有的点），相当于把抽屉整个扔掉。
                # 【潜在风险】这是不可恢复的操作，数据直接没了。所以它只在 recreate=True 时执行，
                #   而 recreate=True 只会由「重建知识库」这个明确动作触发。
                self.client.delete_collection(self.collection)
            # 【这行在干什么】如果（删完之后）集合仍然不存在，就创建它。
            # 【为什么这里要再查一次存在性】因为上面的删除只在 recreate=True 时发生；
            #   如果 recreate=False 且集合本来就存在，就应该走下面那条「只检查维度」的路，
            #   不要重复创建。这一次判断把两种情况分流开了。
            if not self.collection_exists():
                # 【这行在干什么】创建集合，同时声明它里面要存哪几种向量、各自什么规格。
                # 【参数逐个解释（本文件最核心的一个调用，值得细读）】
                #   collection_name —— 集合叫什么名字（来自 .env）；
                #   vectors_config  —— 「稠密向量」的规格登记表，是个字典，键是向量名：
                #       DENSE_VECTOR_NAME（"dense"）对应 models.VectorParams(...)，里面两个参数：
                #         · size=self.settings.embed_dim —— 每个向量有几个数字（本模型 512）。
                #           这个数字是硬性契约，写进去之后，以后写入/查询的向量必须严格等于它，
                #           多一个少一个数字都会报错。所以改模型必然要重建库。
                #         · distance=models.Distance.COSINE —— 「有多像」怎么量。
                #           COSINE 是「余弦相似度」：只看两个向量的方向是否一致，不看出身长度。
                #           为什么用它？因为文本向量更适合比「方向」；用点积的话长文本会因为
                #           数值整体偏大而占便宜，用欧氏距离则对整体缩放敏感。余弦是文本领域的常规选择。
                #       【通俗解释余弦相似度】把两个向量想成两支箭头，只看它们夹角的余弦值：
                #         方向完全一致=1（最像），互相垂直=0（不相关），方向相反=-1（最不像）。
                #   sparse_vectors_config —— 「稀疏向量」的规格登记表，同样是个字典：
                #       SPARSE_VECTOR_NAME（"bm25"）对应 models.SparseVectorParams()。
                #       注意这里没写 size：因为稀疏向量的「长度」取决于词表大小、会随数据变化，
                #       不需要（也不能）在建集合时固定，所以用默认配置即可。
                self.client.create_collection(
                    collection_name=self.collection,
                    vectors_config={
                        DENSE_VECTOR_NAME: models.VectorParams(
                            size=self.settings.embed_dim,
                            distance=models.Distance.COSINE,
                        )
                    },
                    sparse_vectors_config={SPARSE_VECTOR_NAME: models.SparseVectorParams()},
                )
                # 【这行在干什么】创建完就直接结束这个方法，不再往下走。
                # 【为什么这里要 return（关键）】因为集合是「刚刚新建」的，维度必然是按当前配置
                #   设的，不可能不一致，所以完全不需要再做下面的维度检查。
                #   少绕一圈、少一次数据库查询，纯粹是为了省事。
                return
            # 【这行在干什么】走到这里说明「集合原本就存在」（没被删、也不是刚建），
            #   于是做一次维度核对，确保库里存的维度和当前配置对得上。
            # 【为什么必须核对（重要）】如果换了向量模型（比如从 512 维换成 768 维）却没重建库，
            #   库里还是旧的 512 维。此时写入/查询会因为维度对不上而失败，而且 Qdrant 报的错
            #   往往很抽象。在这里主动检查并给出「请重建知识库」的明确提示，能省大量排查时间。
            self._verify_dimension()

    # 【这行在干什么】定义方法 _verify_dimension：核对「库里现有的向量维度」是否等于「配置要求的维度」。
    # 【为什么名字前面有下划线 _】这是 Python 的约定：表示「内部用的私人物品，外部请不要直接调用」。
    #   它只是个君子协定，Python 不会强制阻止，但看到下划线就该明白别乱用。
    # 【返回值为 -> None】表示只检查、不返回结果；发现问题的方式是「抛异常」。
    def _verify_dimension(self) -> None:
        """集合维度与当前配置不一致时给出明确提示，而不是让检索悄悄报错。"""
        # 【这行在干什么】打开「接住岔子」的网，准备去读集合的配置信息（含维度）。
        # 【为什么这里允许失败】如果连「读集合配置」都失败了（库文件损坏等），
        #   说明问题已经严重到不是「维度不匹配」这种小事，让后面真正的操作去报错更合适。
        #   所以这里选择宽容处理（下面 except 里直接 return）。
        try:
            # 【这行在干什么】从数据库取出这个集合的详细信息（一个描述对象）。
            # 【返回值里有什么】它的 config 里记录了集合的各种设置，其中包括每种向量的规格。
            info = self.client.get_collection(self.collection)
            # 【这行在干什么】从这层层嵌套的信息里，把「向量部分的配置」取出来。
            # 【为什么要点这么多层】这是 Qdrant 客户端的结构：info.config.params.vectors。
            #   可以理解成「总信息 → 配置 → 参数 → 向量规格」四层嵌套。
            params = info.config.params.vectors
            # 【这行在干什么】取出「dense 这一种向量」的规格对象，赋给变量 dense。
            # 【这行在读什么（三元表达式）】`A if 条件 else B` = 「条件成立用 A，否则用 B」。
            #   意思是：如果 params 是一个字典（新版客户端的行为），就用 params.get("dense")
            #   按键取值；如果不是字典（老版本客户端直接给对象），那就直接把它当作 dense 规格用。
            # 【为什么写这种兼容代码（重要背景）】不同版本的 qdrant_client 在「只有一种向量时」
            #   返回的结构不一样：有的给 {名字: 规格} 的字典，有的直接给规格本身。
            #   这里两种都兼容，避免「升级第三方库就崩」。
            #   这就是为什么本文件有些写法看起来不像新手会写。
            dense = params.get(DENSE_VECTOR_NAME) if isinstance(params, dict) else params
            # 【这行在干什么】从 dense 规格对象上取出 size（维度数字）。
            # 【为什么用 getattr(..., None) 而不是 dense.size】因为如果前面拿到的对象
            #   根本不是预期的规格对象，直接写 .size 会抛异常；getattr 在这种取不到的情况下
            #   会安静地返回第三个参数（这里给了 None），更稳。
            # 【专业词解释：getattr】「按名字取属性」的函数，等价于 obj.属性名，
            #   但它可以在属性不存在时给一个兜底值，因此更适合处理不确定的结构。
            actual = getattr(dense, "size", None)
        # 【这行在干什么】接住上面这一串「读配置」过程中可能出现的任何异常。
        except Exception:
            # 【这行在干什么】直接结束方法，什么都不做（连警告都不打）。
            # 【为什么这么宽容】理由同上：读不出来多半意味着库本身有更大的问题，
            #   而这个方法的职责只是「顺手核对维度」，不该由它来把请求拦下来。
            # 【注意事项】代价是：万一真的维度不一致、同时又读不出配置，这里会「悄悄放过」。
            #   但这种双重巧合概率极低，而且真正写入时 Qdrant 仍会报错兜住，属于可接受的取舍。
            return
        # 【这行在干什么】如果确实读到了维度（actual 不是 None/0），且它和配置不一致，就报错。
        # 【为什么要先判断 actual 非空】如果前面没读到维度（None 或 0），说明信息不全，
        #   这时不该凭空报错。`actual and ...` 这种写法就是「actual 有值才继续判断」的简写。
        # 【为什么用 != 而不是 ==】这里在找「不一致」这种坏情况，只有不一致才需要报错，
        #   一致（正常）就安静地什么都不做。
        if actual and int(actual) != self.settings.embed_dim:
            # 【这行在干什么】抛出一个说明详细的异常，把「现状、期望、怎么办」一次讲清。
            # 【为什么要把「怎么办」写进报错里】这种错误几乎都发生在「换了模型/改了配置
            #   但忘了重建库」。直接告诉用户「请重建知识库（POST /api/ingest）」，
            #   照着做就能解决，比一句「维度不匹配」有用得多。
            # 【注意事项】必须 raise 而不能只打印日志：带着不一致的维度继续写库，
            #   会把整个知识库污染成不可用状态，那比当场失败要严重得多。
            raise VectorStoreError(
                f"向量库现有维度为 {actual}，当前配置 EMBED_DIM={self.settings.embed_dim} 不一致。"
                "请重建知识库（POST /api/ingest）以适配新模型。"
            )

    # ------------------------------------------------------------------ #
    # 写入
    # 【这段在干什么】把一批文档「打包」成数据库认识的格式，然后分批写进去。
    # 【读代码顺序提示】到这里才真正往库里放数据。上面「集合管理」是前菜，这里是主菜。
    # ------------------------------------------------------------------ #
    # 【这行在干什么】定义方法 upsert_documents：把一批文档连同它们的两种向量写入数据库。
    # 【upsert 是什么意思（重要词）】= update + insert「更新或插入」：
    #   如果这个 ID 已经存在就覆盖它，不存在就新增。这正是我们想要的「重跑幂等」效果——
    #   重跑建库时不会产生重复记录，而是把同一位置的旧内容覆盖成新内容。
    # 【参数逐个解释】
    #   documents      —— 一批 Document 对象（文档原文 + 元信息），来自 documents.py；
    #   dense_vectors  —— 与 documents 一一对应的稠密向量（每篇一个 512 维数组）；
    #   sparse_vectors —— 与 documents 一一对应的稀疏向量，每项是 (下标列表, 权重列表) 的组合；
    #   batch_size=128 —— 每次往数据库送多少条。分批是为了控制单次请求的数据量，
    #     避免一次性送几万条把内存和网络压垮；128 是常见的稳妥值。
    # 【返回值】实际写入的条数（整数）。
    # 【注意事项（三个列表必须一一对应）】这三个参数是靠「位置」配对的（第 i 篇文档
    #   配第 i 个稠密向量、第 i 个稀疏向量）。如果上游给的数量或顺序不一致，
    #   就会出现「文档 A 配上了文档 B 的向量」这种严重错位，所以上游务必保证严格对齐。
    def upsert_documents(
        self,
        documents: list[Document],
        dense_vectors: list[list[float]],
        sparse_vectors: list[tuple[list[int], list[float]]],
        batch_size: int = 128,
    ) -> int:
        """批量写入。稀疏向量为空（BM25 未拟合）时只写稠密向量。"""
        # 【这行在干什么】如果文档列表是空的，直接返回 0（一条也没写）。
        # 【为什么这么写】空输入没必要走后面所有逻辑；同时保证函数一定返回整数，
        #   调用方不用额外判断。这叫「防御性编程」——把边界情况在入口处理掉。
        if not documents:
            # 【这行在干什么】返回 0，表示写入了零条。
            # 【为什么返回 0 而不是 None】保持返回值类型统一，调用方可以直接拿去做加法或比较。
            return 0

        # 【这行在干什么】准备一个空列表 points，用来装「待写入的点」。
        # 【类型标注解释】points: list[models.PointStruct] 意思是「这是一个列表，
        #   里面每个元素都是 Qdrant 的数据模型 PointStruct（一个点的完整定义）」。
        # 【为什么先攒起来再写，而不是边算边写】因为要支持「分批写入」：先全部打包好，
        #   再按每 128 条切一刀发送，逻辑更清楚，也便于统计总数。
        points: list[models.PointStruct] = []
        # 【这行在干什么】用 zip 把三个列表「按位置串起来」，一圈处理一篇文档。
        # 【这行的读法（元组解包，重点）】zip(documents, dense_vectors, sparse_vectors)
        #   会把三个列表的「第 0 项、第 1 项、第 2 项……」分别凑成一组，循环变量写成
        #   `doc, dense, (indices, values)` 时：
        #     · doc     —— 第 i 篇文档；
        #     · dense   —— 第 i 个稠密向量；
        #     · (indices, values) —— 把第 i 个稀疏向量「当场拆成两半」，
        #       indices 是「哪些词（词编号）」的列表，values 是「这些词各自的权重」的列表。
        #   这种「把成对/成组的数据一次拆到几个变量里」的写法就叫「元组解包」。
        # 【为什么要这么做】因为我们真正的算法只需要 indices 和 values 两个部分，
        #   直接在循环头上拆开，后面代码里就不用反复写 sparse[0]、sparse[1]，更清楚。
        # 【专业词解释：zip】「拉链」的意思：把多条列表像拉链一样并排咬合起来，
        #   循环次数取决于最短的那条列表。
        # 【注意事项】如果三个列表长度不一致，zip 会「悄悄按最短的来」，
        #   多出来的会被忽略而不报错。所以上游必须保证长度严格一致（见上面参数说明）。
        for doc, dense, (indices, values) in zip(documents, dense_vectors, sparse_vectors):
            # 【这行在干什么】组装「这条点要存哪些向量」，先把稠密向量放进去。
            # 【这个字典的结构】{向量名: 具体的向量}，例如 {"dense": [0.12, -0.05, ...]}。
            #   用之前定义的常量 DENSE_VECTOR_NAME 当键，保证和建集合时的名字完全一致。
            # 【为什么用 dict[str, Any] 标注】因为下面可能再往里塞一个稀疏向量，
            #   而两种向量的「值」类型完全不同（一个是普通数组、一个是 SparseVector 对象），
            #   所以用 Any（任意类型）兜住。
            vector: dict[str, Any] = {DENSE_VECTOR_NAME: dense}
            # 【这行在干什么】如果这条点的稀疏向量里有内容（indices 非空），就把它也放进去。
            # 【为什么要判断非空（重要，别删）】存在一种情况：BM25 还没拟合（例如空知识库首次建库），
            #   此时稀疏向量是空的。如果硬塞一个「空稀疏向量」进去，可能会被数据库拒绝、
            #   或者写入无意义的数据。判断一下就能优雅地退化成「这条点只有稠密向量」，
            #   语义检索照样能用。
            # 【注意事项】这就是文档里「稀疏向量为空时只写稠密向量」那句话的落地实现。
            if indices:
                # 【这行在干什么】把稀疏向量包装成 Qdrant 认识的对象，挂到 "bm25" 这个名字下。
                # 【参数逐个解释】
                #   indices —— 词的下标列表，例如 [12, 480, 901]（这些数字是词在词表里的编号）；
                #   values  —— 与下标一一对应的权重列表，例如 [0.83, 0.12, 2.40]。
                # 【为什么稀疏向量要写成这种「两串数字」】因为词表可能有几十万个词，
                #   但一篇文档只用到几百个。如果老老实实写成一个几十万长的数组，
                #   里面绝大多数都是 0，既浪费空间又慢。所以只记录「哪些位置有值、值是多少」，
                #   这就是「稀疏」的含义 —— 相比「稠密」的全量数组，它稀疏得多。
                # 【注意事项】indices 和 values 长度必须相同、必须一一对应。
                #   而且这些下标是 bm25.py 分配的词编号，必须和查询时用的是同一份词表
                #   （所以 bm25 的词表才会存盘、且必须整体重建，不能增量改）。
                vector[SPARSE_VECTOR_NAME] = models.SparseVector(indices=indices, values=values)
            # 【这行在干什么】把文档自带的 payload 复制一份，准备补充信息后再写入。
            # 【为什么用 dict(doc.payload) 复制而不是直接用 doc.payload】因为下面要往里面
            #   塞 doc_id 和 text 两个字段。如果直接改原对象，会「顺手改坏」上游还在用的
            #   那份数据（这种副作用很难查）。复制一份再改，原对象保持干净 —— 这叫「不产生副作用」。
            # 【专业词解释：payload】直译「有效载荷」，这里指「跟着向量一起存进库的附加资料」，
            #   检索命中后前端展示的原文就来自它。
            payload = dict(doc.payload)
            # 【这行在干什么】往 payload 里补上文档编号。
            # 【为什么必须补（重要）】检索命中后，程序需要知道「命中的是哪一篇」才能去查原文、
            #   做去重、做展示。而 payload 是命中后唯一能带回来的东西，所以 doc_id 必须放进去。
            payload["doc_id"] = doc.doc_id
            # 【这行在干什么】把文档正文也放进 payload。
            # 【为什么正文要存两份（一份用来算向量，一份存在 payload 里）】听起来有点重复，
            #   但用途不同：算向量那份是给机器比相似度用的；payload 里这份是给「人看」用的 ——
            #   用户提问命中后，前端要展示命中的原文，就必须能取到它。
            # 【注意事项】正文一般不会太长（建库前已被切块，见 documents.py），
            #   所以存进来占的空间是可接受的。
            payload["text"] = doc.text
            # 【这行在干什么】把一个完整的「点」打包好，放进待写入列表。
            # 【参数逐个解释】
            #   id      —— 点的编号，用 point_id_of(doc.doc_id) 换算成 UUID，
            #              保证「同一块每次得到同一个 ID」，于是写入变成覆盖（幂等）；
            #   vector  —— 上面组装好的向量字典（可能含 dense 和 bm25 两种）；
            #   payload —— 上面的附加资料（含原文、表名、主键、doc_id 等）。
            points.append(
                models.PointStruct(id=point_id_of(doc.doc_id), vector=vector, payload=payload)
            )

        # 【这行在干什么】加锁，进入「一次只允许一个线程操作数据库」的保护范围。
        # 【为什么写入必须加锁】①客户端不是天生线程安全的；②写入是「改数据」的操作，
        #   两批写入交叉进行容易产生混乱。加锁保证一批写入是连续完成的。
        with self._lock:
            # 【这行在干什么】按 batch_size 把点分成若干小批，一批一批地送。
            # 【这行的读法（range 的三个参数）】range(0, 总数, 步长) 会生成
            #   0, 步长, 2×步长, … 这样的数列，直到超过总数。所以 start 依次是
            #   0、128、256…… 每一圈代表「这一批的起始位置」。
            # 【为什么必须分批】一次性送几万条，会把请求体撑得巨大（内存飙升、
            #   网络超时、失败后要全部重来）。分批后单次数据量可控，也更稳。
            for start in range(0, len(points), batch_size):
                # 【这行在干什么】把「从 start 开始、连续 batch_size 条」这一小批真正写进数据库。
                # 【参数逐个解释】
                #   collection_name —— 写到哪个集合（柜子）；
                #   points=points[start : start + batch_size] —— 这一批点。
                #     注意这个「切片」写法：列表[起点:终点] 表示「取从起点到终点前一个位置的元素」，
                #     例如 [128:256] 取第 128~255 个。这是 Python 里取「一段连续元素」的标准方式。
                #     【小知识】切到头时（比如总数是 300、start=256）会自动只取到末尾，
                #     不会因为超出范围而报错，所以这里不用写边界判断。
                #   wait=True —— 「等这次写入真正落盘完成再返回」。
                #     设成 False 会立刻返回、后台慢慢写，速度更快，但「刚写完马上查」可能查不到。
                #     这里选 True 是为了「写完就能查到」，行为更可预期，代价是稍慢一点。
                #     【取舍说明】这是典型的「一致性 vs 速度」权衡；本项目选了稳妥的一方。
                self.client.upsert(
                    collection_name=self.collection,
                    points=points[start : start + batch_size],
                    wait=True,
                )
        # 【这行在干什么】返回这次一共写入了多少条。
        # 【为什么用 len(points) 而不是累加每批数量】因为 points 就是「全部要写的点」，
        #   它的长度天然就是总数，一行搞定，不用额外维护一个计数器变量。
        return len(points)

    # ------------------------------------------------------------------ #
    # 增量建库支持：读现有文档指纹 + 按 doc_id 批量删除
    # 【这段在干什么】给「增量更新」提供两件必备工具：
    #   ① scroll_existing() —— 把库里现有文档的「编号 + 内容指纹」取出来（只读、分批）；
    #   ② delete_documents() —— 把「已从数据源消失」的文档按 doc_id 批量删除。
    # 【为什么单独成段】它们不参与常规问答，只服务于建库；集中在一处便于理解增量方案。
    # ------------------------------------------------------------------ #
    def scroll_existing(self, batch_size: int = 1024) -> dict[str, str]:
        """只读：分批滚动取回全库文档，返回 ``{doc_id: 正文sha256}``。

        【为什么需要它】增量建库要拿「库里现有的文档」和「数据源新生成的文档」做差集，
        所以必须先把现有文档的标识与内容摘要取回来。返回「指纹」而不是「正文」，
        是为了省内存：9164 条正文可能有几十 MB，而指纹每条只有 64 个字符。

        【为什么必须分批（关键，别改成一次全取）】库里现在有近万条，将来可能几十万条。
        一次性 scroll 全部会把这些点的 payload 全拉进内存，可能把内存撑爆。
        这里按 batch_size（默认 1024）一批一批取，内存里始终只有一批的量，稳。

        【参数解释】batch_size=每批取多少条，默认 1024。

        【其他说明】
        - with_payload=True：正文和 doc_id 都藏在 payload 里，必须一起取回；
        - with_vectors=False：我们只要内容指纹，不需要 512 维向量，关掉能显著省传输与内存。
        """
        # 集合不存在（还没建过库）就直接返回空字典，表示「库里一条都没有」。
        # 这样增量流程会把所有新文档都算成 added，逻辑自洽，也不会对不存在的集合发查询而报错。
        if not self.collection_exists():
            return {}
        # 准备结果字典：键是 doc_id，值是正文的 sha256 指纹。
        existing: dict[str, str] = {}
        # offset 是「下一页的游标」：Qdrant 的 scroll 是分页的，第一次传 None 表示从头开始，
        # 每次返回「本页的点 + 下一页游标」，当游标变成 None 就说明翻到底了。这就是分批的关键。
        offset: Any = None
        # 加锁：本文件约定「所有真正读写数据库的地方都加锁」，滚动读大量数据同样遵守，
        # 避免与别的线程的写入交叉进行、读到半新半旧的状态。
        with self._lock:
            while True:
                points, offset = self.client.scroll(
                    collection_name=self.collection,
                    limit=batch_size,
                    offset=offset,
                    with_payload=True,
                    with_vectors=False,
                )
                # 逐条把 doc_id → 正文指纹 收集起来。
                for point in points:
                    # (p.payload or {}) 先兜住「payload 为空」的极端情况，再 .get 取值。
                    payload = point.payload or {}
                    doc_id = payload.get("doc_id")
                    # 没有 doc_id 的点（理论上不该有）没法参与差集对比，跳过。
                    if doc_id:
                        existing[doc_id] = text_hash(payload.get("text") or "")
                # 游标为空 = 已经翻到最后一页，结束循环。
                if offset is None:
                    break
        return existing

    def delete_documents(self, doc_ids: list[str], batch_size: int = 256) -> int:
        """按 doc_id 批量删除点，返回实际删除的条数。

        【为什么需要它】增量建库时，某些记录从数据源被删掉（或长文本改短导致多余分块消失），
        它们在库里对应的点必须清掉，否则会残留「僵尸文档」被检索到。

        【为什么按 point id 删】doc_id（表:主键:块序号）不能直接当 Qdrant 的 ID，
        必须先用 point_id_of 换算成 UUID，再用 PointIdsList 指定这一批 ID 删除。

        【参数解释】doc_ids=要删除的文档编号列表；batch_size=每批删多少（避免一次删太多）。

        【返回值】删掉的条数（就是传入 doc_ids 的个数，前提是这一步没抛异常）。
        """
        # 空输入直接返回 0，省掉后面所有动作。
        if not doc_ids:
            return 0
        # 把 doc_id 换算成 Qdrant 能认的 UUID，并分批。
        point_ids = [point_id_of(doc_id) for doc_id in doc_ids]
        deleted = 0
        with self._lock:
            for start in range(0, len(point_ids), batch_size):
                batch = point_ids[start : start + batch_size]
                # delete + PointIdsList 是 Qdrant 的「按 ID 批量删除」标准用法。
                # wait=True 表示「等删除真正生效再返回」，保证删完后立刻统计数字是准的。
                self.client.delete(
                    collection_name=self.collection,
                    points_selector=models.PointIdsList(points=batch),
                    wait=True,
                )
                deleted += len(batch)
        return deleted

    # ------------------------------------------------------------------ #
    # 检索
    # 【这段在干什么】两条检索通道：dense（语义）和 bm25（关键词）。
    #   它们各自返回一批「命中」，由 retriever.py 做融合。
    # 【为什么分成两个方法而不是一个】因为两种向量类型不同、名字不同、来源不同，
    #   分开写更清楚；而且调用方常常需要「只走一路」（比如开了 rerank 想先看看某一路的效果）。
    # ------------------------------------------------------------------ #
    # 【这行在干什么】@staticmethod 表示下面这个 _to_hit 方法是「静态方法」：
    #   它不依赖对象身上的任何数据（整个函数体里没用到 self），只是顺手放在这个类里。
    # 【为什么要这么标】标了之后调用它不用先创建对象，直接 VectorStore._to_hit(...) 即可；
    #   同时也是一种「声明」：告诉读代码的人「这个函数是纯工具，不碰对象状态」。
    @staticmethod
    def _to_hit(point: models.ScoredPoint, source: str) -> dict[str, Any]:
        # 【这行在干什么】定义 _to_hit：把 Qdrant 返回的一个「命中点」整理成我们自己统一的字典格式。
        # 【为什么需要这个转换（重要）】数据库返回的对象结构很繁琐（层层嵌套），
        #   而且上面带着数据库自己的字段名。直接把它透传到业务代码里，会导致「到处都在解析数据库结构」，
        #   将来换个数据库要改一大堆地方。这里统一「洗」成我们自己定义的扁平字典，
        #   业务层只认这个格式，耦合就解开了。
        # 【参数逐个解释】
        #   point  —— 数据库返回的「带分数的点」（ScoredPoint），既有内容也有相似度分数；
        #   source —— 这一条是从哪条通道来的："dense" 或 "bm25"。为什么要记它？
        #     因为两路结果的分数「不是一个口径」（稠密是余弦相似度，稀疏是 BM25 分），
        #     不能直接比较大小；必须记住来源，融合时才知道该怎么处理，
        #     前端也可以据此展示「这条是靠语义命中的还是靠关键词命中的」。
        # 【返回值】一个扁平字典，包含编号、表名、原文、字段、分数、来源等。
        # 【这行在干什么】取出这条点携带的 payload。
        # 【为什么写成 point.payload or {}（重要的防坑写法）】万一某条点的 payload 是空的
        #   （None），后面 payload.get(...) 就会直接报错中断整个检索。用 `A or B` 的写法
        #   （意思是「A 有值就用 A，否则用 B」）把它兜成一个空字典，后面怎么取都不会崩。
        payload = point.payload or {}
        # 【这行在干什么】开始组装我们要返回的字典。
        # 【为什么字典里的键名都是英文】这些键名会一路传到前端，前端按这些键名取值。
        #   它们是一份「接口约定」，前后端必须一致，所以用固定英文名、且不要随意改。
        return {
            # 【这行在干什么】把点的 ID 转成字符串放进结果。
            # 【为什么 str(...)】数据库返回的 ID 可能是 UUID 对象，转成字符串更便于传输和打印。
            "point_id": str(point.id),
            # 【这行在干什么】取出文档编号（就是我们在写入时放进去的那个 doc_id）。
            # 【参数解释】payload.get("doc_id", "") 的意思是「取 doc_id 这个键的值；
            #   要是没有这个键，就给个空字符串当默认值」。
            # 【为什么处处用 get 带默认值】避免「某个字段恰好缺失」时整个检索链崩掉。
            #   这属于防御性编程：宁可少显示一个字段，也不要让用户看到一个 500 报错。
            "doc_id": payload.get("doc_id", ""),
            # 【这行在干什么】取出这条数据来自哪张数据库表。
            "table": payload.get("table", ""),
            # 【这行在干什么】取出表的中文展示名；如果没有这个字段，就退而使用英文表名。
            # 【这行在读什么（嵌套默认值）】get 的第二个参数又是一个 get 的结果：
            #   意思是「优先用 label；label 不存在就用 table；table 也不存在就给空字符串」。
            #   这样前端总能拿到一个可显示的东西，不会出现空白标题。
            "label": payload.get("label", payload.get("table", "")),
            # 【这行在干什么】取出文档正文（用户看到的那段原文）。
            "text": payload.get("text", ""),
            # 【这行在干什么】取出原始字段的展示副本（前端可以把它渲染成一个小表格）。
            # 【为什么默认值给 {} 而不是 ""】因为它本身是个字典，类型要对上，
            #   否则前端拿到字符串再去当字典用会出错。
            "fields": payload.get("fields", {}),
            # 【这行在干什么】取出主键值（用来精确指向数据库里的某一行原始记录）。
            # 【为什么这里不写默认值】主键可能是数字 0，也可能是空。给默认值反而可能混淆，
            #   所以直接允许它是 None（不存在就取到 None），由前端自行处理。
            "primary_key": payload.get("primary_key"),
            # 【这行在干什么】取出「这是本条第几块」（从 0 开始数），默认 0。
            "chunk_index": payload.get("chunk_index", 0),
            # 【这行在干什么】取出「本条一共被切成几块」，默认 1。
            # 【为什么默认值是 1 而不是 0】因为「至少也算一块」，默认 1 更符合常识，
            #   前端计算「第 2/1 块」这种别扭显示就不会出现（真实数据里这两个字段都会存在）。
            "chunk_total": payload.get("chunk_total", 1),
            # 【这行在干什么】把相似度分数转成标准浮点数放进结果。
            # 【为什么 float(...)】数据库返回的分数可能是它自己封装的数值类型，
            #   转成 Python 标准 float 之后才能被 JSON 序列化、才能正常做算术和排序。
            "score": float(point.score),
            # 【这行在干什么】记下这一条来自哪条检索通道（"dense" 或 "bm25"）。
            # 【为什么重要】见上面 source 参数说明：两路分数口径不同，不能直接比大小；
            #   带上来源，融合逻辑和前端展示才有依据。
            "source": source,
        }

    # 【这行在干什么】定义方法 search_dense：用稠密向量（语义）去库里找最像的若干条。
    # 【参数逐个解释】
    #   vector —— 查询向量（用户问题被 embeddings.py 算成的那 512 个小数）；
    #   limit  —— 最多返回多少条（例如先召回 20 条，再精排挑 5 条）。
    # 【返回值】一批统一格式的命中字典（每条的 source 都是 "dense"）。
    def search_dense(self, vector: list[float], limit: int) -> list[dict[str, Any]]:
        # 【这行在干什么】做三个前置检查，任何一个不满足就直接返回空列表：
        #   ① not vector —— 查询向量是空的（比如模型没算出来），那没法查；
        #   ② limit <= 0 —— 要返回 0 条或负数条，没有意义（负数还会让数据库报错）；
        #   ③ 集合不存在 —— 柜子都没有，自然查不到东西。
        # 【为什么要在入口把这些挡住（重要）】这三种情况在「首次运行、空知识库」时很常见。
        #   如果直接发给数据库，轻则报错、重则刷出难懂的异常；在这里挡住，
        #   检索就优雅地返回「什么都没找到」，上层（比如 main.py）就能正常回一句「暂无数据」。
        # 【or 的短路特性】`A or B or C` 会从左往右判断，遇到第一个成立的就立刻停下、
        #   不再看后面（这叫「短路」），所以这里效率很高、逻辑也很直观。
        if not vector or limit <= 0 or not self.collection_exists():
            # 【这行在干什么】返回空列表，表示「这一路没有命中」。
            # 【为什么返回 [] 而不是 None】保持返回类型一致，调用方可以直接遍历结果。
            return []
        # 【这行在干什么】加锁，保护这次查询。
        # 【为什么查询也要加锁】因为本地模式下客户端共享同一个文件句柄，且它并非天生线程安全；
        #   多个请求同时查询可能互相干扰。加锁让查询排队进行（对本地小库来说，这点排队代价可以接受）。
        with self._lock:
            # 【这行在干什么】向数据库发出「按向量找最像的 N 条」的请求，拿到响应对象。
            # 【参数逐个解释】
            #   collection_name —— 在哪个集合里找；
            #   query=vector    —— 查询向量（问题的 512 个小数）；
            #   using=DENSE_VECTOR_NAME —— 「用哪种向量来比」：这里指定稠密那种（"dense"）。
            #     一个集合里有两种向量，不指定的话数据库不知道你指哪个。
            #   limit=limit     —— 最多要几条；
            #   with_payload=True —— 「顺便把附加资料（原文、表名等）也带回来」。
            #     如果设 False 只拿 ID 和分数，虽然省流量，但后面还得再查一次原文，反而更慢。
            # 【为什么是 query_points 而不是 search】这是 Qdrant 新版客户端的统一查询入口
            #   （老版本叫 search）。用新接口可以更好地兼容将来的版本。
            response = self.client.query_points(
                collection_name=self.collection,
                query=vector,
                using=DENSE_VECTOR_NAME,
                limit=limit,
                with_payload=True,
            )
        # 【这行在干什么】把数据库返回的一批原生命中点，逐个「洗」成我们统一的字典格式，返回出去。
        # 【这行的读法（列表推导式）】这是 Python 的「一行写循环」写法，等价于：
        #       result = []
        #       for p in response.points:
        #           result.append(self._to_hit(p, "dense"))
        #   用推导式只是更紧凑。
        # 【参数解释】response.points 是返回的命中列表；第二个参数 "dense" 表示
        #   「这些结果的来源是稠密检索通道」，会被写进每条结果的 source 字段。
        # 【注意事项】返回的顺序是数据库按相似度从高到低给的，融合排序时会用到这个顺序。
        return [self._to_hit(p, "dense") for p in response.points]

    # 【这行在干什么】定义方法 search_sparse：用稀疏向量（关键词/BM25）去库里找最匹配的若干条。
    # 【参数逐个解释】
    #   indices —— 用户问题分词后，每个词在词表里的编号列表（例如 [12, 480]）；
    #   values  —— 与编号一一对应的权重列表（例如 [1.5, 0.9]），由 bm25.py 算出；
    #   limit   —— 最多返回几条。
    # 【返回值】一批统一格式的命中字典（每条的 source 是 "bm25"）。
    # 【为什么参数是「两串数字」而不是一个向量对象】因为这是 bm25.py 的产出形式，
    #   直接在函数签名里说明「我要下标和权重这两样」，比让上游先包一个对象更省事。
    def search_sparse(self, indices: list[int], values: list[float], limit: int) -> list[dict[str, Any]]:
        # 【这行在干什么】三个前置检查，任一不满足就返回空列表：
        #   ① not indices —— 下标是空的（说明问题里没有一个词在词表里，或 BM25 还没拟合）；
        #   ② limit <= 0；③ 集合不存在。
        # 【为什么第一条特别重要】严格说 values 也应为空，但两串数字总是一起有或一起没有，
        #   检查其中一个就够了。这种「词表里查不到任何词」的情况在空库或生僻问题上很常见，
        #   提前挡住能避免「拿空向量去查」引发数据库报错。
        if not indices or limit <= 0 or not self.collection_exists():
            # 【这行在干什么】返回空列表，表示关键词这一路没有命中。
            return []
        # 【这行在干什么】加锁，保护这次查询（原因同 search_dense）。
        with self._lock:
            # 【这行在干什么】向数据库发出「按稀疏向量找最匹配的 N 条」的请求。
            # 【参数逐个解释】
            #   query=models.SparseVector(indices=indices, values=values) —— 把两串数字
            #     包成 Qdrant 认识的稀疏向量对象，作为「要查的东西」；
            #   using=SPARSE_VECTOR_NAME —— 「用哪种向量来比」：这里指定 "bm25" 这一种。
            #     数据库会拿问题的稀疏向量与库里每条点的稀疏向量做匹配，算出一个分数。
            #     【分数是怎么来的】稀疏向量的匹配本质上就是 BM25 打分，即
            #     「问题里每个词在候选文档里出现了没、出现几次、这个词有多稀有」的加权合计。
            #   limit / with_payload —— 同 search_dense。
            # 【为什么这条通道值得单独存在】稠密向量擅长「意思像」，但对公司名、项目编号、
            #   精确术语这类「一字不差才对」的内容并不敏感；BM25 恰好相反，专治精确命中。
            #   两者互补，所以项目用「混合检索」。
            response = self.client.query_points(
                collection_name=self.collection,
                query=models.SparseVector(indices=indices, values=values),
                using=SPARSE_VECTOR_NAME,
                limit=limit,
                with_payload=True,
            )
        # 【这行在干什么】把结果逐个洗成统一格式返回；来源标记为 "bm25"。
        # 【注意事项】这里返回的分数是 BM25 分（通常大于 1、上不封顶），
        #   而 dense 那路是余弦相似度（0~1 之间）。所以两边的分数**绝对不能直接比大小**，
        #   融合时必须用「看排名、不看分数」的办法（RRF），这一点在 retriever.py 里实现。
        return [self._to_hit(p, "bm25") for p in response.points]

    # ------------------------------------------------------------------ #
    # 统计
    # 【这段在干什么】给前端和管理接口提供「库里现在什么情况」的信息，
    #   以及「随便抽几条出来看看」的能力 —— 用于自检和展示。
    # ------------------------------------------------------------------ #
    # 【这行在干什么】定义方法 stats：汇总向量库的现状，返回一个字典。
    # 【谁在用】main.py 的 /api/health、/api/config 等接口，前端侧栏会显示「库里有几条」。
    # 【返回值】一个包含集合名、路径、是否存在、总点数、按表统计、维度、是否为空 的字典。
    # 【设计要点：这个函数几乎不会抛异常】即使集合不存在、统计失败，它也会返回一份
    #   「能看懂的报告」（而不是崩溃），因为「探活/展示」类接口最忌讳自己出错。
    def stats(self) -> dict[str, Any]:
        # 【这行在干什么】先把「最坏情况」的一份默认报告准备好，后面再逐步用真实数据覆盖它。
        # 【为什么先造底稿（重要设计）】这样无论后面哪一步失败，都能返回一份结构完整的报告，
        #   而不是缺字段的残缺字典 —— 前端就不用为「某些字段可能不存在」写一堆兼容代码。
        base: dict[str, Any] = {
            # 【这行在干什么】集合名。
            "collection": self.collection,
            # 【这行在干什么】数据目录路径，便于运维确认「到底在用哪个文件夹」。
            "path": str(self.settings.qdrant_path),
            # 【这行在干什么】集合是否存在，先假定不存在，后面查到了再改成 True。
            "exists": False,
            # 【这行在干什么】总共有多少条数据，先假定 0。
            "points": 0,
            # 【这行在干什么】按表分组的条数统计，先给个空字典。
            "by_table": {},
            # 【这行在干什么】当前配置的向量维度（512）。
            "vector_dim": self.settings.embed_dim,
            # 【这行在干什么】是否为空库，先假定是（空库是初始状态，更保守）。
            "empty": True,
        }
        # 【这行在干什么】如果集合根本不存在，直接返回上面那份「不存在」的底稿，到此为止。
        # 【为什么这么写】柜子都没有，后面的「数总数、分表统计、抽样本」全都无从谈起，
        #   提前返回既省事又安全（避免对不存在的集合发查询而报错）。
        if not self.collection_exists():
            # 【这行在干什么】返回底稿（此时 exists=False、points=0、empty=True）。
            return base

        # 【这行在干什么】走到这里说明集合是存在的，把底稿里的 exists 改成 True。
        # 【为什么直接改字典的某个键】base["exists"] = True 就是「把 exists 这个键的值改成 True」，
        #   相当于在底稿上打个勾。
        base["exists"] = True
        # 【这行在干什么】打开「接住岔子」的网，准备去读集合的总点数。
        # 【为什么这里也要 try】「读统计」失败不该导致整个探活接口崩掉，
        #   宁可少显示一个数字（保持底稿里的 0），也不要让前端拿不到任何东西。
        try:
            # 【这行在干什么】取出集合的详细信息。
            info = self.client.get_collection(self.collection)
            # 【这行在干什么】从信息里取出总点数（库里一共有多少条）。
            # 【这行的读法】`int(info.points_count or 0)` 是「取 points_count；如果它是 None
            #   就当作 0；再转成整数」。
            #   【为什么用 or 0】某些情况下数据库可能不返回这个数字（None），
            #   直接 int(None) 会报错，用 or 0 兜一下更稳。
            base["points"] = int(info.points_count or 0)
        # 【这行在干什么】接住上面取统计时的任何异常，什么都不做（pass）。
        # 【为什么允许吞掉】同上面理由：探活接口的目标是「尽力给出信息」，
        #   而不是「要么全对要么报错」。吞掉异常后，points 保持底稿里的 0。
        except Exception:
            pass

        # 【这行在干什么】准备一个空字典，用来装「每张表各有多少条」。
        # 【类型解释】dict[str, int] 表示「键是表名（字符串），值是条数（整数）」。
        by_table: dict[str, int] = {}
        # 【这行在干什么】遍历配置里关心的那几张业务表，逐张统计条数。
        # 【参数解释】self.settings.kb_tables 来自 .env（KB_TABLES），
        #   是「要建索引的表名清单」。为什么要按清单来？因为库里可能混着别的数据，
        #   只统计我们关心的几张表，报告才有意义。
        for table in self.settings.kb_tables:
            # 【这行在干什么】打开「接住岔子」的网，单独统计这一张表。
            # 【为什么每张表单独 try】这样某一张表统计失败只影响它自己（记 0），
            #   其余表照常统计，整体报告仍然可用。
            try:
                # 【这行在干什么】按条件数一数：库里「table 字段等于这张表名」的点有几条。
                # 【参数逐个解释】
                #   count_filter=models.Filter(must=[...]) —— 过滤条件，「must」表示必须满足；
                #   models.FieldCondition(key="table", match=models.MatchValue(value=table)) ——
                #     「payload 里 table 这个字段的值，必须等于 table 这张表名」。
                #     （match 是「精确相等」的意思。）
                #   exact=True —— 「要精确的数字」。为什么特意开它？因为 Qdrant 为了快，
                #     默认有可能给出「近似计数」；开 exact 强制精确统计。
                #     代价是稍慢，但统计接口对准确性要求高，这点代价值得。
                counted = self.client.count(
                    collection_name=self.collection,
                    count_filter=models.Filter(
                        must=[models.FieldCondition(key="table", match=models.MatchValue(value=table))]
                    ),
                    exact=True,
                )
                # 【这行在干什么】把数出来的条数记进字典（转成整数）。
                by_table[table] = int(counted.count)
            # 【这行在干什么】接住这张表统计失败时的异常。
            except Exception:
                # 【这行在干什么】把这张表记为 0 条。
                # 【为什么记 0 而不是不写】让报告里这张表始终出现（值为 0），
                #   前端展示「招标公告：0 条」比「这项突然消失」更好理解。
                by_table[table] = 0
        # 【这行在干什么】把分表统计结果放进总报告。
        base["by_table"] = by_table
        # 【这行在干什么】根据总点数判断是不是空库：点数是 0 就是空库。
        # 【为什么要专门给个 empty 字段】因为上层（比如回答生成环节）需要据此决定
        #   「要不要告诉用户暂无数据」，直接读这个布尔值比让它自己去比对 0 更清楚。
        base["empty"] = base["points"] == 0
        # 【这行在干什么】返回整理好的完整报告。
        return base

    # 【这行在干什么】定义方法 sample：随机/顺序取少量数据出来看看。
    # 【参数解释】limit=5 表示默认取 5 条。
    # 【谁在用】前端侧栏或自检接口，用来证明「库里真的有东西、内容长这样」。
    # 【和 stats 的区别】stats 给的是「数字」（有几条），sample 给的是「实物」（具体内容）。
    def sample(self, limit: int = 5) -> list[dict[str, Any]]:
        """取少量样本，供前端自检「库里有东西」。"""
        # 【这行在干什么】集合不存在就直接返回空列表。
        # 【为什么需要】对不存在的集合发「取数据」请求会报错，提前挡住最省事。
        if not self.collection_exists():
            # 【这行在干什么】返回空列表，表示取不到样本。
            return []
        # 【这行在干什么】打开「接住岔子」的网，准备从库里取一批点出来。
        # 【为什么取样本也要兜异常】这是「展示/自检」用途，失败了也不该让接口报 500；
        #   返回空列表让前端显示「暂无样本」即可。
        try:
            # 【这行在干什么】用 scroll（滚动浏览）方式取点：不按相似度排序，只按存储顺序拿一批。
            # 【参数逐个解释】
            #   collection_name / limit —— 从哪个集合取几条；
            #   with_payload=True  —— 把附加资料（原文、表名等）一起带回来，我们正是要看它；
            #   with_vectors=False —— **不要向量**。为什么？因为 512 个小数乘上几百条体积很大，
            #     而我们只是想「看看内容」，不需要数值。关掉能显著减少传输和内存。
            # 【返回值为什么是两个值】scroll 返回 (本页的点列表, 下一页的游标)。
            #   这里不需要翻页，所以用 `points, _` 把第二个值（游标）直接丢弃
            #   （下划线 _ 是 Python 惯例，表示「这个值我不用，占个位」）。
            points, _ = self.client.scroll(
                collection_name=self.collection,
                limit=limit,
                with_payload=True,
                with_vectors=False,
            )
        # 【这行在干什么】接住取值过程中的任何异常，返回空列表。
        except Exception:
            return []
        # 【这行在干什么】把取回来的点「精简」成前端真正需要的几个字段，返回。
        # 【读法：列表推导式】一行写循环，等价于「新建列表 → 逐个处理 → 追加」。
        # 【每一行的含义】
        #   doc_id / table / label / primary_key —— 都是用来溯源「这条来自哪里」的；
        #   text —— 原文，注意后面跟了 [:300]。
        #     这是「切片」：取这段文字的前 300 个字符（从开头到第 300 个位置之前）。
        #     为什么要截断？因为样本只是用来「看一眼」，一篇几千字的公告全带回来
        #     会让响应变得很大、前端显示也很长。取开头 300 字足以证明「里面是什么内容」。
        #     【注意事项】切片切开的是「字符数」，不是显示宽度；中文一个字算一个字符。
        # 【为什么每个字段都写 (p.payload or {}).get(...)】payload 理论上不会为空，
        #   但万一为空，`.payload.get(...)` 会抛异常；用 `(p.payload or {})`
        #   先兜成空字典，再 .get 就不会崩。这种写法在本文件里反复出现，是刻意的防守。
        return [
            {
                "doc_id": (p.payload or {}).get("doc_id", ""),
                "table": (p.payload or {}).get("table", ""),
                "label": (p.payload or {}).get("label", ""),
                "primary_key": (p.payload or {}).get("primary_key"),
                "text": (p.payload or {}).get("text", "")[:300],
            }
            for p in points
        ]


# 【这行在干什么】声明一个模块级的全局变量 _store，用来保存「唯一的那个 VectorStore 对象」。
# 【为什么初始值是 None】表示「还没创建过」，等第一次调用 get_store 时才真正创建。
# 【为什么必须全局只有一个（比 embeddings.py 里更硬的要求）】因为本地模式对数据目录
#   加了独占锁：同一个目录只能被一个进程打开一次。如果程序里创建了两个 VectorStore，
#   第二个就会因为「目录已被占用」而直接失败。所以「单例」在这里不只是省内存的问题，
#   而是「不做成单例就根本跑不起来」。
# 【为什么类型标注是 VectorStore | None】竖线 | 表示「或者」，
#   即「要么是一个 VectorStore，要么还是 None（尚未创建）」。
_store: VectorStore | None = None

# 【这行在干什么】创建一把独立的锁，专门保护「创建这个单例」的动作。
# 【为什么要独立的锁、不复用对象内部那把】因为两者保护的是不同的事：
#   · 这把保护「谁来创建/持有唯一的 VectorStore」；
#   · 对象内部那把保护「对数据库的每一次读写」。
#   混用一把锁在极端情况下会造成「自己等自己」的死锁。分开更安全、职责也更清楚。
_store_lock = threading.Lock()


# 【这行在干什么】定义函数 get_store：给外界一个「拿向量库对象」的统一入口。
# 【为什么要有它】它保证全局只有一个 VectorStore（也就只有一个数据库客户端），
#   既满足「本地模式只能开一个」的硬约束，也避免重复打开浪费资源。
# 【参数解释】settings=None 表示「调用方可以不传配置」。不传就用 get_settings() 从 .env 读。
#   这个设计是为了方便测试：测试时塞一份假配置（比如指向临时目录），就不碰真实数据库了。
# 【返回值】一个 VectorStore 对象（已建好连接）。
def get_store(settings: Settings | None = None) -> VectorStore:
    """进程内单例（本地模式一个目录只能开一个客户端）。"""
    # 【这行在干什么】声明「下面要修改的是模块级的全局变量 _store」。
    # 【为什么必须写 global（最常见的坑）】在函数里给变量赋值时，Python 默认会创建一个
    #   「局部的」新变量，函数一结束就丢了。写上 global 才是告诉 Python
    #   「我改的是外面那个真正的全局变量」，这样创建好的对象才能被保存下来、
    #   下次调用才能复用。少了这行，单例彻底失效 —— 而在这里单例失效的后果更严重：
    #   第二个 VectorStore 会因为目录被锁而直接报错。
    global _store
    # 【这行在干什么】第一次检查：全局变量是不是已经创建好了？
    # 【为什么先检查一次（性能考虑）】绝大多数调用都发生在「已经创建过」之后。
    #   先在锁外面快速看一眼，有就直接返回，完全不必抢锁。这叫「双重检查锁定」，
    #   是本文件里第二次出现这个模式（第一次在 embeddings.py 的 get_embedder，
    #   以及本文件对象内部的 model 属性）。
    if _store is None:
        # 【这行在干什么】加锁，进入「创建单例」的独占区域。
        # 【with 的含义】进入代码块时上锁、离开时自动解锁（即使中途报错也一定解锁），
        #   不会把锁永久卡死。
        with _store_lock:
            # 【这行在干什么】拿到锁后再检查一次：是不是已经被别的线程创建好了？
            # 【为什么必须再查一次（精髓）】设想两个请求线程同时走到外层 if、都发现是 None，
            #   于是都来抢锁。先抢到的创建完毕；后抢到的如果没有这第二次检查，
            #   就会再创建一个 VectorStore —— 而第二个客户端会因为「目录已被第一个占用」
            #   直接报错，把一次本来正常的请求搞崩。第二次检查让后到的线程一眼看到
            #   「已经有人建好了」，于是直接用现成的，避免了这个问题。
            if _store is None:
                # 【这行在干什么】创建唯一的 VectorStore 对象并存进全局变量。
                # 【参数解释】settings or get_settings() 的意思是：
                #   调用方传了配置就用它；没传（None 在 Python 里算「假」）就用 get_settings()
                #   从 .env 读一份。这是常见的「可以不传，不传我给默认值」写法。
                # 【注意事项】get_settings() 内部有缓存，反复调用不会重复读磁盘，可以放心用。
                _store = VectorStore(settings or get_settings())
    # 【这行在干什么】把那个唯一的 VectorStore 交给调用方。
    # 【为什么写在所有 if 外面】因为不论「早就建好」「刚被别人建好」还是「这次刚建好」，
    #   最终都要返回它，写在最外层只需一句，逻辑最干净。
    return _store